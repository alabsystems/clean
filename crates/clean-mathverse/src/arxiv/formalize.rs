    #[test]
    fn test_dependency_ordering() {
        let items = vec![
            OrderableItem {
                kind: "theorem".to_string(),
                label: "Theorem 1".to_string(),
                ref_label: "thm:1".to_string(),
                latex: "...".to_string(),
                proof_latex: String::new(),
                dependencies: vec!["def:A".to_string()],
            },
            OrderableItem {
                kind: "definition".to_string(),
                label: "Definition B".to_string(),
                ref_label: "def:B".to_string(),
                latex: "...".to_string(),
                proof_latex: String::new(),
                dependencies: vec!["def:A".to_string()],
            },
            OrderableItem {
                kind: "definition".to_string(),
                label: "Definition A".to_string(),
                ref_label: "def:A".to_string(),
                latex: "...".to_string(),
                proof_latex: String::new(),
                dependencies: vec![],
            },
        ];

        let order = order_by_dependencies(&items);
        // Definition A should come before Definition B (dependency order)
        let a_pos = order.iter().position(|&i| i == 2).unwrap();
        let b_pos = order.iter().position(|&i| i == 1).unwrap();
        let thm_pos = order.iter().position(|&i| i == 0).unwrap();
        assert!(a_pos < b_pos, "Definition A before Definition B");
        assert!(b_pos < thm_pos, "Definitions before theorems");
    }
