/// The emitted preamble.
///
/// `maxRecDepth 262144` is measured, not guessed. At Lean's default the export
/// reported 5 `maximum recursion depth` failures; 262144 (4x) clears 2 of them
/// and their 3 cascades, 15 errors -> 10. 524288 measures IDENTICALLY, so the
/// survivors are not depth-bound and more is pure cost. 2,000,000 is worse than
/// useless: it turns the clean diagnostic into a SIGABRT.
///
/// Note this `set_option` BEATS a `-D maxRecDepth=N` on the command line, so
/// tuning the limit means editing here, not the invocation.
pub fn header(roots: &[String]) -> String {
    format!(
        "/-\n\
         CleanVerifyExport.lean — MACHINE-GENERATED foreign-kernel cross-check.\n\
         Generated by `lean_export` from the LIVE\n\
         clean-verify Specification environment (elaborated kernel terms, not\n\
         hand-written mirrors). Lean 4's kernel independently re-checks the\n\
         dependency closure of: {roots:?}.\n\
         Every value-less constant is an explicit `axiom` below, so\n\
         `#print axioms` reports the census honestly.\n\
         DO NOT EDIT BY HAND.\n\
         -/\n\
         set_option autoImplicit false\n\
         set_option maxHeartbeats 900000\n\
         set_option maxRecDepth 262144\n\
         set_option linter.unusedVariables false\n\n"
    )
}

/// THE HEARTBEAT CEILING, RE-BRACKETED 2026-10-01: 900,000 = 4x THE COSTLIEST
/// ELABORATOR PHASE, rounded up to the next 100,000.
///
/// WHAT THE OPTION LIMITS (measured on the pinned Lean): `maxHeartbeats` bounds
/// a declaration's ELABORATOR phase, the `Meta`-level check that its value has
/// its type. It does NOT bound the kernel's re-check. A probe with an elaborator
/// phase of about 811,000 fails at 780,000 and passes at 850,000. A kernel-only
/// copy of it costs 1,246,147 and passes under a 300,000 ceiling. So the
/// canary's subject is the elaborator phase, and a divergent KERNEL check is
/// caught only by the gate's wall clock, never by this number.
///
/// The measurement elaborated every declaration of the export (11,581 of them)
/// inside the W1 instrument at `maxHeartbeats 0` with `Elab.async false`, which
/// counts both phases. The costliest two were then re-checked kernel-only, and
/// the elaborator phase is the total minus that. The unit is the option's unit,
/// thousands of heartbeats.
///
///   declaration                        total   kernel  elaborator
///   `ir_f64_w_fin_max_alignment`     496,349  293,769     202,580  (the costliest)
///   `ir_nat_bitlen_wide_w`           489,126  288,070     201,056
///   every other declaration          <= 64,356 in total, so less in either phase
///   `ir_lzd_deref_activation`         14,566      177      14,389  (passes at
///                                                           15,000, fails at 14,000)
///
/// 4 x 202,580 = 810,320, which rounds up to 900,000. The two costliest are
/// big-literal arithmetic witnesses whose cost their literals fix, not model
/// growth. Four leaves room for a heavier witness of the same family and for
/// Lean-version drift.
///
/// Both edges were shown in the gate's own configuration, with the export
/// header and plain `lean`, no harness. A probe of that family with an
/// elaborator phase of 877,775 passes at 900,000. One at 912,180 is refused with
/// a deterministic timeout. `gate::leancross` is GREEN on the real export at
/// 900,000. The record is `reports/crystal-lane/2026-09-30-link4-m0/rebracket/`.
///
/// By the same measure 32M was 158x the costliest elaborator phase. It was not
/// the 2,200x that dividing by the lzd chain's 14,566 suggests, and not 64x the
/// costliest TOTAL, a number that counts kernel work the option never limits.
///
/// Re-bracket from a fresh sweep (`rebracket_gen.py measure`, then `kernel` on
/// the top declarations) whenever a declaration's elaborator phase passes a
/// quarter of the ceiling. Never raise the number until a red run goes green.
///
/// HISTORY (2026-09-15, superseded above): THE HEARTBEAT CEILING IS A
/// MEASUREMENT, NOT A ROUND NUMBER.
///
/// It was 4,000,000 and `gate::leancross` was RED under it with two
/// `(deterministic) timeout at whnf` diagnostics plus four cascades. Both are
/// EXPENSIVE, not pathological, and that was settled by running the whole
/// 34,123-line export at `maxHeartbeats 0`: **zero errors, zero `sorryAx`**.
///
/// Each was then bracketed at 1M granularity by an adjacent PASS and FAIL,
/// which is why the ceiling is not simply "bigger":
///
///   `ir_lzd_dstep40`            passes at 12M, fails at 11M
///   `ir_lzd_deref_activation`   passes at 14M, fails at 13M
///
/// The cost is real work rather than a loop: `ir_lzd_dstep40` is an `Eq.refl`
/// whose conversion check RUNS the reflected machine for twelve steps over
/// `ir_lzd_module` (fuel `ir_d12` — every other member of that family is fuel
/// 1-7 and fits inside 4M), and `ir_lzd_deref_activation` carries that through
/// forty deref steps of `Eq.subst` re-framing.
///
/// 14M is the smallest round value at which the file passes, and it is the
/// wrong choice: it leaves ~7% over a number that moves whenever the lzd model
/// gains a segment. 32M is 2.3x the worst case, so a term that grows several
/// more segments still lands while a genuinely divergent one is still refused —
/// the ceiling stays a canary rather than being removed. It costs nothing above
/// the requirement: whole-file wall is 1368 s at 32M, 1373 s at 16M and 1431 s
/// at no limit, the same run within noise.
///
/// Raise this only from a fresh bracketing. A ceiling chosen to clear just one
/// of the two declarations would have left the other red: anything in 12M..13M
/// clears `dstep40` and still fails `deref_activation`, and anything in
/// 4M..11M clears neither.
pub fn footer(roots: &[String], renames: &HashMap<String, String>) -> String {
    let mut s = String::from("\n-- ==== flagship axiom audits ====\n");
    for r in roots {
        let mapped = renames.get(r).cloned().unwrap_or_else(|| r.clone());
        s.push_str(&format!(
            "#print axioms {NAMESPACE}.{}\n",
            escape_name(&mapped)
        ));
    }
    s
}

pub fn emit_item(
    env: &Environment,
    item: &Item,
    renames: &HashMap<String, String>,
    structs: &HashSet<String>,
) -> Result<String, String> {
    match item.kind {
        ItemKind::Inductive => {
            if structs.contains(&item.name.to_string()) {
                emit_structure(env, &item.name, renames, structs)
            } else {
                emit_inductive(env, &item.name, renames, structs)
            }
        }
        ItemKind::QuotShim => emit_quot_shim(env, item, renames, structs),
        ItemKind::NatCarrier => emit_nat_carrier(env, renames, structs),
        ItemKind::ComparisonBridge => {
            crate::comparison_bridge::emit_comparison(env, item, renames, structs)
        }
        ItemKind::ComparisonAgreement => {
            crate::comparison_bridge::emit_agreement(env, item, renames, structs)
        }
        ItemKind::NatShim => Ok(format!(
            "-- {} is emitted in the Nat carrier block above, as a reducible\n\
             -- alias of Lean's own `{}` (and, under the name NatSpec, verbatim\n\
             -- from Clean's stored body with its correspondence proved).\n\n",
            item.name, item.name
        )),
        _ => emit_constant(env, item, renames, structs),
    }
}

fn emit_inductive(
    env: &Environment,
    name: &Name,
    renames: &HashMap<String, String>,
    structs: &HashSet<String>,
) -> Result<String, String> {
    let iv = env
        .get_inductive(name)
        .ok_or_else(|| "inductive vanished from environment".to_string())?;
    if iv.all_names.len() > 1 {
        return Err(format!(
            "mutual inductive block ({:?}) not supported by exporter",
            iv.all_names
        ));
    }
    if iv.is_nested {
        return Err("nested inductive not supported by exporter".to_string());
    }
    let mut p = Printer::new(renames, structs);
    let mut ctx: Vec<String> = Vec::new();
    let (binders, rest) = p.telescope(&iv.type_, iv.num_params as usize, &mut ctx, "p_")?;
    let result_ty = p.expr(rest, &mut ctx)?;

    let ind_str = name.to_string();
    // The DECLARED name honours `renames`, exactly as `emit_constant` does for
    // its own. It did not until 2026-08-29, and nothing noticed because no
    // inductive had ever been renamed: the constructor TYPES print through the
    // `Printer`, which does apply renames, so a renamed inductive emitted a
    // header saying `Nat` over constructors saying `NatSpec` and Lean rejected
    // the block with `unknown identifier`. `ind_str` stays the Clean name --
    // environment lookups and the constructor-prefix strip below both key on it.
    let lean_ind = renames
        .get(&ind_str)
        .cloned()
        .unwrap_or_else(|| ind_str.clone());
    let mut out = format!(
        "inductive {NAMESPACE}.{}{}{} : {}",
        escape_name(&lean_ind),
        level_params_suffix(&iv.level_params),
        binders,
        result_ty
    );
    if !iv.constructor_names.is_empty() {
        out.push_str(" where");
    }

    for cn in &iv.constructor_names {
        let cv = env
            .get_constructor(cn)
            .ok_or_else(|| format!("constructor {cn} missing"))?;
        let cn_str = cn.to_string();
        let short = cn_str
            .strip_prefix(&format!("{ind_str}."))
            .ok_or_else(|| format!("constructor {cn_str} not namespaced under {ind_str}"))?;
        if short.contains('.') {
            return Err(format!("constructor {cn_str} has nested name component"));
        }
        // Strip the inductive parameters from the stored ctor type, binding
        // them to the SAME names as the header binders.
        let mut cp = Printer::new(renames, structs);
        cp.next_var = p.next_var;
        let mut cctx: Vec<String> = Vec::new();
        let (_pb, crest) = cp.telescope(&cv.type_, cv.num_params as usize, &mut cctx, "p_")?;
        let cty = cp.expr(crest, &mut cctx)?;
        out.push_str(&format!("\n  | {} : {}", escape_name(short), cty));
    }
    out.push('\n');
    Ok(out)
}

/// The seven names the carrier block defines, in the order it defines them.
const NAT_BRIDGED_NAMES: [&str; 7] = [
    "Nat", "Nat.zero", "Nat.succ", "Nat.rec", "Nat.add", "Nat.sub", "Nat.pred",
];

/// The bridge and the working carrier: fixed text, because these declarations
/// have no Clean counterpart to print from -- they are the CORRESPONDENCE, not
/// part of the exported spec. Everything above them in the block comes from the
/// live environment.
///
/// Every theorem here is proved, with no `sorry` and no axiom, and the proofs
/// have content: an off-by-one `toCore` is rejected by Lean, and a
/// `NatSpec.add` that recurses on the wrong argument makes `add_agrees`
/// unprovable. That is the difference between this and a bare alias, which
/// would let a garbage declared body ride along invisibly in both kernels.
const NAT_BRIDGE_AND_ALIASES: &str = r#"
-- ==== the bridge, PROVED rather than assumed ====
noncomputable def CleanVerify.toCore : CleanVerify.NatSpec -> _root_.Nat :=
  fun n => @CleanVerify.NatSpec.rec (fun _ => _root_.Nat) _root_.Nat.zero
    (fun _ ih => _root_.Nat.succ ih) n

noncomputable def CleanVerify.ofCore : _root_.Nat -> CleanVerify.NatSpec :=
  fun n => @_root_.Nat.rec (fun _ => CleanVerify.NatSpec) CleanVerify.NatSpec.zero
    (fun _ ih => CleanVerify.NatSpec.succ ih) n

theorem CleanVerify.toCore_zero :
    _root_.Eq (CleanVerify.toCore CleanVerify.NatSpec.zero) _root_.Nat.zero := rfl

theorem CleanVerify.toCore_succ : forall (n : CleanVerify.NatSpec),
    _root_.Eq (CleanVerify.toCore (CleanVerify.NatSpec.succ n))
      (_root_.Nat.succ (CleanVerify.toCore n)) := fun _ => rfl

theorem CleanVerify.ofCore_toCore : forall (n : CleanVerify.NatSpec),
    _root_.Eq (CleanVerify.ofCore (CleanVerify.toCore n)) n :=
  fun n => @CleanVerify.NatSpec.rec
    (fun k => _root_.Eq (CleanVerify.ofCore (CleanVerify.toCore k)) k)
    rfl
    (fun k ih => congrArg CleanVerify.NatSpec.succ ih) n

theorem CleanVerify.toCore_ofCore : forall (n : _root_.Nat),
    _root_.Eq (CleanVerify.toCore (CleanVerify.ofCore n)) n :=
  fun n => @_root_.Nat.rec
    (fun k => _root_.Eq (CleanVerify.toCore (CleanVerify.ofCore k)) k)
    rfl
    (fun k ih => congrArg _root_.Nat.succ ih) n

theorem CleanVerify.add_agrees : forall (a b : CleanVerify.NatSpec),
    _root_.Eq (CleanVerify.toCore (CleanVerify.NatSpec.add a b))
      (_root_.Nat.add (CleanVerify.toCore a) (CleanVerify.toCore b)) :=
  fun a b => @CleanVerify.NatSpec.rec
    (fun k => _root_.Eq (CleanVerify.toCore (CleanVerify.NatSpec.add a k))
      (_root_.Nat.add (CleanVerify.toCore a) (CleanVerify.toCore k)))
    rfl
    (fun k ih => congrArg _root_.Nat.succ ih) b

theorem CleanVerify.pred_agrees : forall (a : CleanVerify.NatSpec),
    _root_.Eq (CleanVerify.toCore (CleanVerify.NatSpec.pred a))
      (_root_.Nat.pred (CleanVerify.toCore a)) :=
  fun a => @CleanVerify.NatSpec.rec
    (fun k => _root_.Eq (CleanVerify.toCore (CleanVerify.NatSpec.pred k))
      (_root_.Nat.pred (CleanVerify.toCore k)))
    rfl
    (fun k _ => rfl) a

theorem CleanVerify.sub_agrees : forall (a b : CleanVerify.NatSpec),
    _root_.Eq (CleanVerify.toCore (CleanVerify.NatSpec.sub a b))
      (_root_.Nat.sub (CleanVerify.toCore a) (CleanVerify.toCore b)) :=
  fun a b => @CleanVerify.NatSpec.rec
    (fun k => _root_.Eq (CleanVerify.toCore (CleanVerify.NatSpec.sub a k))
      (_root_.Nat.sub (CleanVerify.toCore a) (CleanVerify.toCore k)))
    rfl
    (fun k ih => Eq.trans (CleanVerify.pred_agrees (CleanVerify.NatSpec.sub a k))
      (congrArg _root_.Nat.pred ih)) b

-- The RECURSOR agrees too, so `toCore` maps the whole vocabulary and not just
-- zero/succ/add/sub. Universe-polymorphic, matching the recursor it mirrors.
theorem CleanVerify.rec_agrees.{u} (motive : _root_.Nat -> Sort u)
    (z : motive _root_.Nat.zero)
    (s : (k : _root_.Nat) -> motive k -> motive (_root_.Nat.succ k)) :
    forall (n : CleanVerify.NatSpec),
      _root_.Eq
        (@CleanVerify.NatSpec.rec (fun k => motive (CleanVerify.toCore k)) z
          (fun k ih => s (CleanVerify.toCore k) ih) n)
        (@_root_.Nat.rec motive z s (CleanVerify.toCore n)) :=
  fun n => @CleanVerify.NatSpec.rec
    (fun m => _root_.Eq
      (@CleanVerify.NatSpec.rec (fun k => motive (CleanVerify.toCore k)) z
        (fun k ih => s (CleanVerify.toCore k) ih) m)
      (@_root_.Nat.rec motive z s (CleanVerify.toCore m)))
    rfl
    (fun k ih => congrArg (s (CleanVerify.toCore k)) ih) n

-- ==== the working carrier: what every OTHER exported declaration sees ====
-- `@[reducible]` is REQUIRED, measured: with a plain `noncomputable def` the
-- ELABORATOR fails `OfNat` synthesis on every numeral. The kernel is
-- indifferent either way.
@[reducible] def CleanVerify.Nat : Type := _root_.Nat
@[reducible] def CleanVerify.Nat.zero : CleanVerify.Nat := _root_.Nat.zero
@[reducible] def CleanVerify.Nat.succ : CleanVerify.Nat -> CleanVerify.Nat := _root_.Nat.succ
@[reducible] def CleanVerify.Nat.rec.{u} :
    (motive : CleanVerify.Nat -> Sort u) -> motive CleanVerify.Nat.zero ->
    ((n : CleanVerify.Nat) -> motive n -> motive (CleanVerify.Nat.succ n)) ->
    (t : CleanVerify.Nat) -> motive t :=
  fun motive z s t => @_root_.Nat.rec motive z s t
-- `casesOn` is AUTO-GENERATED by both kernels for an inductive, and the carrier
-- is a `def`, so it has none. Missed by the first cut of this block, which
-- enumerated the names the SPEC declares and forgot the ones the KERNEL
-- synthesises -- measured: `Nat.noConfusion_clean` is built on it, so its
-- absence took out the noConfusion pair and everything downstream. Argument
-- order is motive-first, matching how the exporter applies it (always with `@`,
-- so Lean's implicit motive is passed explicitly).
@[reducible] def CleanVerify.Nat.casesOn.{u} :
    (motive : CleanVerify.Nat -> Sort u) -> (t : CleanVerify.Nat) ->
    motive CleanVerify.Nat.zero ->
    ((n : CleanVerify.Nat) -> motive (CleanVerify.Nat.succ n)) -> motive t :=
  fun motive t z s => @_root_.Nat.casesOn motive t z s
@[reducible] def CleanVerify.Nat.add : CleanVerify.Nat -> CleanVerify.Nat -> CleanVerify.Nat :=
  _root_.Nat.add
@[reducible] def CleanVerify.Nat.pred : CleanVerify.Nat -> CleanVerify.Nat := _root_.Nat.pred
@[reducible] def CleanVerify.Nat.sub : CleanVerify.Nat -> CleanVerify.Nat -> CleanVerify.Nat :=
  _root_.Nat.sub

"#;

/// Emit the bridged Nat carrier block.
///
/// WHY THIS EXISTS. Clean's kernel does not walk Nat literals unary: its Nat
/// reduction is native on `BigNat` and keyed by NAME (`names::NAT_ADD` and
/// siblings in `clean-kernel/src/tc/reduction/mod.rs`, with `whnf` running
/// `reduce_nat` BEFORE delta). Emitting into the `CleanVerify` namespace turned
/// that off, so the old mirror export was not replaying what Clean's kernel did
/// -- it was demanding something strictly harder, and the spec says so about
/// itself at `core_spec/eval_ir_float.rs:174-177`: a unary numeral of magnitude
/// 2^63 "does not exist". Measured on the mirror, at the best possible
/// encoding: 2x per doubling, extrapolating to 33 h for `u32::MAX` and 7.9
/// million years for 2^63.
///
/// WHAT IS AND IS NOT CLAIMED AFTERWARDS is stated in
/// `docs/SELF_VERIFICATION_CERTIFICATE.md` section 4. In short: Clean's Nat
/// inductive and its three declared bodies are still emitted verbatim and still
/// independently re-checked (as `NatSpec`, with the correspondence PROVED); but
/// every other exported declaration is re-checked with Lean's `Nat` substituted
/// for Clean's, i.e. Lean re-checks the IMAGE of Clean's theorem under a proved
/// isomorphism rather than the theorem verbatim.
fn emit_nat_carrier(
    env: &Environment,
    renames: &HashMap<String, String>,
    structs: &HashSet<String>,
) -> Result<String, String> {
    // The spec side is emitted from the LIVE environment under a local rename,
    // never from fixed text. If the spec's `Nat.add` body ever changes, the
    // emitted `NatSpec.add` changes with it and `add_agrees` must still be
    // proved -- a hardcoded body would instead export the old one and prove the
    // correspondence of something the spec no longer says.
    let mut spec: HashMap<String, String> = renames.clone();
    for n in NAT_BRIDGED_NAMES {
        spec.insert(n.to_string(), n.replacen("Nat", "NatSpec", 1));
    }

    let mut s = String::new();
    s.push_str(
        "-- ==== the spec's OWN Nat, emitted verbatim as NatSpec and still\n\
         -- ==== independently re-checked: positivity, universe, recursor ====\n",
    );
    s.push_str(&emit_inductive(
        env,
        &Name::from_string("Nat"),
        &spec,
        structs,
    )?);

    for op in ["Nat.add", "Nat.pred", "Nat.sub"] {
        let n = Name::from_string(op);
        let ci = env
            .get_const(&n)
            .ok_or_else(|| format!("{op} is not in the environment"))?;
        let value = ci
            .value
            .as_ref()
            .ok_or_else(|| format!("{op} has no value to emit"))?;
        let mut p = Printer::new(&spec, structs);
        let ty = p.expr(&ci.type_, &mut Vec::new())?;
        let v = p.expr(value, &mut Vec::new())?;
        let lean = op.replacen("Nat", "NatSpec", 1);
        s.push_str(&format!(
            "noncomputable def {NAMESPACE}.{}{} : {} :=\n  {}\n\n",
            escape_name(&lean),
            level_params_suffix(&ci.level_params),
            ty,
            v
        ));
    }

    s.push_str(NAT_BRIDGE_AND_ALIASES);
    s.push_str(crate::comparison_bridge::GUARDED_SUBTRACTION);
    Ok(s)
}

pub(crate) fn emit_constant(
    env: &Environment,
    item: &Item,
    renames: &HashMap<String, String>,
    structs: &HashSet<String>,
) -> Result<String, String> {
    let ci = env
        .get_const(&item.name)
        .ok_or_else(|| "constant not found in environment".to_string())?;
    let name_str = item.name.to_string();
    let lean_name = renames.get(&name_str).cloned().unwrap_or(name_str);
    let mut p = Printer::new(renames, structs);
    let mut ctx: Vec<String> = Vec::new();
    let ty = p.expr(&ci.type_, &mut ctx)?;
    let suffix = level_params_suffix(&ci.level_params);
    let qname = format!("{NAMESPACE}.{}", escape_name(&lean_name));

    match item.kind {
        ItemKind::Axiom => Ok(format!("axiom {qname}{suffix} : {ty}\n")),
        ItemKind::Theorem | ItemKind::Def => {
            let value = ci
                .value
                .as_ref()
                .ok_or_else(|| "valued constant lost its value".to_string())?;
            let v = p.expr(value, &mut ctx)?;
            // FIDELITY: a Clean `ConstantKind::Opaque` is delta-BLOCKED by
            // Clean's own kernel — `get_delta_const` excludes it
            // (`tc/def_eq/delta_helpers.rs:169`), so Clean structurally cannot
            // unfold it during conversion. Lean's `opaque` is the faithful
            // counterpart: it typechecks the value and then seals the constant,
            // and Lean's kernel will not unfold it either. Emitting these as a
            // plain `def` handed the foreign checker STRICTLY MORE reduction
            // power than the checker under test, so the cross-check could have
            // passed on a conversion Clean itself cannot perform. Opacity used
            // to survive only as a comment; it is now carried by the keyword.
            //
            // `noncomputable` is load-bearing, not cosmetic: a bare `opaque`
            // runs the Lean CODE GENERATOR (a `noncomputable def` does not),
            // which rejects every recursor-based body here with "code generator
            // does not support recursor `X.rec` yet". `noncomputable opaque`
            // suppresses codegen and keeps the kernel-level seal. Both halves
            // measured on the 8,010-declaration export.
            let kw = match (&item.kind, ci.kind) {
                // Clean `Theorem` is likewise delta-blocked, and so is a Lean
                // `theorem` (ReducibilityHints::Opaque) — already faithful.
                (ItemKind::Theorem, _) => "theorem",
                (_, ConstantKind::Opaque) => "noncomputable opaque",
                // `noncomputable`: recursor-based bodies have no codegen; this
                // affects compilation only, never kernel checking.
                _ => "noncomputable def",
            };
            let comment = match ci.kind {
                ConstantKind::Opaque => "-- (opaque in Clean)\n",
                _ => "",
            };
            Ok(format!("{comment}{kw} {qname}{suffix} : {ty} :=\n  {v}\n"))
        }
        ItemKind::NatCarrier | ItemKind::NatShim => {
            unreachable!("handled by emit_nat_carrier / the NatShim arm of emit_item")
        }
        ItemKind::Inductive | ItemKind::QuotShim => {
            unreachable!("handled by emit_inductive / emit_quot_shim")
        }
        ItemKind::ComparisonBridge | ItemKind::ComparisonAgreement => {
            unreachable!("handled by the comparison bridge emitter")
        }
    }
}

/// Emit a single-constructor, index-free inductive as a Lean `structure`, so
/// Lean auto-generates positional field accessors (`pf0`, `pf1`, …) that are
/// the same primitive projections Clean's kernel `Proj` nodes denote. The
/// underlying inductive declaration Lean elaborates is identical (same
/// constructor telescope); field names are `pf<i>` to avoid colliding with
/// Clean's own accessor *definitions* (e.g. `Prod.fst`), which are exported
/// separately as defs whose bodies project via `pf<i>`.
fn emit_structure(
    env: &Environment,
    name: &Name,
    renames: &HashMap<String, String>,
    structs: &HashSet<String>,
) -> Result<String, String> {
    let iv = env
        .get_inductive(name)
        .ok_or_else(|| "inductive vanished from environment".to_string())?;
    // Guarded by the structure-likeness check in main; re-assert here.
    if iv.constructor_names.len() != 1 || iv.num_indices != 0 || iv.is_nested {
        return Err("proj target is not structure-like".to_string());
    }
    let mut p = Printer::new(renames, structs);
    let mut ctx: Vec<String> = Vec::new();
    let (binders, rest) = p.telescope(&iv.type_, iv.num_params as usize, &mut ctx, "p_")?;
    let result_ty = p.expr(rest, &mut ctx)?;

    let ind_str = name.to_string();
    let cn = &iv.constructor_names[0];
    let cv = env
        .get_constructor(cn)
        .ok_or_else(|| format!("constructor {cn} missing"))?;
    let cn_str = cn.to_string();
    let short = cn_str
        .strip_prefix(&format!("{ind_str}."))
        .ok_or_else(|| format!("constructor {cn_str} not namespaced under {ind_str}"))?;
    if short.contains('.') {
        return Err(format!("constructor {cn_str} has nested name component"));
    }

    // Peel the ctor telescope: params (bound to the header names), then every
    // remaining Pi binder is a field. Fields may depend on earlier fields —
    // the context carries the field names so later types print them.
    let mut cp = Printer::new(renames, structs);
    cp.next_var = p.next_var;
    let mut cctx: Vec<String> = Vec::new();
    let (_pb, mut crest) = cp.telescope(&cv.type_, cv.num_params as usize, &mut cctx, "p_")?;
    let mut fields = String::new();
    let mut nfields = 0usize;
    while let ExprKind::Pi(_, ty, body) = crest.kind() {
        let t = cp.expr(ty, &mut cctx)?;
        fields.push_str(&format!("\n  pf{nfields} : {t}"));
        cctx.push(format!("pf{nfields}"));
        crest = body;
        nfields += 1;
    }
    if nfields == 0 {
        // A zero-field type can never be a Proj target; keep the plain form.
        return emit_inductive(env, name, renames, structs);
    }

    Ok(format!(
        "structure {NAMESPACE}.{}{}{} : {} where\n  {} ::{}\n",
        escape_name(&ind_str),
        level_params_suffix(&iv.level_params),
        binders,
        result_ty,
        escape_name(short),
        fields
    ))
}

/// Emit the Quot family as a visible adapter block over Lean core's built-in
/// quotient primitives instead of opaque `axiom`s. Clean's kernel implements
/// `Quot`/`Quot.mk`/`Quot.lift`/`Quot.ind` with the same types and the same
/// computation rule (`Quot.lift f h (Quot.mk r a) ≡ f a`) as Lean's kernel
/// (`crates/clean-kernel/src/quot.rs`, mirroring lean4 `src/kernel/quot.cpp`);
/// an `axiom` cannot carry a computation rule, so mapping onto Lean's own
/// primitives is what lets Lean re-check the Quot-backed towers (Rat, NNReal,
/// …) rather than skipping them. `Quot.sound` stays an explicit axiom.
/// The TYPE of each shim is still printed from Clean's stored elaborated type
/// (fidelity contract); only the VALUE is the adapter. The mirror-Eq adapter
/// `mirrorEqToCore` converts `CleanVerify.Eq` (the exported mirror inductive)
/// to Lean's `Eq` where `Quot.lift`'s respect-obligation meets Lean's.
fn emit_quot_shim(
    env: &Environment,
    item: &Item,
    renames: &HashMap<String, String>,
    structs: &HashSet<String>,
) -> Result<String, String> {
    let ci = env
        .get_const(&item.name)
        .ok_or_else(|| "constant not found in environment".to_string())?;
    let mut p = Printer::new(renames, structs);
    let mut ctx: Vec<String> = Vec::new();
    let ty = p.expr(&ci.type_, &mut ctx)?;
    let suffix = level_params_suffix(&ci.level_params);
    let name_str = item.name.to_string();
    let qname = format!("{NAMESPACE}.{}", escape_name(&name_str));

    let (pre, value): (&str, &str) = match name_str.as_str() {
        "Quot" => (
            "-- ==== Quot family: adapter block onto Lean core's built-in quotient ====\n\
             -- Same types + same computation rule as Clean's kernel primitives\n\
             -- (clean-kernel/src/quot.rs); defs (not axioms) so Lean's own kernel\n\
             -- supplies `Quot.lift f h (Quot.mk r a) ≡ f a`. Quot.sound stays an axiom.\n",
            "fun a r => @_root_.Quot a r",
        ),
        "Quot.mk" => ("", "fun a r x => @_root_.Quot.mk a r x"),
        "Quot.lift" => (
            // The mirror-Eq -> core-Eq adapter, needed exactly here.
            "noncomputable def CleanVerify.mirrorEqToCore.{u} : (a : Sort u) -> ((x : a) -> ((y : a) -> ((@CleanVerify.Eq a x y) -> (@_root_.Eq a x y)))) :=\n  \
             fun a x y h => @CleanVerify.Eq.rec a x (fun z _hz => @_root_.Eq a x z) (@_root_.Eq.refl a x) y h\n\n",
            "fun a r b f h q => @_root_.Quot.lift a r b f (fun x y hr => CleanVerify.mirrorEqToCore b (f x) (f y) (h x y hr)) q",
        ),
        "Quot.ind" => ("", "fun a r m h q => @_root_.Quot.ind a r m h q"),
        other => return Err(format!("unexpected Quot-shim item {other}")),
    };
    Ok(format!(
        "{pre}noncomputable def {qname}{suffix} : {ty} :=\n  {value}\n"
    ))
}
