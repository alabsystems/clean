/// Imports Dafny verification results into the Mathverse trust framework.
///
/// Dafny programs compile to Boogie, which generates SMT-LIB2 verification
/// conditions. This importer parses those VCs and tracks their verification
/// status through the trust pipeline.
pub struct DafnyImporter {
    /// Whether to attempt certificate replay (upgrades trust level).
    cert_replay_enabled: bool,
}

impl Default for DafnyImporter {
    fn default() -> Self {
        Self::new()
    }
}

impl DafnyImporter {
    /// Create a new Dafny importer with default settings.
    #[must_use]
    pub fn new() -> Self {
        Self {
            cert_replay_enabled: false,
        }
    }

    /// Enable certificate replay for upgraded trust.
    #[must_use]
    pub fn with_cert_replay(mut self, enabled: bool) -> Self {
        self.cert_replay_enabled = enabled;
        self
    }

    /// Import a single Boogie verification condition from SMT-LIB2 text.
    ///
    /// Parses the VC text and extracts the method name, source location, and
    /// assertion body. The VC text must contain at least an `(assert ...)` form.
    pub fn import_boogie_vc(
        &self,
        vc_text: &str,
    ) -> Result<DafnyVerificationCondition, DafnyError> {
        let trimmed = vc_text.trim();
        if trimmed.is_empty() {
            return Err(DafnyError::ParseError {
                reason: "empty VC text".to_string(),
            });
        }

        // Extract VC name from a `;; VC: <name>` comment line if present.
        let name =
            extract_comment_field(trimmed, "VC:").unwrap_or_else(|| "anonymous_vc".to_string());

        // Extract method name from `;; Method: <name>` comment.
        let method_name = extract_comment_field(trimmed, "Method:")
            .unwrap_or_else(|| "unknown_method".to_string());

        // Extract source file from `;; File: <path>` comment.
        let source_file = extract_comment_field(trimmed, "File:");

        // Extract source line from `;; Line: <n>` comment.
        let source_line =
            extract_comment_field(trimmed, "Line:").and_then(|s| s.parse::<u32>().ok());

        // The assertion body is the full text (including metadata comments).
        // In production, this would be validated as well-formed SMT-LIB2.
        let assertion = trimmed.to_string();

        Ok(DafnyVerificationCondition {
            name,
            method_name,
            source_file,
            source_line,
            assertion,
        })
    }

    /// Produce an import result from a set of parsed VCs and their verification status.
    ///
    /// - `name`: Name for the overall verification session (e.g., module name).
    /// - `vcs`: Parsed verification conditions.
    /// - `all_verified`: Whether the SMT solver reported all VCs as valid.
    #[must_use]
    pub fn import_dafny_result(
        &self,
        name: &str,
        vcs: &[DafnyVerificationCondition],
        all_verified: bool,
    ) -> DafnyImportResult {
        let vc_count = vcs.len();
        let verified_count = if all_verified { vc_count } else { 0 };

        let (axiom_profile, trust_level) = if all_verified && self.cert_replay_enabled {
            // Certificate replay upgrades from oracle trust to certificate trust.
            (AxiomProfile::SAT_CERT, TrustLevel::CertificateReplayed)
        } else {
            // Without cert replay, we trust the SMT solver as an oracle.
            (AxiomProfile::SMT_ORACLE, TrustLevel::TrustedOracle)
        };

        let mut diagnostics = Vec::new();
        if !all_verified {
            diagnostics.push(format!(
                "not all VCs verified: {verified_count}/{vc_count} passed"
            ));
        }
        if self.cert_replay_enabled && all_verified {
            diagnostics.push("certificate replay: enabled and successful".to_string());
        }

        // Collect source file from first VC with a known source.
        let source_file = vcs.iter().find_map(|vc| vc.source_file.clone());

        let provenance = Provenance {
            source: SourceSystem::Dafny,
            original_name: name.to_string(),
            source_file,
            axiom_profile,
        };

        DafnyImportResult {
            name: name.to_string(),
            vc_count,
            verified_count,
            axiom_profile,
            trust_level,
            provenance,
            diagnostics,
        }
    }
}

