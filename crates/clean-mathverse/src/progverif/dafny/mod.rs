/// Extract a value from an SMT-LIB2 comment line: `;; <prefix> <value>`.
fn extract_comment_field(text: &str, prefix: &str) -> Option<String> {
    for line in text.lines() {
        let line = line.trim();
        if let Some(rest) = line.strip_prefix(";;") {
            let rest = rest.trim();
            if let Some(value) = rest.strip_prefix(prefix) {
                let value = value.trim();
                if !value.is_empty() {
                    return Some(value.to_string());
                }
            }
        }
    }
    None
}

