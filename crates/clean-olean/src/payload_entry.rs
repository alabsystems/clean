//! A separately built module's Clean payload, admitted through the reference
//! entry (KR1 increment 3, `docs/DECISIONS.md` R143).
//!
//! Probe K1 (Trust `reports/2026-09-17-phase0-k1-one-env.md`) found that an
//! importer took a built module's declarations as stored: `.olean` payload
//! constants were inserted structurally, so a payload whose
//! `K1Lib.zero_add'` stated `0 + n = n + 1` over the original proof let
//! `theorem k1_false : (0 : Nat) = 1 := K1Lib.zero_add' 0` check (mutation
//! M3). `clean check` has since refused to credit such a citation (the
//! module-trust gate, `clean-cli`'s `check_import_gate_tests`). This module is
//! the same import for the reference entry, the door Certified evidence goes
//! through: every declaration of the payload is checked by
//! [`ReferenceKernel::add_checked`] / [`ReferenceKernel::add_inductive_checked`]
//! in Lean's theory, in dependency order, and nothing of the payload is taken
//! on trust. An inductive family's recursors are regenerated by the kernel and
//! must equal the payload's; a payload axiom outside Ax0 is refused by the
//! entry's own rule.

use std::collections::{HashMap, HashSet};

use clean_kernel::env::{ConstantInfo, ConstantKind, Declaration};
use clean_kernel::expr::UsedConstants;
use clean_kernel::inductive::{Constructor, InductiveDecl, InductiveType};
use clean_kernel::name::Name;
use clean_kernel::{ReferenceAccepted, ReferenceKernel, ReferenceRefusal};

use crate::payload::CleanPayload;

/// Why a payload was not admitted, naming the first declaration that failed.
#[derive(Debug, thiserror::Error)]
pub enum PayloadAdmission {
    /// The entry refused `decl`.
    #[error("`{decl}`: {refusal}")]
    Refused {
        /// The payload declaration (an inductive block's first type).
        decl: Name,
        /// The entry's refusal.
        refusal: ReferenceRefusal,
    },
    /// The payload is not a set of declarations the entry can replay: a
    /// value-less non-axiom constant that is no inductive member, a
    /// constructor or family it does not describe, a dependency cycle, or a
    /// stored recursor that differs from the one the kernel regenerated.
    #[error("`{decl}`: {reason}")]
    Malformed {
        /// The payload declaration.
        decl: Name,
        /// What is wrong.
        reason: String,
    },
}

/// One unit of replay: a constant, or an inductive block.
enum Unit {
    Constant(Declaration),
    Block(InductiveDecl),
}

impl Unit {
    fn head(&self) -> Name {
        match self {
            Unit::Constant(d) => parts(d).0.clone(),
            Unit::Block(b) => b.types[0].name.clone(),
        }
    }
}

/// Admit every declaration of `payload` through `kernel`, in dependency order.
/// Returns one token per admitted unit, in admission order.
///
/// # Errors
///
/// [`PayloadAdmission::Refused`] for the first unit the entry refuses (nothing
/// after it is admitted; what came before stays, as with any sequence of
/// entry admissions); [`PayloadAdmission::Malformed`] for a payload the entry
/// cannot replay.
pub fn admit_payload(
    kernel: &mut ReferenceKernel,
    payload: &CleanPayload,
) -> Result<Vec<ReferenceAccepted>, PayloadAdmission> {
    let units = units_of(payload)?;
    // Names each unit declares, and the unit declaring each name.
    let mut owner: HashMap<Name, usize> = HashMap::new();
    let mut declares: Vec<Vec<Name>> = Vec::with_capacity(units.len());
    for (i, u) in units.iter().enumerate() {
        let names = unit_names(u, payload);
        for n in &names {
            owner.insert(n.clone(), i);
        }
        declares.push(names);
    }
    let deps: Vec<HashSet<usize>> = units
        .iter()
        .enumerate()
        .map(|(i, u)| {
            unit_citations(u)
                .into_iter()
                .filter_map(|n| owner.get(&n).copied())
                .filter(|&j| j != i)
                .collect()
        })
        .collect();
    let order = dependency_order(&units, &deps)?;
    let mut tokens = Vec::with_capacity(units.len());
    // `order` names each unit exactly once, so admitting the units sorted by
    // their place in it admits each once, in that order.
    let mut rank = vec![0; units.len()];
    for (place, &i) in order.iter().enumerate() {
        rank[i] = place;
    }
    let mut ordered: Vec<(usize, Unit)> = units.into_iter().enumerate().collect();
    ordered.sort_by_key(|&(i, _)| rank[i]);
    for (i, unit) in ordered {
        let head = unit.head();
        let token = match unit {
            Unit::Constant(d) => kernel.add_checked(d),
            Unit::Block(b) => kernel.add_inductive_checked(b),
        }
        .map_err(|refusal| PayloadAdmission::Refused {
            decl: head.clone(),
            refusal,
        })?;
        compare_recursors(kernel, payload, &declares[i])?;
        tokens.push(token);
    }
    Ok(tokens)
}

/// The payload's replay units: one block per mutual inductive group (in the
/// order of its first member), then every other constant.
fn units_of(payload: &CleanPayload) -> Result<Vec<Unit>, PayloadAdmission> {
    let generated: HashSet<&Name> = payload
        .inductives
        .iter()
        .map(|i| &i.name)
        .chain(payload.constructors.iter().map(|c| &c.name))
        .chain(payload.recursors.iter().map(|r| &r.name))
        .collect();
    let mut units = Vec::new();
    let mut seen_blocks: HashSet<Name> = HashSet::new();
    for ind in &payload.inductives {
        if seen_blocks.contains(&ind.name) {
            continue;
        }
        let members: Vec<Name> = if ind.all_names.is_empty() {
            vec![ind.name.clone()]
        } else {
            ind.all_names.clone()
        };
        let mut types = Vec::with_capacity(members.len());
        for m in &members {
            let Some(val) = payload.inductives.iter().find(|i| &i.name == m) else {
                return Err(PayloadAdmission::Malformed {
                    decl: m.clone(),
                    reason: "a mutual member the payload does not describe".to_string(),
                });
            };
            let mut constructors = Vec::with_capacity(val.constructor_names.len());
            for c in &val.constructor_names {
                let Some(ctor) = payload.constructors.iter().find(|k| &k.name == c) else {
                    return Err(PayloadAdmission::Malformed {
                        decl: c.clone(),
                        reason: "a constructor the payload does not describe".to_string(),
                    });
                };
                constructors.push(Constructor {
                    name: ctor.name.clone(),
                    type_: ctor.type_.clone(),
                });
            }
            types.push(InductiveType {
                name: val.name.clone(),
                type_: val.type_.clone(),
                constructors,
            });
            seen_blocks.insert(m.clone());
        }
        units.push(Unit::Block(InductiveDecl {
            level_params: ind.level_params.clone(),
            num_params: ind.num_params,
            types,
        }));
    }
    for c in &payload.constants {
        if generated.contains(&c.name) {
            continue;
        }
        units.push(Unit::Constant(declaration_of(c)?));
    }
    Ok(units)
}

fn parts(d: &Declaration) -> (&Name, &clean_kernel::Expr, Option<&clean_kernel::Expr>) {
    match d {
        Declaration::Definition {
            name, type_, value, ..
        }
        | Declaration::Theorem {
            name, type_, value, ..
        }
        | Declaration::Opaque {
            name, type_, value, ..
        } => (name, type_, Some(value)),
        Declaration::Axiom { name, type_, .. } => (name, type_, None),
    }
}

fn declaration_of(c: &ConstantInfo) -> Result<Declaration, PayloadAdmission> {
    let name = c.name.clone();
    let level_params = c.level_params.clone();
    let type_ = c.type_.clone();
    let value = || {
        c.value.clone().ok_or_else(|| PayloadAdmission::Malformed {
            decl: c.name.clone(),
            reason: format!("a {:?} with no value", c.kind),
        })
    };
    Ok(match c.kind {
        ConstantKind::Axiom => Declaration::Axiom {
            name,
            level_params,
            type_,
        },
        ConstantKind::Definition => Declaration::Definition {
            name,
            level_params,
            type_,
            value: value()?,
            is_reducible: c.is_reducible,
        },
        ConstantKind::Theorem => Declaration::Theorem {
            name,
            level_params,
            type_,
            value: value()?,
        },
        ConstantKind::Opaque => Declaration::Opaque {
            name,
            level_params,
            type_,
            value: value()?,
        },
    })
}

/// Every name a unit declares (a block: its types, constructors and the
/// payload's recursors of those types).
fn unit_names(u: &Unit, payload: &CleanPayload) -> Vec<Name> {
    match u {
        Unit::Constant(d) => vec![parts(d).0.clone()],
        Unit::Block(b) => {
            let families: HashSet<&Name> = b.types.iter().map(|t| &t.name).collect();
            let mut out: Vec<Name> = Vec::new();
            for t in &b.types {
                out.push(t.name.clone());
                out.extend(t.constructors.iter().map(|c| c.name.clone()));
            }
            out.extend(
                payload
                    .recursors
                    .iter()
                    .filter(|r| families.contains(&r.inductive_name))
                    .map(|r| r.name.clone()),
            );
            out
        }
    }
}

fn unit_citations(u: &Unit) -> HashSet<Name> {
    let mut out = HashSet::new();
    match u {
        Unit::Constant(d) => {
            let (_, type_, value) = parts(d);
            type_.used_constants_dag(UsedConstants::WithProjectionStructures, &mut out);
            if let Some(v) = value {
                v.used_constants_dag(UsedConstants::WithProjectionStructures, &mut out);
            }
        }
        Unit::Block(b) => {
            for t in &b.types {
                t.type_
                    .used_constants_dag(UsedConstants::WithProjectionStructures, &mut out);
                for c in &t.constructors {
                    c.type_
                        .used_constants_dag(UsedConstants::WithProjectionStructures, &mut out);
                }
            }
        }
    }
    out
}

/// Kahn's order over `deps`, ties broken by the payload's own order.
fn dependency_order(
    units: &[Unit],
    deps: &[HashSet<usize>],
) -> Result<Vec<usize>, PayloadAdmission> {
    let mut done = vec![false; units.len()];
    let mut order = Vec::with_capacity(units.len());
    // Every unit before `first` is done, so the search for the next one can
    // start there; when none is ready, `first` is the unit the cycle names.
    while let Some(first) = (0..units.len()).find(|&i| !done[i]) {
        let next = (first..units.len()).find(|&i| !done[i] && deps[i].iter().all(|&j| done[j]));
        let Some(i) = next else {
            return Err(PayloadAdmission::Malformed {
                decl: units[first].head(),
                reason: "a dependency cycle among the payload's declarations".to_string(),
            });
        };
        done[i] = true;
        order.push(i);
    }
    Ok(order)
}

/// Each payload recursor of a just-admitted block must equal the one the
/// kernel regenerated (type and rules): a stored recursor is never taken.
fn compare_recursors(
    kernel: &ReferenceKernel,
    payload: &CleanPayload,
    declared: &[Name],
) -> Result<(), PayloadAdmission> {
    for r in payload
        .recursors
        .iter()
        .filter(|r| declared.contains(&r.name))
    {
        let Some(regenerated) = kernel.environment().get_recursor(&r.name) else {
            return Err(PayloadAdmission::Malformed {
                decl: r.name.clone(),
                reason: "the kernel generated no recursor of this name".to_string(),
            });
        };
        let same_rules = regenerated.rules.len() == r.rules.len()
            && regenerated
                .rules
                .iter()
                .zip(&r.rules)
                .all(|(a, b)| a.constructor_name == b.constructor_name && a.rhs == b.rhs);
        if regenerated.type_ != r.type_ || !same_rules {
            return Err(PayloadAdmission::Malformed {
                decl: r.name.clone(),
                reason: "the stored recursor differs from the one the kernel regenerated"
                    .to_string(),
            });
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use clean_kernel::{Environment, Expr};

    fn n(s: &str) -> Name {
        Name::from_string(s)
    }

    /// A payload as `clean lake build` would write it for a module holding
    /// `inductive KR3B : Prop | mk`, `def kr3_use : KR3B := KR3B.mk` and
    /// `def kr3_use2 : KR3B := kr3_use`, with `kr3_use2` listed FIRST and
    /// `kr3_use` second. Inductive blocks are always replayed before
    /// constants, so only a constant citing a constant listed after it
    /// tests the order: admission must follow dependencies, not payload
    /// order (in payload order `kr3_use2` would cite an absent `kr3_use`).
    fn module_payload() -> CleanPayload {
        let mut env = Environment::default();
        env.add_inductive_core(InductiveDecl {
            level_params: vec![],
            num_params: 0,
            types: vec![InductiveType {
                name: n("KR3B"),
                type_: Expr::prop(),
                constructors: vec![Constructor {
                    name: n("KR3B.mk"),
                    type_: Expr::const_(n("KR3B"), vec![]),
                }],
            }],
        })
        .expect("KR3B");
        env.add_decl(Declaration::Definition {
            name: n("kr3_use"),
            level_params: vec![],
            type_: Expr::const_(n("KR3B"), vec![]),
            value: Expr::const_(n("KR3B.mk"), vec![]),
            is_reducible: false,
        })
        .expect("kr3_use");
        env.add_decl(Declaration::Definition {
            name: n("kr3_use2"),
            level_params: vec![],
            type_: Expr::const_(n("KR3B"), vec![]),
            value: Expr::const_(n("kr3_use"), vec![]),
            is_reducible: false,
        })
        .expect("kr3_use2");
        let mut constants: Vec<ConstantInfo> = env.constants().cloned().collect();
        let rank = |c: &ConstantInfo| match c.name.to_string().as_str() {
            "kr3_use2" => 0,
            "kr3_use" => 1,
            _ => 2,
        };
        constants.sort_by_key(rank);
        CleanPayload {
            constants,
            inductives: env.inductives().cloned().collect(),
            constructors: env.constructors().cloned().collect(),
            recursors: env.recursors().cloned().collect(),
            ..CleanPayload::default()
        }
    }

    fn entry() -> ReferenceKernel {
        ReferenceKernel::new(Environment::default()).expect("empty base")
    }

    #[test]
    fn test_a_module_is_admitted_in_dependency_order() {
        let p = module_payload();
        assert_eq!(p.constants[0].name, n("kr3_use2"), "listed first");
        assert_eq!(p.constants[1].name, n("kr3_use"), "listed second");
        let mut k = entry();
        let tokens = admit_payload(&mut k, &p).expect("the genuine module");
        assert_eq!(tokens.len(), 3, "the block, then the two definitions");
        assert!(k.environment().get_const(&n("kr3_use")).is_some());
        assert!(k.environment().get_const(&n("kr3_use2")).is_some());
        // Control: the payload order itself is not admissible.
        let mut k = entry();
        let units = units_of(&p).expect("units");
        let mut refused = None;
        for u in units {
            let head = u.head();
            let r = match u {
                Unit::Constant(d) => k.add_checked(d),
                Unit::Block(b) => k.add_inductive_checked(b),
            };
            if r.is_err() {
                refused = Some(head);
                break;
            }
        }
        assert_eq!(
            refused,
            Some(n("kr3_use2")),
            "payload order refuses kr3_use2"
        );
        assert!(k.environment().get_recursor(&n("KR3B.rec")).is_some());
    }

    /// A stored recursor whose rule differs from the regenerated one is
    /// refused (control: the genuine payload above).
    #[test]
    fn test_a_doctored_stored_recursor_is_refused() {
        let mut p = module_payload();
        let rec = p
            .recursors
            .iter_mut()
            .find(|r| r.name == n("KR3B.rec"))
            .expect("KR3B.rec");
        rec.rules[0].rhs = Expr::prop();
        match admit_payload(&mut entry(), &p) {
            Err(PayloadAdmission::Malformed { decl, .. }) => assert_eq!(decl, n("KR3B.rec")),
            other => panic!("expected the recursor refused, got {other:?}"),
        }
    }

    /// A stored recursor whose TYPE differs from the regenerated one (its
    /// rules unchanged) is refused, and so is a stored recursor of an
    /// admitted family that the kernel did not generate at all. Control:
    /// the genuine payload (`test_a_module_is_admitted_in_dependency_order`).
    #[test]
    fn test_a_stored_recursor_differing_in_type_or_absent_is_refused() {
        let mut p = module_payload();
        let rec = p
            .recursors
            .iter_mut()
            .find(|r| r.name == n("KR3B.rec"))
            .expect("KR3B.rec");
        rec.type_ = Expr::prop();
        match admit_payload(&mut entry(), &p) {
            Err(PayloadAdmission::Malformed { decl, .. }) => assert_eq!(decl, n("KR3B.rec")),
            other => panic!("expected the recursor's type refused, got {other:?}"),
        }
        let mut p = module_payload();
        let mut extra = p
            .recursors
            .iter()
            .find(|r| r.name == n("KR3B.rec"))
            .expect("KR3B.rec")
            .clone();
        extra.name = n("KR3B.rec_extra");
        p.recursors.push(extra);
        match admit_payload(&mut entry(), &p) {
            Err(PayloadAdmission::Malformed { decl, .. }) => {
                assert_eq!(decl, n("KR3B.rec_extra"));
            }
            other => panic!("expected the ungenerated recursor refused, got {other:?}"),
        }
    }

    /// A definition whose stored value does not have its stored type is
    /// refused by the kernel, and nothing after it is admitted.
    #[test]
    fn test_a_tampered_definition_is_refused() {
        let mut p = module_payload();
        let use_ = p
            .constants
            .iter_mut()
            .find(|c| c.name == n("kr3_use"))
            .expect("kr3_use");
        use_.type_ = Expr::prop();
        let mut k = entry();
        match admit_payload(&mut k, &p) {
            Err(PayloadAdmission::Refused { decl, .. }) => assert_eq!(decl, n("kr3_use")),
            other => panic!("expected kr3_use refused, got {other:?}"),
        }
        assert!(k.environment().get_const(&n("kr3_use")).is_none());
    }
}
