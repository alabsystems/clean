/// Every extension key `cone` declares, with its dependency-closed fingerprint
/// over `env`.
fn extension_key_fingerprints(
    env: &Environment,
    cone: &BTreeSet<Name>,
    index: &FamilyIndex,
) -> BTreeMap<Name, [u8; 32]> {
    let mut fp = Fingerprinter::with_family_index(env, index);
    cone.iter()
        .filter(|name| extension_hook(name).is_some())
        .map(|name| (name.clone(), fp.constant(name)))
        .collect()
}

/// One reason the closed re-check refused something.
///
/// Every variant is fail-closed: the named object is NOT in the replay
/// environment, and every unit that depends on it is refused in turn.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[non_exhaustive]
pub enum ClosedRecheckRefusal {
    /// A name in the cone is not registered in the source environment at all
    /// (e.g. an import skipped it), so there is nothing to re-derive.
    AbsentFromEnvironment {
        /// The missing constant.
        name: String,
    },
    /// The cone contains a reference cycle between replay units.
    DependencyCycle {
        /// The unit names on the cycle, in discovery order.
        names: Vec<String>,
    },
    /// `add_decl` refused the declaration against the already-replayed prefix.
    DeclarationRefused {
        /// The declaration.
        name: String,
        /// Verbatim kernel error.
        error: String,
    },
    /// `add_inductive_core` refused the reconstructed family.
    FamilyRefused {
        /// Canonical family head.
        family: String,
        /// Verbatim kernel error.
        error: String,
    },
    /// The family's own metadata could not be reconstructed (a member named by
    /// the family is missing from the source environment's registries).
    FamilyIncomplete {
        /// Canonical family head.
        family: String,
        /// What was missing.
        detail: String,
    },
    /// The import carries a family member the kernel's replay does not
    /// generate, so it can only be believed, never re-derived.
    MemberNotRegenerated {
        /// The imported member.
        name: String,
        /// Canonical family head.
        family: String,
    },
    /// The kernel regenerated this member and it disagrees with the imported
    /// bytes.
    MemberMismatch {
        /// The imported member.
        name: String,
        /// How it disagrees.
        detail: String,
    },
    /// A regenerated ι-rule disagrees with the imported one. THIS is the class
    /// no weaker level can see: the imported right-hand side is what the
    /// importing environment reduces with, and nothing re-derives it.
    RecursorRuleMismatch {
        /// The recursor.
        recursor: String,
        /// The constructor whose rule differs.
        constructor: String,
        /// How it differs.
        detail: String,
    },
    /// A dependency of this unit was refused, so the unit cannot be replayed.
    DependencyRefused {
        /// The unit that could not be replayed.
        name: String,
        /// The refused dependency it needed.
        blocked_by: String,
    },
    /// A name the kernel reduces BY NAME (see
    /// [`extension_binding::EXTENSION_KEYS`]) is declared by the cone with a
    /// dependency-closed fingerprint the binding table does not pin for it, so
    /// the kernel's built-in meaning and the declaration's own meaning may
    /// differ. Refused before `add_decl` / `add_inductive_core` sees it.
    ExtensionBindingMismatch {
        /// The key.
        name: String,
        /// Where the kernel matches it by name, and what it does with it.
        hook: &'static str,
        /// Label of the table compared against.
        table: String,
        /// Every fingerprint the table pins for it, each labelled with the
        /// world that pinned it (`<world>: <hex> | …`), or `None` when no
        /// world has a row for it.
        expected: Option<String>,
        /// The cone's fingerprint for it.
        found: String,
    },
    /// The cone reaches a declaration the source environment marks `unsafe` or
    /// `partial`, which is outside the kernel's trusted fragment.
    OutsideTrustedFragment {
        /// The declaration.
        name: String,
        /// `"unsafe"` or `"partial"`.
        marker: &'static str,
    },
    /// [`ImportedConeGate`] only: a cone member carries a name the consumer's
    /// base already holds, but the declaration the cone reaches is not the
    /// base's declaration (or a family is only partly the base's).
    BaseConflict {
        /// The member.
        name: String,
        /// How it differs.
        detail: String,
    },
    /// A quotient primitive (`Quot`, `Quot.mk`, `Quot.lift`, `Quot.ind`,
    /// `Quot.sound`) could not be provided. These are KERNEL-BUILT: their
    /// types name `Eq` by name and are never re-derived, so the replay installs
    /// them only through [`Environment::add_quot`] — Lean's `add_quot`
    /// precondition that the already-admitted `Eq` has exactly the shape those
    /// types assume — and never admits a cone declaration under one of their
    /// names.
    QuotientPrecondition {
        /// The cone member carrying the quotient name.
        name: String,
        /// Why the quotient could not be provided.
        detail: String,
    },
}

impl ClosedRecheckRefusal {
    /// The object this refusal is about.
    #[must_use]
    pub fn subject(&self) -> &str {
        match self {
            Self::AbsentFromEnvironment { name }
            | Self::DeclarationRefused { name, .. }
            | Self::MemberNotRegenerated { name, .. }
            | Self::MemberMismatch { name, .. }
            | Self::DependencyRefused { name, .. }
            | Self::ExtensionBindingMismatch { name, .. }
            | Self::OutsideTrustedFragment { name, .. }
            | Self::BaseConflict { name, .. }
            | Self::QuotientPrecondition { name, .. } => name,
            Self::FamilyRefused { family, .. } | Self::FamilyIncomplete { family, .. } => family,
            Self::RecursorRuleMismatch { recursor, .. } => recursor,
            Self::DependencyCycle { .. } => "<cycle>",
        }
    }
}

/// Resource and policy knobs for [`recheck_closed`].
#[derive(Debug, Clone)]
pub struct ClosedRecheckOptions {
    /// Per-check reduction/inference budget handed to the kernel (`0` =
    /// unlimited). A pure resource limit: exhaustion is a conservative refusal,
    /// never a pass.
    pub max_heartbeats: u32,
    /// The table every name the kernel reduces by name is gated against.
    ///
    /// Always the pinned table outside this crate: the field is crate-private,
    /// so no lane can hand the replay a table of its own. In-crate tests set a
    /// derived table to state an honest meaning, and a run under one is
    /// reported as unpinned and promotes nothing. There is deliberately no
    /// option to install Clean's native-reducer table: it is keyed by name and
    /// tied to no declaration (see [`extension_binding`]).
    pub(crate) extension_bindings: ExtensionBindings,
    /// Provide the kernel's quotient primitives to a cone that reaches them.
    ///
    /// The quotient primitives are kernel-owned canonical builders, not
    /// imported declarations; without them `Quot.lift` does not ι-reduce.
    /// They are installed LAZILY, when the replay reaches the first of them,
    /// and only through [`Environment::add_quot`] (Lean's `add_quot`: the
    /// cone's `Eq`, already admitted, must have exactly the shape their types
    /// assume). With `false`, a cone that reaches one is refused.
    pub install_quotient_primitives: bool,
    /// Refuse (rather than attempt) once the cone exceeds this many constants.
    /// `None` = no bound.
    pub max_closure: Option<usize>,
}

impl Default for ClosedRecheckOptions {
    fn default() -> Self {
        Self {
            max_heartbeats: clean_kernel::tc::DEFAULT_HEARTBEAT_LIMIT,
            extension_bindings: ExtensionBindings::pinned(),
            install_quotient_primitives: true,
            max_closure: None,
        }
    }
}

/// The measured result of a dependency-closed re-check.
#[derive(Debug, Clone, Serialize)]
pub struct ClosedRecheckReport {
    /// Always [`RecheckLevel::ClosedReplay`]; carried so a serialized report
    /// names its own level.
    pub level: RecheckLevel,
    /// The requested targets.
    pub targets: Vec<String>,
    /// Distinct constant names in the transitive cone (including the targets).
    pub cone_constants: usize,
    /// Replay units: one per ordinary constant plus one per inductive family
    /// block.
    pub units: usize,
    /// Ordinary constants re-admitted through `add_decl`.
    pub constants_admitted: usize,
    /// Inductive family blocks re-admitted through `add_inductive_core`.
    pub families_replayed: usize,
    /// Imported family members (heads, constructors, recursors) compared
    /// against the regenerated ones.
    pub family_members_compared: usize,
    /// Imported ι-rules compared against regenerated ones.
    pub recursor_rules_compared: usize,
    /// Axioms the replay admitted, sorted. An axiom is admitted by `add_decl`
    /// like any other declaration; it is listed because it is an assumption,
    /// not a derivation.
    pub axioms_admitted: Vec<String>,
    /// Everything refused, in discovery order.
    pub refusals: Vec<ClosedRecheckRefusal>,
    /// Wall-clock milliseconds for the replay (cone walk included).
    pub elapsed_ms: u128,
    /// Label of the extension-binding table the by-name keys were gated
    /// against.
    pub extension_bindings: String,
    /// Whether that table is the pinned one. A pass under any other table may
    /// not ground a `Certified`-class claim and promotes nothing.
    pub extension_bindings_pinned: bool,
    /// Extension keys the cone declared that matched the table, sorted.
    pub extension_keys_bound: Vec<String>,
    /// `(key, dependency-closed fingerprint)` for every extension key the cone
    /// declares, bound or not — the values a binding table for this closure
    /// would pin.
    pub extension_key_fingerprints: Vec<(String, String)>,
    /// Whether the replay environment ended up carrying the kernel's quotient
    /// primitives (installed only when the cone reached one, after `Eq`).
    pub quotient_primitives_installed: bool,
}

impl ClosedRecheckReport {
    /// True iff nothing was refused.
    ///
    /// A `true` here is the only thing in this crate that may be cited as the
    /// re-check behind a `Certified`-class claim, and even then only together
    /// with an audit of the replay environment (see
    /// [`recheck_closed`]'s returned environment) — this says the cone was
    /// re-derived, not that its axioms are acceptable.
    #[must_use]
    pub fn passed(&self) -> bool {
        self.refusals.is_empty()
    }

    /// A sentence that states the verdict together with what the level proves,
    /// for direct use in a lane's output.
    #[must_use]
    pub fn verdict_sentence(&self) -> String {
        if self.passed() {
            let axioms = if self.axioms_admitted.is_empty() {
                "It rests on no axioms.".to_string()
            } else {
                format!(
                    "CONDITIONAL on {} admitted axiom(s), each an assumption and not a \
                     derivation: {}.",
                    self.axioms_admitted.len(),
                    self.axioms_admitted.join(", ")
                )
            };
            let table = if self.extension_bindings_pinned {
                format!(
                    "by-name kernel reductions bound by the pinned `{}` table",
                    self.extension_bindings
                )
            } else {
                format!(
                    "by-name kernel reductions bound only by the UNPINNED table `{}` — this pass \
                     grounds no Certified-class claim",
                    self.extension_bindings
                )
            };
            format!(
                "{}: PASS over {} constants in {} units, {}. {} What that proves: {}. What it \
                 does NOT prove: {}.",
                self.level.token(),
                self.cone_constants,
                self.units,
                table,
                axioms,
                self.level.proves(),
                self.level.does_not_prove()
            )
        } else {
            format!(
                "{}: REFUSED ({} refusals) over {} constants in {} units",
                self.level.token(),
                self.refusals.len(),
                self.cone_constants,
                self.units
            )
        }
    }
}

/// A closed re-check plus the environment it built.
#[derive(Debug)]
pub struct ClosedRecheck {
    /// What the replay measured and refused.
    pub report: ClosedRecheckReport,
    /// The replay environment. Every constant in it entered through
    /// `add_decl` or `add_inductive_core`, so `audit_certification` run here
    /// answers about a kernel-re-derived cone rather than an imported one.
    pub replayed: Environment,
    /// Exactly the names this replay re-admitted through a checking path.
    ///
    /// This is what
    /// [`promote_origins_after_closed_recheck`] is allowed to promote — never
    /// the requested targets, and never a name that only appeared in the cone.
    pub admitted: BTreeSet<Name>,
}

/// Promote the trust-ledger origin of every constant a PASSING closed re-check
/// re-admitted, from `needs_recheck` to `KernelChecked`.
///
/// # Why this function exists
///
/// [`Environment::promote_origin_kernel_checked`] states its precondition as
/// "the caller MUST have just re-derived this constant with the kernel's
/// `add_decl`-equivalent checker". Until 2026-09-17 the only production caller
/// was the bootstrap lane, feeding it
/// [`crate::verify_batch_full::typecheck_constants_full`] — which is not one.
/// A promotion is not cosmetic: it clears
/// [`Environment::constant_needs_recheck`], a BLOCKING issue in
/// [`Environment::audit_certification`]. This is the only lane in this crate
/// that meets the precondition.
///
/// # Fail-closed
///
/// A report with ANY refusal promotes nothing and returns `0` — a cone is
/// re-derived or it is not. Neither does a report whose by-name keys were
/// gated against anything but the pinned table. Returns the number of origins
/// actually raised.
pub fn promote_origins_after_closed_recheck(env: &mut Environment, run: &ClosedRecheck) -> usize {
    if !run.report.passed() || !run.report.extension_bindings_pinned {
        return 0;
    }
    debug_assert!(
        run.report.level.may_ground_certified_class(),
        "only a dependency-closed level may promote a trust-ledger origin"
    );
    run.admitted
        .iter()
        .filter(|name| env.promote_origin_kernel_checked(name))
        .count()
}

/// One replay unit: either a single ordinary constant or a whole (possibly
/// mutual) inductive family block.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
enum UnitId {
    Constant(Name),
    Family(Name),
}

impl UnitId {
    fn label(&self) -> String {
        match self {
            Self::Constant(n) => n.to_string(),
            Self::Family(n) => format!("inductive {n}"),
        }
    }
}

/// Everything the replay needs to know about one unit, resolved once.
struct Unit {
    /// Names this unit is responsible for admitting.
    members: Vec<Name>,
    /// Constants this unit references, outside its own members.
    deps: BTreeSet<Name>,
}

/// Run a dependency-closed re-check of `targets` against `env`.
///
/// `targets` are kernel [`Name`]s, NOT display strings. A display string is
/// not a name: `Name`'s `Display` joins components with `.` and does not
/// escape a component that itself contains one, so `Name::interned` of a
/// rendered name re-splits it into a DIFFERENT name. Lean's macro/parser node
/// names do exactly that (`Lean.termMacro.trace[_]_` is `Lean` +
/// `termMacro.trace[_]_`, two components), and taking strings here refused
/// four such true constants as absent. A caller holding a string must resolve
/// it to the environment's own `Name` before asking.
///
/// The cone is walked through every reachable constant's type and value, and
/// through an inductive family's head types, constructor types, recursor
/// types and ι-rule right-hand sides.
#[must_use]
pub fn recheck_closed(
    env: &Environment,
    targets: &BTreeSet<Name>,
    options: &ClosedRecheckOptions,
) -> ClosedRecheck {
    let mut replay = Environment::default();
    replay.set_option(
        "maxHeartbeats".to_string(),
        Some(options.max_heartbeats.to_string()),
    );
    // NO native reducers: `Environment::default()` starts with an empty
    // table and nothing below adds to it (see `extension_binding`).
    //
    // NO quotient primitives yet either. Their types name `Eq` BY NAME, so
    // installing them before the cone's `Eq` is admitted let that `Eq` decide
    // what the axiom `Quot.sound` asserts (`Eq a b := False` proved `False`;
    // round-23 verification). `drive::replay_in_order` installs them through
    // `Environment::add_quot` when the first quotient unit comes up, which
    // the planner orders after `Eq` (`ConePlanner::build_unit`).
    let (report, admitted) = run_closed(env, targets, &BTreeSet::new(), options, &mut replay);
    ClosedRecheck {
        report,
        replayed: replay,
        admitted,
    }
}

/// The closed replay of `targets`' cone into `replay`, which must start
/// empty: plan the cone, order it, drive every unit through `replay`'s
/// admissions. Shared by [`recheck_closed`] and
/// [`reference_base::reference_base_closed`]. Only captured source replay
/// supplies ownership for its auxiliary wrappers.
fn run_closed(
    env: &Environment,
    targets: &BTreeSet<Name>,
    source_owned: &BTreeSet<Name>,
    options: &ClosedRecheckOptions,
    replay: &mut dyn drive::ReplayTarget,
) -> (ClosedRecheckReport, BTreeSet<Name>) {
    let started = Instant::now();
    let mut refusals = Vec::new();

    let index = FamilyIndex::with_source_wrappers(env, source_owned);
    let mut planner = ConePlanner::new(env, &index, ConeInputs::Replay);
    for target in targets {
        planner.enqueue(target);
    }
    planner.run(options.max_closure, &mut refusals);
    let ConePlanner {
        units,
        cone,
        order,
        cycles,
        absent,
        ..
    } = planner;
    for cycle in cycles {
        refusals.push(ClosedRecheckRefusal::DependencyCycle { names: cycle });
    }

    let mut stats = ReplayStats::default();
    // Every extension key the cone declares, fingerprinted up front over the
    // source environment (see `extension_binding::check_binding` for why the
    // source is the right one to hash).
    let key_fingerprints = extension_key_fingerprints(env, &cone, &index);
    // Names refused (directly or by cascade) → the unit that first refused them.
    // Seed the cascade from the planner's own absent NAMES. Re-parsing the
    // refusals' display strings (`Name::interned`) would key a component that
    // contains `.` under a different name, and its dependents would then reach
    // `add_decl` instead of being reported as blocked by the absent constant.
    let mut unavailable: BTreeMap<Name, String> = absent
        .into_iter()
        .map(|name| {
            let label = name.to_string();
            (name, label)
        })
        .collect();
    let plan = drive::ReplayPlan {
        env,
        index: &index,
        units: &units,
        order: &order,
        key_fingerprints: &key_fingerprints,
        options,
        clean_families: false,
    };
    // An empty replay environment holds nothing to take as given.
    let driven = drive::replay_in_order(
        &plan,
        replay,
        &mut unavailable,
        &mut stats,
        &mut refusals,
        &|_, _, _| drive::Given::No,
    );
    let keys_bound = driven.keys_bound;

    let report = ClosedRecheckReport {
        level: RecheckLevel::ClosedReplay,
        targets: targets.iter().map(ToString::to_string).collect(),
        cone_constants: cone.len(),
        units: units.len(),
        constants_admitted: stats.constants_admitted,
        families_replayed: stats.families_replayed,
        family_members_compared: stats.family_members_compared,
        recursor_rules_compared: stats.recursor_rules_compared,
        axioms_admitted: stats.axioms_admitted.iter().map(Name::to_string).collect(),
        refusals,
        elapsed_ms: started.elapsed().as_millis(),
        extension_bindings: options.extension_bindings.label().to_string(),
        extension_bindings_pinned: options.extension_bindings.is_pinned(),
        extension_keys_bound: keys_bound.into_iter().collect(),
        extension_key_fingerprints: key_fingerprints
            .iter()
            .map(|(name, digest)| (name.to_string(), encode_hex(digest)))
            .collect(),
        quotient_primitives_installed: replay.env().quot_installed(),
    };
    (report, stats.admitted_names)
}

fn mark_unavailable(unavailable: &mut BTreeMap<Name, String>, unit: &Unit, id: &UnitId) {
    let label = id.label();
    for member in &unit.members {
        unavailable.insert(member.clone(), label.clone());
    }
}

#[derive(Default)]
struct ReplayStats {
    constants_admitted: usize,
    families_replayed: usize,
    family_members_compared: usize,
    recursor_rules_compared: usize,
    axioms_admitted: BTreeSet<Name>,
    admitted_names: BTreeSet<Name>,
}

/// Closed replay regenerates recursors and can consult canonical conversion
/// helpers. Export writes the resident expressions and their literal support.
#[derive(Clone, Copy, PartialEq, Eq)]
enum ConeInputs {
    Replay,
    Export,
}

/// Walks the cone, groups it into units and produces a dependency order.
struct ConePlanner<'a> {
    inputs: ConeInputs,
    env: &'a Environment,
    index: &'a FamilyIndex,
    pending: Vec<Name>,
    cone: BTreeSet<Name>,
    units: BTreeMap<UnitId, Unit>,
    unit_of: BTreeMap<Name, UnitId>,
    order: Vec<UnitId>,
    /// Each unit's dependency units, resolved once after the cone is known.
    dep_units: BTreeMap<UnitId, Vec<UnitId>>,
    cycles: Vec<Vec<String>>,
    absent: BTreeSet<Name>,
}

impl<'a> ConePlanner<'a> {
    fn new(env: &'a Environment, index: &'a FamilyIndex, inputs: ConeInputs) -> Self {
        Self {
            inputs,
            env,
            index,
            pending: Vec::new(),
            cone: BTreeSet::new(),
            units: BTreeMap::new(),
            unit_of: BTreeMap::new(),
            order: Vec::new(),
            dep_units: BTreeMap::new(),
            cycles: Vec::new(),
            absent: BTreeSet::new(),
        }
    }

    fn enqueue(&mut self, name: &Name) {
        self.pending.push(name.clone());
    }

    /// The canonical head of the family `name` belongs to, if any.
    fn family_head(&self, name: &Name) -> Option<Name> {
        if self.index.is_source_wrapper(name) {
            return None;
        }
        let ind = self.env.get_inductive(name).or_else(|| {
            self.env
                .get_constructor(name)
                .and_then(|c| self.env.get_inductive(&c.inductive_name))
                .or_else(|| {
                    self.env
                        .get_recursor(name)
                        .filter(|r| {
                            self.inputs == ConeInputs::Replay
                                || !cone_plan::is_exported_eliminator_definition(self.env, r)
                        })
                        .and_then(|r| self.env.get_inductive(&r.inductive_name))
                })
        })?;
        let head = ind
            .all_names
            .iter()
            .filter(|n| self.env.get_inductive(n).is_some())
            .min()
            .cloned()
            .unwrap_or_else(|| ind.name.clone());
        Some(head)
    }

    fn resolve_unit(&self, name: &Name) -> Option<UnitId> {
        if let Some(head) = self.family_head(name) {
            return Some(UnitId::Family(head));
        }
        if self.env.get_const(name).is_some() {
            return Some(UnitId::Constant(name.clone()));
        }
        None
    }

    /// Build the unit for `id`: its member names and the constants it needs.
    fn build_unit(&self, id: &UnitId) -> Unit {
        let mut members: Vec<Name> = Vec::new();
        let mut refs: HashSet<Name> = HashSet::new();
        let mut nat_literal = false;
        let mut string_literal = false;
        let mut collect = |expr: &Expr, refs: &mut HashSet<Name>| match self.inputs {
            ConeInputs::Replay => expr.used_constants_dag(UsedConstants::ConstantsOnly, refs),
            ConeInputs::Export => {
                expr.used_constants_dag_with_literals(UsedConstants::ConstantsOnly, refs, |lit| {
                    match lit {
                        Literal::Nat(_) => nat_literal = true,
                        Literal::String(_) => string_literal = true,
                    }
                });
            }
        };
        match id {
            UnitId::Constant(name) => {
                members.push(name.clone());
                // A quotient primitive is provided by `Environment::add_quot`,
                // which requires the admitted `Eq` (Lean's `add_quot`
                // precondition): make `Eq` a dependency so it is admitted
                // first, and so a refused or absent `Eq` blocks the quotient.
                if clean_kernel::quot::is_quot_name(name) {
                    refs.insert(Name::from_string("Eq"));
                }
                if let Some(info) = self.env.get_const(name) {
                    // DAG walks: shared subterms are visited once.
                    collect(&info.type_, &mut refs);
                    if let Some(value) = &info.value {
                        collect(value, &mut refs);
                    }
                }
            }
            UnitId::Family(head) => {
                let families: Vec<Name> = self
                    .env
                    .get_inductive(head)
                    .map(|ind| {
                        if ind.all_names.is_empty() {
                            vec![ind.name.clone()]
                        } else {
                            ind.all_names.clone()
                        }
                    })
                    .unwrap_or_else(|| vec![head.clone()]);
                for family in &families {
                    let Some(ind) = self.env.get_inductive(family) else {
                        continue;
                    };
                    members.push(family.clone());
                    // REPLAY DEPENDENCIES ARE EXACTLY `add_inductive_core`'s INPUT: the
                    // family types and the constructor types. Deliberately NOT
                    // the imported recursors' types or ι-rule right-hand sides —
                    // the replay REGENERATES those from the constructors and
                    // never consumes the imported ones, and Lean's nested-family
                    // aux recursors reference constants that in turn reference
                    // the family, which would report a dependency cycle for a
                    // dependency the replay does not have.
                    collect(&ind.type_, &mut refs);
                    for ctor in &ind.constructor_names {
                        members.push(ctor.clone());
                        if let Some(c) = self.env.get_constructor(ctor) {
                            collect(&c.type_, &mut refs);
                        }
                    }
                    for rec_name in self.index.recursors(family) {
                        if self.inputs == ConeInputs::Export {
                            if let Some(rec) = self.env.get_recursor(rec_name) {
                                if cone_plan::is_exported_eliminator_definition(self.env, rec) {
                                    continue;
                                }
                                collect(&rec.type_, &mut refs);
                                for rule in &rec.rules {
                                    collect(&rule.rhs, &mut refs);
                                }
                            }
                        }
                        members.push(rec_name.clone());
                    }
                }
            }
        }
        // String conversion consults the canonical literal-expansion heads
        // even though an expression's Const-only walk cannot see them. A
        // freshly replayed Name/String comparison must not depend on an
        // unrelated later target happening to admit those definitions.
        // The String family itself bootstraps the representation; its
        // constructor types do not require literal expansion. The helpers
        // enter through the same checked, binding-pinned replay as every
        // other dependency, never through a structural/native shortcut.
        let string = Name::from_string("String");
        // lean4export's dumpNatDeps and dumpStrDeps run at a literal leaf.
        // An ordinary reference to the String type adds no export dependency.
        if nat_literal {
            let nat = Name::from_string("Nat");
            if self.env.get_const(&nat).is_some() {
                refs.insert(nat);
            }
        }
        if string_literal
            || (self.inputs == ConeInputs::Replay
                && refs.contains(&string)
                && !members.contains(&string))
        {
            for label in ["Char.ofNat", "String.ofList"] {
                let support = Name::from_string(label);
                if self.env.get_const(&support).is_some() {
                    refs.insert(support);
                }
            }
        }
        let own: HashSet<&Name> = members.iter().collect();
        let deps = refs
            .into_iter()
            .filter(|n| !own.contains(n))
            .collect::<BTreeSet<_>>();
        Unit { members, deps }
    }

    /// Resolve every queued name into units, then emit a dependency order.
    fn run(&mut self, max_closure: Option<usize>, refusals: &mut Vec<ClosedRecheckRefusal>) {
        let mut roots: Vec<UnitId> = Vec::new();
        let mut discovered: BTreeSet<UnitId> = BTreeSet::new();
        let mut frontier: Vec<Name> = std::mem::take(&mut self.pending);
        let mut root_names: Vec<Name> = frontier.clone();

        while let Some(name) = frontier.pop() {
            if !self.cone.insert(name.clone()) {
                continue;
            }
            if let Some(limit) = max_closure {
                if self.cone.len() > limit {
                    refusals.push(ClosedRecheckRefusal::AbsentFromEnvironment {
                        name: format!("<cone exceeded max_closure={limit}>"),
                    });
                    return;
                }
            }
            let Some(id) = self.resolve_unit(&name) else {
                self.absent.insert(name.clone());
                refusals.push(ClosedRecheckRefusal::AbsentFromEnvironment {
                    name: name.to_string(),
                });
                continue;
            };
            self.unit_of.insert(name.clone(), id.clone());
            if discovered.insert(id.clone()) {
                let unit = self.build_unit(&id);
                for member in &unit.members {
                    self.unit_of.insert(member.clone(), id.clone());
                    self.cone.insert(member.clone());
                }
                if let UnitId::Family(_) = &id {
                    for member in &unit.members {
                        // Keep the auxiliary definitions in the cone. Their
                        // bodies depend on the family, so queue them as
                        // separate units without a reverse dependency.
                        frontier.extend(self.index.source_wrappers(member).iter().cloned());
                    }
                }
                for dep in &unit.deps {
                    frontier.push(dep.clone());
                }
                self.units.insert(id.clone(), unit);
            }
        }

        // Roots in a deterministic order: requested targets first, then the
        // rest of the discovered units by name. A `BTreeSet` rather than a
        // linear `contains`: a real Lean cone is tens of thousands of units.
        let mut seen: BTreeSet<UnitId> = BTreeSet::new();
        root_names.sort();
        root_names.dedup();
        for name in &root_names {
            if let Some(id) = self.unit_of.get(name) {
                if seen.insert(id.clone()) {
                    roots.push(id.clone());
                }
            }
        }
        for id in self.units.keys() {
            if seen.insert(id.clone()) {
                roots.push(id.clone());
            }
        }

        // Each unit's dependency UNITS, resolved once. Recomputing them inside
        // the DFS made the walk quadratic in a unit's reference count.
        self.dep_units = self
            .units
            .iter()
            .map(|(id, unit)| {
                let mut ds: Vec<UnitId> = unit
                    .deps
                    .iter()
                    .filter_map(|d| self.unit_of.get(d).cloned())
                    .filter(|d| d != id)
                    .collect();
                ds.sort();
                ds.dedup();
                (id.clone(), ds)
            })
            .collect();

        self.order = self.topological_order(&roots);
    }

    /// Iterative DFS post-order. A back edge is reported as a cycle and the
    /// edge is dropped so the rest of the cone still gets an order.
    fn topological_order(&mut self, roots: &[UnitId]) -> Vec<UnitId> {
        #[derive(Clone, Copy, PartialEq, Eq)]
        enum Color {
            Grey,
            Black,
        }
        let mut color: BTreeMap<UnitId, Color> = BTreeMap::new();
        let mut order = Vec::with_capacity(self.units.len());
        let mut path: Vec<UnitId> = Vec::new();

        for root in roots {
            if color.contains_key(root) {
                continue;
            }
            let mut stack: Vec<(UnitId, usize)> = vec![(root.clone(), 0)];
            color.insert(root.clone(), Color::Grey);
            path.push(root.clone());
            while let Some((id, next)) = stack.pop() {
                let dep_units: &[UnitId] = self.dep_units.get(&id).map_or(&[][..], Vec::as_slice);
                if next < dep_units.len() {
                    stack.push((id.clone(), next + 1));
                    let dep = dep_units[next].clone();
                    match color.get(&dep) {
                        Some(Color::Black) => {}
                        Some(Color::Grey) => {
                            let start = path.iter().position(|p| p == &dep).unwrap_or(0);
                            let mut names: Vec<String> =
                                path[start..].iter().map(UnitId::label).collect();
                            names.push(dep.label());
                            if !self.cycles.contains(&names) {
                                self.cycles.push(names);
                            }
                        }
                        None => {
                            color.insert(dep.clone(), Color::Grey);
                            path.push(dep.clone());
                            stack.push((dep, 0));
                        }
                    }
                } else {
                    color.insert(id.clone(), Color::Black);
                    if path.last() == Some(&id) {
                        path.pop();
                    }
                    order.push(id);
                }
            }
        }
        order
    }
}

