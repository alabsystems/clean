/// A proof obligation generated by the Dafny/Boogie pipeline.
///
/// Proof obligations are finer-grained than verification conditions: a single
/// VC may contain multiple proof obligations (e.g., a method postcondition
/// generates one PO per `ensures` clause). Source location tracking enables
/// diagnostic mapping back to the original `.dfy` file.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[non_exhaustive]
pub struct DafnyProofObligation {
    /// Unique identifier for this proof obligation.
    pub id: String,
    /// Kind of proof obligation.
    pub kind: DafnyPoKind,
    /// Enclosing method or function name.
    pub method_name: String,
    /// Source `.dfy` file path, if known.
    pub source_file: Option<String>,
    /// Source line number, if known.
    pub source_line: Option<u32>,
    /// Source column number, if known.
    pub source_column: Option<u32>,
    /// The assertion text in SMT-LIB2 format.
    pub assertion: String,
    /// Whether this PO was discharged.
    pub discharged: bool,
}

/// Kind of Dafny proof obligation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[non_exhaustive]
pub enum DafnyPoKind {
    /// Method/function precondition check.
    Precondition,
    /// Method/function postcondition check.
    Postcondition,
    /// Loop invariant maintenance.
    LoopInvariant,
    /// Loop variant (termination measure) decrease.
    LoopVariant,
    /// Assert statement.
    Assertion,
    /// Array/sequence bounds check.
    BoundsCheck,
    /// Division by zero check.
    DivisionByZero,
    /// Object non-null check.
    NonNull,
    /// Other (unclassified) proof obligation.
    Other,
}

/// Statistics collected during a Dafny verification session.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct DafnyStatistics {
    /// Total number of VCs generated.
    pub vcs_total: usize,
    /// Number of VCs successfully proved.
    pub vcs_proved: usize,
    /// Number of axioms used across all VCs.
    pub axioms_used: usize,
    /// Number of unique methods verified.
    pub methods_verified: usize,
    /// Number of unique methods with at least one unproved VC.
    pub methods_with_errors: usize,
    /// Total solver time in milliseconds.
    pub solver_time_ms: u64,
}

impl DafnyStatistics {
    /// Compute statistics from a set of parsed VCs and their verification status.
    ///
    /// - `vcs`: Parsed verification conditions.
    /// - `all_verified`: Whether the SMT solver reported all VCs as valid.
    /// - `axiom_count`: Number of axioms used by the solver.
    #[must_use]
    pub fn from_vcs(
        vcs: &[DafnyVerificationCondition],
        all_verified: bool,
        axiom_count: usize,
    ) -> Self {
        let vcs_total = vcs.len();
        let vcs_proved = if all_verified { vcs_total } else { 0 };

        // Count unique methods.
        let mut method_names: Vec<&str> = vcs.iter().map(|vc| vc.method_name.as_str()).collect();
        method_names.sort_unstable();
        method_names.dedup();
        let methods_verified = if all_verified { method_names.len() } else { 0 };
        let methods_with_errors = if all_verified { 0 } else { method_names.len() };

        Self {
            vcs_total,
            vcs_proved,
            axioms_used: axiom_count,
            methods_verified,
            methods_with_errors,
            solver_time_ms: 0,
        }
    }

    /// Fraction of VCs proved, as a value in `[0.0, 1.0]`.
    ///
    /// Returns `1.0` if there are no VCs (vacuously true).
    #[must_use]
    pub fn success_rate(&self) -> f64 {
        if self.vcs_total == 0 {
            1.0
        } else {
            self.vcs_proved as f64 / self.vcs_total as f64
        }
    }
}

/// Parse a Boogie verification condition from SMT-LIB2 text.
///
/// This is a standalone function that performs the same parsing as
/// [`DafnyImporter::import_boogie_vc`] but without requiring an importer
/// instance. Useful for batch processing pipelines.
///
/// # Errors
///
/// Returns `DafnyError::ParseError` if the input is empty.
pub fn parse_boogie_vc(vc_text: &str) -> Result<DafnyVerificationCondition, DafnyError> {
    let trimmed = vc_text.trim();
    if trimmed.is_empty() {
        return Err(DafnyError::ParseError {
            reason: "empty VC text".to_string(),
        });
    }

    let name = extract_comment_field(trimmed, "VC:").unwrap_or_else(|| "anonymous_vc".to_string());
    let method_name =
        extract_comment_field(trimmed, "Method:").unwrap_or_else(|| "unknown_method".to_string());
    let source_file = extract_comment_field(trimmed, "File:");
    let source_line = extract_comment_field(trimmed, "Line:").and_then(|s| s.parse::<u32>().ok());
    let assertion = trimmed.to_string();

    Ok(DafnyVerificationCondition {
        name,
        method_name,
        source_file,
        source_line,
        assertion,
    })
}

/// Classify a Boogie VC name into a proof obligation kind.
///
/// Boogie VCs follow naming conventions like `<method>::precondition::0`,
/// `<method>::loop_invariant::1`, etc.
#[must_use]
pub fn classify_vc_kind(vc_name: &str) -> DafnyPoKind {
    let lower = vc_name.to_ascii_lowercase();
    if lower.contains("precondition") || lower.contains("requires") {
        DafnyPoKind::Precondition
    } else if lower.contains("postcondition") || lower.contains("ensures") {
        DafnyPoKind::Postcondition
    } else if lower.contains("loop_invariant") || lower.contains("invariant") {
        DafnyPoKind::LoopInvariant
    } else if lower.contains("variant") || lower.contains("decreases") {
        DafnyPoKind::LoopVariant
    } else if lower.contains("assert") {
        DafnyPoKind::Assertion
    } else if lower.contains("bounds") || lower.contains("index") {
        DafnyPoKind::BoundsCheck
    } else if lower.contains("division") || lower.contains("div_by_zero") {
        DafnyPoKind::DivisionByZero
    } else if lower.contains("non_null") || lower.contains("nonnull") {
        DafnyPoKind::NonNull
    } else {
        DafnyPoKind::Other
    }
}

