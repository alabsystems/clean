//! Dependency-closed re-check: a fresh kernel replay of a target's whole cone.
//!
//! # What was wrong
//!
//! [`crate::verify_batch_full::typecheck_constants_full`] is the check that
//! import lanes and reports have called "a full kernel re-check of every
//! imported constant". Its own module doc says what it is not: "NOT fresh
//! `add_decl`, dependency-closed replay, inductive-rule validation, or import
//! authority". It re-checks each named declaration **against the environment
//! that already contains every other imported declaration**, so:
//!
//! * a constant's type is believed on sight wherever it is *referenced* — only
//!   the row for that constant itself re-derives it;
//! * an inductive family's head, constructors and recursors are
//!   `extend_*_structural` insertions (`no free vars / no metavariables /
//!   level scope` and nothing else), and **a recursor's ι-rule right-hand
//!   sides are never re-derived at all** — so a tampered reduction rule is
//!   invisible to every existing level;
//! * a per-constant PASS says nothing about whether the rest of the cone
//!   passed, and the batch's own failures do not propagate to the theorems
//!   that depend on them.
//!
//! This module adds the level those claims actually need.
//!
//! # What this does
//!
//! [`recheck_closed`] takes the target names and the loaded environment and
//! replays the targets' transitive constant cone into a **fresh, initially
//! empty** [`Environment`], in dependency order:
//!
//! * ordinary constants through [`Environment::add_decl`] — the same gate a
//!   locally elaborated declaration passes, against only the constants already
//!   admitted by this replay;
//! * inductive families through [`Environment::add_inductive_core`], so the
//!   family is re-validated (positivity, constructor shape, universe
//!   constraints) and **its recursors and their ι-rules are regenerated by the
//!   kernel**. The imported recursor bytes are compared against the
//!   regenerated ones and reported, but they are never installed.
//!
//! Nothing enters the replay environment except through one of those two
//! checking paths, plus the kernel's own quotient primitives — and those only
//! through [`Environment::add_quot`], after the cone's `Eq` has been admitted
//! and found to have exactly the shape their kernel-built types assume
//! (Lean's `add_quot`). The replay environment carries NO native-reducer
//! table, and every name the kernel reduces or builds by name must match the
//! pinned extension-binding table before it is admitted — see
//! [`extension_binding`] for why both are needed.
//!
//! A constant that is absent, refused, unsafe, partial, or whose own
//! dependency was refused is not admitted, and everything that depends on it
//! is refused in turn.
//!
//! # Levels
//!
//! [`RecheckLevel`] names the three levels that exist and states, per level,
//! what a pass proves and what it does not. Only [`RecheckLevel::ClosedReplay`]
//! answers `true` to [`RecheckLevel::may_ground_certified_class`]; the weaker
//! two say so in their own `proves`/`does_not_prove` text, so a lane cannot
//! print "re-checked" for a level that did not re-check the cone.

