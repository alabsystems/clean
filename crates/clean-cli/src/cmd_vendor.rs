//! `clean vendor` — manage vendored crate sources for offline / reproducible builds.
//!
//! The external crate sources (`cargo vendor` output — ~583M uncompressed, mostly
//! cfg-gated `windows`/`wasm` bindings) are deliberately **NOT committed to git**.
//! They are published as a compressed `vendor.tar.zst` GitHub Release artifact —
//! the same pattern the `.mathverse` shards use — and fetched on demand. Default
//! reproducibility comes from `Cargo.lock` + `--locked`; this command adds the
//! offline tier.
//!
//! - `clean vendor fetch`   — download + extract the artifact and write an
//!   (untracked) `.cargo/vendor.toml` source-replacement config.
//! - `clean vendor package` — `cargo vendor` + compress to a `vendor.tar.zst`
//!   artifact (the maintainer side: produce what `fetch` consumes).
//! - `clean vendor status`  — report whether the vendor tier is set up + the
//!   `Cargo.lock` fingerprint it should correspond to.
//! - `clean vendor clean`   — remove `vendor/` and `.cargo/vendor.toml`.
//!
//! Internal repos (`ay`, `trust`, `trust-ir`) are path-dep submodules and are
//! never vendored — only external crates.io/git deps are. Replaces the former
//! `scripts/fetch_vendor.sh`.

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{anyhow, bail, Context};
use clap::Subcommand;
use clean_features::{Category, Example, FeatureDescriptor, RefKind, Reference, Stability};

/// Default GitHub repo hosting the vendor release artifact.
const DEFAULT_REPO: &str = "alabsystems/clean";
/// Default release tag carrying the `vendor.tar.zst` asset.
const DEFAULT_TAG: &str = "vendor-latest";
/// Release asset name.
const VENDOR_ASSET: &str = "vendor.tar.zst";
/// Vendored-sources directory (workspace-root-relative).
const VENDOR_DIR: &str = "vendor";
/// Untracked cargo source-replacement config written by `fetch`.
const VENDOR_CONFIG_REL: &str = ".cargo/vendor.toml";

/// Canonical cargo source-replacement config. Mirrors `cargo vendor`'s printed
/// stanza for this workspace; `package` re-derives it and warns on drift (e.g. a
/// changed git-source rev), so this constant stays the single source of truth.
const VENDOR_CONFIG_TOML: &str = r#"# Generated by `clean vendor fetch` — DO NOT COMMIT (gitignored).
# Source-replaces crates.io + git deps with the vendored copies under vendor/.
[source.crates-io]
replace-with = "vendored-sources"

[source."git+https://github.com/ufmg-smite/carcara?rev=fecb4224def3c26f93a5d4f1804ecf58eb979650"]
git = "https://github.com/ufmg-smite/carcara"
rev = "fecb4224def3c26f93a5d4f1804ecf58eb979650"
replace-with = "vendored-sources"

[source.vendored-sources]
directory = "vendor"
"#;

