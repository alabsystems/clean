//! Deterministic Markdown renderer for the `FeatureDescriptor` registry.
//!
//! This module is the single source of truth for the generated documentation
//! tree under `docs/cli/`. Both the `gen_cli_docs` binary and the
//! `docs_drift` integration test call [`render_all_docs`] to produce the
//! same in-memory `filename -> contents` map; the binary persists it to disk
//! and the test diffs it against the committed tree.
//!
//! Design: `designs/2026-04-18-unified-cli-feature-index.md` (§Phase 5,
//! drift invariant #3). Issue #3482.
//!
//! Rendering invariants:
//!
//! - Output is **deterministic**: every traversal order is derived from the
//!   descriptor data (path, category enum order) rather than hash iteration.
//! - Output is **line-stable**: no timestamps, build hashes, or other
//!   ambient inputs. Running the generator twice on the same registry must
//!   produce byte-identical bytes so the drift test can compare by
//!   `String::eq` without whitespace tolerance.
//! - Output is **UTF-8** with `\n` line endings.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use clean_features::{Category, FeatureDescriptor, RefKind, Stability};

/// Banner placed at the top of every generated file so humans who open one
/// by mistake know not to edit it.
pub(crate) const GENERATED_BANNER: &str =
    "<!-- GENERATED by scripts/gen_cli_docs.sh — do not edit by hand. -->\n\
<!-- Source: FeatureDescriptor arrays in crates/*/src/cli*.rs. -->\n\
<!-- Drift test: `cargo test --locked -p clean-cli --test docs_drift`. -->\n";

/// Filename stem used by the index file. Kept as a constant so the drift
/// test, the generator binary, and the renderer agree on one canonical spelling.
pub(crate) const INDEX_FILENAME: &str = "index.md";

/// Convert a descriptor path like `&["kernel", "verify"]` to a dashed file
/// stem (`"kernel-verify"`).
///
/// The stem is guaranteed to be safe as a filename on macOS, Linux, and
/// Windows because `FeatureDescriptor::path` segments are ASCII identifiers
/// sourced from clap subcommand names.
#[must_use]
pub(crate) fn filename_for(descriptor: &FeatureDescriptor) -> String {
    let stem = descriptor.path.join("-");
    format!("{stem}.md")
}

/// Render every descriptor's Markdown body plus an index, returning a map
/// keyed by filename (relative to `docs/cli/`) with UTF-8 contents.
///
/// The map is a `BTreeMap` so callers that iterate (for example the drift
/// test's diff printer) see files in lexicographic order regardless of the
/// input slice ordering.
#[must_use]
pub(crate) fn render_all_docs(
    descriptors: &[&'static FeatureDescriptor],
) -> BTreeMap<String, String> {
    // Work from a path-sorted copy so the index and any future cross-linking
    // sees descriptors in a canonical order.
    let mut sorted: Vec<&'static FeatureDescriptor> = descriptors.to_vec();
    sorted.sort_by(|a, b| a.path.cmp(b.path));

    let mut files = BTreeMap::new();
    for descriptor in &sorted {
        files.insert(filename_for(descriptor), render_descriptor(descriptor));
    }
    files.insert(INDEX_FILENAME.to_owned(), render_index(&sorted));
    files
}

/// Render one descriptor as a standalone Markdown document.
///
/// Pub(crate) so the drift test's diff printer can render one descriptor at
/// a time when reporting a single-file drift, without rebuilding the whole
/// map.
#[must_use]
pub(crate) fn render_descriptor(descriptor: &FeatureDescriptor) -> String {
    let mut md = String::new();
    md.push_str(GENERATED_BANNER);
    md.push('\n');

    let _ = writeln!(md, "# `clean {}`", descriptor.path_display());
    md.push('\n');
    let _ = writeln!(
        md,
        "**Category:** `{}`  \\\n**Stability:** `{}`",
        descriptor.category.as_slug(),
        descriptor.stability.as_slug()
    );
    md.push('\n');
    let _ = writeln!(md, "## Summary");
    md.push('\n');
    let _ = writeln!(md, "{}", descriptor.summary.trim_end());
    md.push('\n');
    let _ = writeln!(md, "## Description");
    md.push('\n');
    let _ = writeln!(md, "{}", descriptor.description.trim_end());
    md.push('\n');

    if !descriptor.examples.is_empty() {
        let _ = writeln!(md, "## Examples");
        md.push('\n');
        for example in descriptor.examples {
            let _ = writeln!(md, "- `{}` — {}", example.cmd, example.what);
        }
        md.push('\n');
    }

    if !descriptor.see_also.is_empty() {
        let _ = writeln!(md, "## See also");
        md.push('\n');
        for other in descriptor.see_also {
            let _ = writeln!(md, "- `clean {other}`");
        }
        md.push('\n');
    }

    if !descriptor.references.is_empty() {
        let _ = writeln!(md, "## References");
        md.push('\n');
        for reference in descriptor.references {
            let _ = writeln!(
                md,
                "- **{}** — {} (`{}`)",
                ref_kind_slug(reference.kind),
                reference.label,
                reference.target
            );
        }
        md.push('\n');
    }

    normalize_terminal_newline(md)
}

/// Render the top-level `index.md` grouping descriptors by category, then
/// by stability, then by path within each bucket. Unused categories are
/// skipped (no empty headers).
#[must_use]
pub(crate) fn render_index(descriptors: &[&'static FeatureDescriptor]) -> String {
    let mut md = String::new();
    md.push_str(GENERATED_BANNER);
    md.push('\n');

    let _ = writeln!(md, "# Clean CLI — feature index");
    md.push('\n');
    let _ = writeln!(
        md,
        "{} descriptor{} registered. One Markdown file per feature lives \
         alongside this index; use `clean help <path>` for interactive rendering.",
        descriptors.len(),
        if descriptors.len() == 1 { "" } else { "s" }
    );
    md.push('\n');

    for &category in Category::all() {
        let in_cat: Vec<&'static FeatureDescriptor> = descriptors
            .iter()
            .copied()
            .filter(|d| d.category == category)
            .collect();
        if in_cat.is_empty() {
            continue;
        }

        let _ = writeln!(md, "## {}", category.as_slug());
        md.push('\n');

        for &stability in Stability::all() {
            let in_stab: Vec<&'static FeatureDescriptor> = in_cat
                .iter()
                .copied()
                .filter(|d| d.stability == stability)
                .collect();
            if in_stab.is_empty() {
                continue;
            }
            let _ = writeln!(md, "### {}", stability.as_slug());
            md.push('\n');
            for d in in_stab {
                let _ = writeln!(
                    md,
                    "- [`clean {path}`]({file}) — {summary}",
                    path = d.path_display(),
                    file = filename_for(d),
                    summary = d.summary
                );
            }
            md.push('\n');
        }
    }

    normalize_terminal_newline(md)
}

fn normalize_terminal_newline(mut md: String) -> String {
    while md.ends_with("\n\n") {
        md.pop();
    }
    if !md.ends_with('\n') {
        md.push('\n');
    }
    md
}

/// Stable lowercase slug for a [`RefKind`] variant.
///
/// Kept as a local helper (rather than a method on `RefKind`) so a future
/// `#[non_exhaustive]` addition to the enum does not silently change the
/// rendered output — any new variant falls through to `"other"` until this
/// helper is updated.
fn ref_kind_slug(kind: RefKind) -> &'static str {
    match kind {
        RefKind::Design => "design",
        RefKind::Issue => "issue",
        RefKind::Doc => "doc",
        RefKind::Crate => "crate",
        _ => "other",
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use clean_features::{Example, Reference};

    const CHECK: FeatureDescriptor = FeatureDescriptor {
        path: &["check"],
        summary: "Type-check a Lean file",
        description: "Runs the kernel type-checker.",
        category: Category::Verification,
        stability: Stability::V1,
        examples: &[Example {
            cmd: "clean check foo.lean",
            what: "check one file",
        }],
        see_also: &["eval"],
        references: &[Reference {
            kind: RefKind::Design,
            label: "Unified CLI design",
            target: "designs/2026-04-18-unified-cli-feature-index.md",
        }],
        domain_root: None,
        alternative_forms: &[],
        feature_gate: None,
    };

    const KERNEL_VERIFY: FeatureDescriptor = FeatureDescriptor {
        path: &["kernel", "verify"],
        summary: "Verify a kernel certificate",
        description: "Checks a `.cert.json` payload.",
        category: Category::Kernel,
        stability: Stability::Usable,
        examples: &[Example {
            cmd: "clean kernel verify proof.cert.json",
            what: "verify a standalone certificate",
        }],
        see_also: &[],
        references: &[],
        domain_root: None,
        alternative_forms: &[],
        feature_gate: None,
    };

    #[test]
    fn test_filename_for_single_segment() {
        assert_eq!(filename_for(&CHECK), "check.md");
    }

    #[test]
    fn test_filename_for_multi_segment() {
        assert_eq!(filename_for(&KERNEL_VERIFY), "kernel-verify.md");
    }

    #[test]
    fn test_render_descriptor_contains_banner_and_headers() {
        let md = render_descriptor(&CHECK);
        assert!(md.contains("GENERATED by scripts/gen_cli_docs.sh"));
        assert!(md.contains("# `clean check`"));
        assert!(md.contains("## Summary"));
        assert!(md.contains("## Description"));
        assert!(md.contains("## Examples"));
        assert!(md.contains("## See also"));
        assert!(md.contains("## References"));
        assert!(md.contains("verification"));
        assert!(md.contains("v1"));
    }

    #[test]
    fn test_render_descriptor_skips_empty_optional_sections() {
        let md = render_descriptor(&KERNEL_VERIFY);
        // KERNEL_VERIFY has one example, no see_also, no references.
        assert!(md.contains("## Examples"));
        assert!(!md.contains("## See also"));
        assert!(!md.contains("## References"));
    }

    #[test]
    fn test_render_descriptor_is_deterministic() {
        let a = render_descriptor(&CHECK);
        let b = render_descriptor(&CHECK);
        assert_eq!(a, b);
        assert!(!a.ends_with("\n\n"));
        assert!(a.ends_with('\n'));
    }

    #[test]
    fn test_render_index_lists_descriptors_grouped_by_category() {
        let md = render_index(&[&CHECK, &KERNEL_VERIFY]);
        assert!(md.contains("# Clean CLI — feature index"));
        assert!(md.contains("## verification"));
        assert!(md.contains("## kernel"));
        assert!(md.contains("[`clean check`](check.md)"));
        assert!(md.contains("[`clean kernel verify`](kernel-verify.md)"));
        let verification_idx = md.find("## verification").expect("verification header");
        let kernel_idx = md.find("## kernel").expect("kernel header");
        assert!(
            verification_idx < kernel_idx,
            "categories appear in declared order"
        );
    }

    #[test]
    fn test_render_index_singular_plural() {
        let md_single = render_index(&[&CHECK]);
        assert!(md_single.contains("1 descriptor registered"));
        let md_plural = render_index(&[&CHECK, &KERNEL_VERIFY]);
        assert!(md_plural.contains("2 descriptors registered"));
        assert!(!md_plural.ends_with("\n\n"));
        assert!(md_plural.ends_with('\n'));
    }

    #[test]
    fn test_render_all_docs_produces_file_per_descriptor_plus_index() {
        let files = render_all_docs(&[&CHECK, &KERNEL_VERIFY]);
        assert_eq!(files.len(), 3);
        assert!(files.contains_key("check.md"));
        assert!(files.contains_key("kernel-verify.md"));
        assert!(files.contains_key(INDEX_FILENAME));
    }

    #[test]
    fn test_render_all_docs_is_order_independent() {
        let a = render_all_docs(&[&CHECK, &KERNEL_VERIFY]);
        let b = render_all_docs(&[&KERNEL_VERIFY, &CHECK]);
        assert_eq!(a, b);
    }

    #[test]
    fn test_render_all_docs_empty_registry_yields_index_only() {
        let files = render_all_docs(&[]);
        assert_eq!(files.len(), 1);
        assert!(files.contains_key(INDEX_FILENAME));
        let index = files.get(INDEX_FILENAME).expect("index present");
        assert!(index.contains("0 descriptors registered"));
    }

    #[test]
    fn test_ref_kind_slug_known_variants() {
        assert_eq!(ref_kind_slug(RefKind::Design), "design");
        assert_eq!(ref_kind_slug(RefKind::Issue), "issue");
        assert_eq!(ref_kind_slug(RefKind::Doc), "doc");
        assert_eq!(ref_kind_slug(RefKind::Crate), "crate");
    }
}
