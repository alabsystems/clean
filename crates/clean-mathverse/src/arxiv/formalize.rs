/// A mapping from a natural language concept to its Lean 4 / Mathlib name.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct ConceptLink {
    /// Natural language term (e.g., "abelian group").
    pub nl_term: String,
    /// Lean 4 / Mathlib name (e.g., "CommGroup").
    pub lean_name: String,
    /// Confidence score (1.0 = exact match from seed dictionary).
    pub confidence: f64,
}

/// Find Mathlib concepts referenced in a LaTeX statement using the seed dictionary.
/// In production, this would also use the Mathverse Library's 5 search modes.
#[must_use]
pub(crate) fn find_concepts(latex: &str) -> Vec<ConceptLink> {
    let lower = latex.to_lowercase();
    let mut found = Vec::new();

    // Sort by length descending so longer matches take priority
    let mut entries: Vec<_> = CONCEPT_MAP.iter().collect();
    entries.sort_by_key(|(k, _)| std::cmp::Reverse(k.len()));

    for (nl_term, lean_name) in entries {
        if lower.contains(nl_term) {
            found.push(ConceptLink {
                nl_term: nl_term.to_string(),
                lean_name: lean_name.to_string(),
                confidence: 1.0,
            });
        }
    }
    found
}

