# Regenerate crates/clean-elab/data/lean_core/init_aliases_v4.8.0.txt — every
# `export` alias a Lean 4.8.0 file with no import line can write — from Lean
# itself (generator: crates/clean-elab/data/lean_core/DumpInitAliases.lean).
# The header records the Lean that ran, the generator's SHA-256, the entry
# count and the entries' SHA-256; `cargo test -p clean-elab lean_core_names`
# checks them and regenerates the table to compare.
#
#   scripts/gen_lean_core_alias_table.sh   # Lean at CLEAN_LEAN_4_8_0, else elan's v4.8.0
set -eu

LEAN="${CLEAN_LEAN_4_8_0:-$HOME/.elan/toolchains/leanprover--lean4---v4.8.0/bin/lean}"
ROOT=$(cd "$(dirname "$0")/.." && pwd)
GEN="$ROOT/crates/clean-elab/data/lean_core/DumpInitAliases.lean"
OUT="$ROOT/crates/clean-elab/data/lean_core/init_aliases_v4.8.0.txt"

[ -x "$LEAN" ] || { echo "no Lean 4.8.0 at $LEAN (set CLEAN_LEAN_4_8_0)" >&2; exit 1; }
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

meta=$("$LEAN" --run "$GEN" "$tmp/aliases")
case "$meta" in
  "lean 4.8.0 "*) ;;
  *) echo "the generator did not run on Lean 4.8.0: $meta" >&2; exit 1 ;;
esac
{
  echo "# Every export alias of the environment of a Lean 4.8.0 file with no import"
  echo "# line (importModules #[Init]), one per line, sorted. Read by"
  echo "# crates/clean-elab/src/lean_core_names.rs. Generated by"
  echo "# scripts/gen_lean_core_alias_table.sh; never edit by hand."
  echo "# lean: ${meta#lean }"
  echo "# generator-sha256: $(shasum -a 256 "$GEN" | cut -d' ' -f1)"
  echo "# entries: $(wc -l < "$tmp/aliases" | tr -d ' ')"
  echo "# body-sha256: $(shasum -a 256 "$tmp/aliases" | cut -d' ' -f1)"
  cat "$tmp/aliases"
} > "$OUT"
echo "wrote $OUT"
