// Lean Code Extraction
// ════════════════════════════════════════════════════════════════════════════

/// Extract Lean 4 code from an LLM response that may contain markdown fencing
/// and explanatory text.
#[must_use]
pub(crate) fn extract_lean_code(response: &str) -> String {
    // Look for ```lean ... ``` blocks
    if let Some(start) = response.find("```lean\n") {
        let code_start = start + 8;
        if let Some(end) = response[code_start..].find("```") {
            return response[code_start..code_start + end].trim().to_string();
        }
    }

    // Look for lines starting with common Lean keywords
    let lean_keywords = [
        "theorem",
        "def",
        "lemma",
        "structure",
        "class",
        "instance",
        "import",
        "open",
        "variable",
        "namespace",
        "section",
        "noncomputable",
        "private",
        "protected",
        "@",
    ];

    let mut in_code = false;
    let mut lean_lines = Vec::new();
    for line in response.lines() {
        let trimmed = line.trim();
        if lean_keywords.iter().any(|k| trimmed.starts_with(k)) {
            in_code = true;
        }
        if in_code {
            lean_lines.push(line);
        }
    }

    if !lean_lines.is_empty() {
        return lean_lines.join("\n").trim().to_string();
    }

    response.trim().to_string()
}

