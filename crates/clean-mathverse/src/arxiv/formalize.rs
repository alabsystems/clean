/// Build an LLM prompt for formalizing a LaTeX statement.
#[must_use]
pub(crate) fn build_formalization_prompt(
    statement_latex: &str,
    kind: &str,
    concepts: &[ConceptLink],
    macros: &[(String, String)],
    prior_definitions: &[String],
) -> String {
    let mut prompt = String::with_capacity(2048);

    let kind_word = if kind == "definition" {
        "definition"
    } else {
        "theorem statement"
    };

    prompt.push_str(&format!(
        "You are a mathematical formalization expert. Convert the following \
         LaTeX {kind_word} into a Lean 4 type declaration.\n\n\
         ## LaTeX {kind_word}\n```latex\n{statement_latex}\n```\n"
    ));

    if !concepts.is_empty() {
        prompt.push_str("\n## Relevant Mathlib types\n");
        for c in concepts.iter().take(10) {
            prompt.push_str(&format!("- \"{}\" → `{}`\n", c.nl_term, c.lean_name));
        }
    }

    if !macros.is_empty() {
        prompt.push_str("\n## Paper-specific notation\n");
        for (name, body) in macros.iter().take(15) {
            prompt.push_str(&format!("- `\\{name}` = `{body}`\n"));
        }
    }

    if !prior_definitions.is_empty() {
        prompt.push_str("\n## Already formalized from this paper\n```lean\n");
        for d in prior_definitions.iter().rev().take(10).rev() {
            prompt.push_str(d);
            prompt.push('\n');
        }
        prompt.push_str("```\n");
    }

    prompt.push_str(LEAN4_INIT_TYPES_PROMPT);
    prompt.push_str(ANTI_HALLUCINATION_PROMPT);
    prompt.push_str(KNOWN_TYPES_PROMPT);
    prompt.push_str(FAILURE_PATTERNS_PROMPT);
    prompt.push_str(RULES_PROMPT);

    prompt
}

