#[test]
fn checked_eq_cong_keeps_domain_and_codomain_universes_distinct() {
    run_with_stack(|| {
        let mut spec = Specification {
            env: Environment::new(),
            definitions: HashMap::new(),
        };
        spec.add_inductive(
            r"inductive Eq (α : Sort u) : α → α → Prop
| refl : forall (a : α), Eq α a a",
            "Parameterized equality",
        )
        .expect("Eq should register");

        let type_src = "forall (α : Sort u) (β : Sort v) (f : α -> β) (a : α) (b : α), Eq α a b -> Eq β (f a) (f b)";
        let value_src =
            "fun (α : Sort u) (β : Sort v) (f : α -> β) (a : α) (b : α) (h : Eq α a b) => \
             Eq.rec α a (fun (x : α) (_h : Eq α a x) => Eq β (f a) (f x)) \
             (Eq.refl β (f a)) b h";
        spec.add_definition_checked(SpecDefinition {
            name: "Eq.cong".to_string(),
            type_src: type_src.to_string(),
            value_src: Some(value_src.to_string()),
            is_axiom: false,
            description: "Mixed-universe congruence regression".to_string(),
            category: AxiomCategory::DerivedLemma,
            proof_status: ProofStatus::DerivedProved,
            elaborated_type: None,
            elaborated_value: None,
            dependencies: Some(HashSet::from([
                "Eq".to_string(),
                "Eq.rec".to_string(),
                "Eq.refl".to_string(),
            ])),
            axiom_deps: HashSet::new(),
        })
        .expect("checked Eq.cong must preserve independent u/v universes");

        let info = spec
            .env()
            .get_const(&Name::from_string("Eq.cong"))
            .expect("Eq.cong should be registered");
        assert_eq!(
            info.level_params.len(),
            2,
            "Eq.cong must retain independent domain/codomain universes"
        );
        assert_ne!(info.level_params[0], info.level_params[1]);
    });
}

