//! Per-item Lean declaration emission.

use std::collections::{HashMap, HashSet};

use clean_kernel::{ConstantKind, Environment, ExprKind, Name};

use crate::printer::{escape_name, level_params_suffix, Printer, NAMESPACE};
use crate::{Item, ItemKind};

pub fn header(roots: &[String]) -> String {
    format!(
        "/-\n\
         CleanVerifyExport.lean — MACHINE-GENERATED foreign-kernel cross-check.\n\
         Generated by `cargo run -p clean-verify --bin lean_export` from the LIVE\n\
         clean-verify Specification environment (elaborated kernel terms, not\n\
         hand-written mirrors). Lean 4's kernel independently re-checks the\n\
         dependency closure of: {roots:?}.\n\
         Every value-less constant is an explicit `axiom` below, so\n\
         `#print axioms` reports the census honestly.\n\
         DO NOT EDIT BY HAND.\n\
         -/\n\
         set_option autoImplicit false\n\
         set_option maxHeartbeats 4000000\n\
         set_option maxRecDepth 65536\n\
         set_option linter.unusedVariables false\n\n"
    )
}

pub fn footer(roots: &[String], renames: &HashMap<String, String>) -> String {
    let mut s = String::from("\n-- ==== flagship axiom audits ====\n");
    for r in roots {
        let mapped = renames.get(r).cloned().unwrap_or_else(|| r.clone());
        s.push_str(&format!(
            "#print axioms {NAMESPACE}.{}\n",
            escape_name(&mapped)
        ));
    }
    s
}

pub fn emit_item(
    env: &Environment,
    item: &Item,
    renames: &HashMap<String, String>,
    structs: &HashSet<String>,
) -> Result<String, String> {
    match item.kind {
        ItemKind::Inductive => {
            if structs.contains(&item.name.to_string()) {
                emit_structure(env, &item.name, renames, structs)
            } else {
                emit_inductive(env, &item.name, renames, structs)
            }
        }
        ItemKind::QuotShim => emit_quot_shim(env, item, renames, structs),
        _ => emit_constant(env, item, renames, structs),
    }
}

fn emit_inductive(
    env: &Environment,
    name: &Name,
    renames: &HashMap<String, String>,
    structs: &HashSet<String>,
) -> Result<String, String> {
    let iv = env
        .get_inductive(name)
        .ok_or_else(|| "inductive vanished from environment".to_string())?;
    if iv.all_names.len() > 1 {
        return Err(format!(
            "mutual inductive block ({:?}) not supported by exporter",
            iv.all_names
        ));
    }
    if iv.is_nested {
        return Err("nested inductive not supported by exporter".to_string());
    }
    let mut p = Printer::new(renames, structs);
    let mut ctx: Vec<String> = Vec::new();
    let (binders, rest) = p.telescope(&iv.type_, iv.num_params as usize, &mut ctx, "p_")?;
    let result_ty = p.expr(rest, &mut ctx)?;

    let ind_str = name.to_string();
    let mut out = format!(
        "inductive {NAMESPACE}.{}{}{} : {}",
        escape_name(&ind_str),
        level_params_suffix(&iv.level_params),
        binders,
        result_ty
    );
    if !iv.constructor_names.is_empty() {
        out.push_str(" where");
    }

    for cn in &iv.constructor_names {
        let cv = env
            .get_constructor(cn)
            .ok_or_else(|| format!("constructor {cn} missing"))?;
        let cn_str = cn.to_string();
        let short = cn_str
            .strip_prefix(&format!("{ind_str}."))
            .ok_or_else(|| format!("constructor {cn_str} not namespaced under {ind_str}"))?;
        if short.contains('.') {
            return Err(format!("constructor {cn_str} has nested name component"));
        }
        // Strip the inductive parameters from the stored ctor type, binding
        // them to the SAME names as the header binders.
        let mut cp = Printer::new(renames, structs);
        cp.next_var = p.next_var;
        let mut cctx: Vec<String> = Vec::new();
        let (_pb, crest) = cp.telescope(&cv.type_, cv.num_params as usize, &mut cctx, "p_")?;
        let cty = cp.expr(crest, &mut cctx)?;
        out.push_str(&format!("\n  | {} : {}", escape_name(short), cty));
    }
    out.push('\n');
    Ok(out)
}

fn emit_constant(
    env: &Environment,
    item: &Item,
    renames: &HashMap<String, String>,
    structs: &HashSet<String>,
) -> Result<String, String> {
    let ci = env
        .get_const(&item.name)
        .ok_or_else(|| "constant not found in environment".to_string())?;
    let name_str = item.name.to_string();
    let lean_name = renames.get(&name_str).cloned().unwrap_or(name_str);
    let mut p = Printer::new(renames, structs);
    let mut ctx: Vec<String> = Vec::new();
    let ty = p.expr(&ci.type_, &mut ctx)?;
    let suffix = level_params_suffix(&ci.level_params);
    let qname = format!("{NAMESPACE}.{}", escape_name(&lean_name));

    match item.kind {
        ItemKind::Axiom => Ok(format!("axiom {qname}{suffix} : {ty}\n")),
        ItemKind::Theorem | ItemKind::Def => {
            let value = ci
                .value
                .as_ref()
                .ok_or_else(|| "valued constant lost its value".to_string())?;
            let v = p.expr(value, &mut ctx)?;
            let kw = if item.kind == ItemKind::Theorem {
                "theorem"
            } else {
                // `noncomputable`: recursor-based bodies have no codegen; this
                // affects compilation only, never kernel checking.
                "noncomputable def"
            };
            let comment = match ci.kind {
                ConstantKind::Opaque => "-- (opaque in Clean)\n",
                _ => "",
            };
            Ok(format!("{comment}{kw} {qname}{suffix} : {ty} :=\n  {v}\n"))
        }
        ItemKind::Inductive | ItemKind::QuotShim => {
            unreachable!("handled by emit_inductive / emit_quot_shim")
        }
    }
}

/// Emit a single-constructor, index-free inductive as a Lean `structure`, so
/// Lean auto-generates positional field accessors (`pf0`, `pf1`, …) that are
/// the same primitive projections Clean's kernel `Proj` nodes denote. The
/// underlying inductive declaration Lean elaborates is identical (same
/// constructor telescope); field names are `pf<i>` to avoid colliding with
/// Clean's own accessor *definitions* (e.g. `Prod.fst`), which are exported
/// separately as defs whose bodies project via `pf<i>`.
fn emit_structure(
    env: &Environment,
    name: &Name,
    renames: &HashMap<String, String>,
    structs: &HashSet<String>,
) -> Result<String, String> {
    let iv = env
        .get_inductive(name)
        .ok_or_else(|| "inductive vanished from environment".to_string())?;
    // Guarded by the structure-likeness check in main; re-assert here.
    if iv.constructor_names.len() != 1 || iv.num_indices != 0 || iv.is_nested {
        return Err("proj target is not structure-like".to_string());
    }
    let mut p = Printer::new(renames, structs);
    let mut ctx: Vec<String> = Vec::new();
    let (binders, rest) = p.telescope(&iv.type_, iv.num_params as usize, &mut ctx, "p_")?;
    let result_ty = p.expr(rest, &mut ctx)?;

    let ind_str = name.to_string();
    let cn = &iv.constructor_names[0];
    let cv = env
        .get_constructor(cn)
        .ok_or_else(|| format!("constructor {cn} missing"))?;
    let cn_str = cn.to_string();
    let short = cn_str
        .strip_prefix(&format!("{ind_str}."))
        .ok_or_else(|| format!("constructor {cn_str} not namespaced under {ind_str}"))?;
    if short.contains('.') {
        return Err(format!("constructor {cn_str} has nested name component"));
    }

    // Peel the ctor telescope: params (bound to the header names), then every
    // remaining Pi binder is a field. Fields may depend on earlier fields —
    // the context carries the field names so later types print them.
    let mut cp = Printer::new(renames, structs);
    cp.next_var = p.next_var;
    let mut cctx: Vec<String> = Vec::new();
    let (_pb, mut crest) = cp.telescope(&cv.type_, cv.num_params as usize, &mut cctx, "p_")?;
    let mut fields = String::new();
    let mut nfields = 0usize;
    while let ExprKind::Pi(_, ty, body) = crest.kind() {
        let t = cp.expr(ty, &mut cctx)?;
        fields.push_str(&format!("\n  pf{nfields} : {t}"));
        cctx.push(format!("pf{nfields}"));
        crest = body;
        nfields += 1;
    }
    if nfields == 0 {
        // A zero-field type can never be a Proj target; keep the plain form.
        return emit_inductive(env, name, renames, structs);
    }

    Ok(format!(
        "structure {NAMESPACE}.{}{}{} : {} where\n  {} ::{}\n",
        escape_name(&ind_str),
        level_params_suffix(&iv.level_params),
        binders,
        result_ty,
        escape_name(short),
        fields
    ))
}

/// Emit the Quot family as a visible adapter block over Lean core's built-in
/// quotient primitives instead of opaque `axiom`s. Clean's kernel implements
/// `Quot`/`Quot.mk`/`Quot.lift`/`Quot.ind` with the same types and the same
/// computation rule (`Quot.lift f h (Quot.mk r a) ≡ f a`) as Lean's kernel
/// (`crates/clean-kernel/src/quot.rs`, mirroring lean4 `src/kernel/quot.cpp`);
/// an `axiom` cannot carry a computation rule, so mapping onto Lean's own
/// primitives is what lets Lean re-check the Quot-backed towers (Rat, NNReal,
/// …) rather than skipping them. `Quot.sound` stays an explicit axiom.
/// The TYPE of each shim is still printed from Clean's stored elaborated type
/// (fidelity contract); only the VALUE is the adapter. The mirror-Eq adapter
/// `mirrorEqToCore` converts `CleanVerify.Eq` (the exported mirror inductive)
/// to Lean's `Eq` where `Quot.lift`'s respect-obligation meets Lean's.
fn emit_quot_shim(
    env: &Environment,
    item: &Item,
    renames: &HashMap<String, String>,
    structs: &HashSet<String>,
) -> Result<String, String> {
    let ci = env
        .get_const(&item.name)
        .ok_or_else(|| "constant not found in environment".to_string())?;
    let mut p = Printer::new(renames, structs);
    let mut ctx: Vec<String> = Vec::new();
    let ty = p.expr(&ci.type_, &mut ctx)?;
    let suffix = level_params_suffix(&ci.level_params);
    let name_str = item.name.to_string();
    let qname = format!("{NAMESPACE}.{}", escape_name(&name_str));

    let (pre, value): (&str, &str) = match name_str.as_str() {
        "Quot" => (
            "-- ==== Quot family: adapter block onto Lean core's built-in quotient ====\n\
             -- Same types + same computation rule as Clean's kernel primitives\n\
             -- (clean-kernel/src/quot.rs); defs (not axioms) so Lean's own kernel\n\
             -- supplies `Quot.lift f h (Quot.mk r a) ≡ f a`. Quot.sound stays an axiom.\n",
            "fun a r => @_root_.Quot a r",
        ),
        "Quot.mk" => ("", "fun a r x => @_root_.Quot.mk a r x"),
        "Quot.lift" => (
            // The mirror-Eq -> core-Eq adapter, needed exactly here.
            "noncomputable def CleanVerify.mirrorEqToCore.{u} : (a : Sort u) -> ((x : a) -> ((y : a) -> ((@CleanVerify.Eq a x y) -> (@_root_.Eq a x y)))) :=\n  \
             fun a x y h => @CleanVerify.Eq.rec a x (fun z _hz => @_root_.Eq a x z) (@_root_.Eq.refl a x) y h\n\n",
            "fun a r b f h q => @_root_.Quot.lift a r b f (fun x y hr => CleanVerify.mirrorEqToCore b (f x) (f y) (h x y hr)) q",
        ),
        "Quot.ind" => ("", "fun a r m h q => @_root_.Quot.ind a r m h q"),
        other => return Err(format!("unexpected Quot-shim item {other}")),
    };
    Ok(format!(
        "{pre}noncomputable def {qname}{suffix} : {ty} :=\n  {value}\n"
    ))
}
