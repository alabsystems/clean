fn refused(k: &mut ReferenceKernel, d: Declaration, what: &str) {
    let e = k
        .add_checked(d)
        .expect_err(&format!("{what} must be refused"));
    assert!(
        matches!(e, ReferenceRefusal::Kernel(_)),
        "{what}: got {e:?}"
    );
}

fn accepted(k: &mut ReferenceKernel, d: Declaration, what: &str) {
    k.add_checked(d)
        .unwrap_or_else(|e| panic!("control: {what} must be accepted, got {e:?}"));
}

/// `@Eq Bool lhs rhs` → (`@Eq`, `Bool`, `lhs`, `rhs`).
fn eq_parts(e: &Expr, what: &str) -> (Expr, Expr, Expr, Expr) {
    match e.get_app_args().as_slice() {
        [ty, lhs, rhs] => (
            e.get_app_fn().clone(),
            (*ty).clone(),
            (*lhs).clone(),
            (*rhs).clone(),
        ),
        other => panic!("{what} is `@Eq _ lhs rhs`, got {other:?}"),
    }
}

/// `f a₀ … aₙ` with argument `i` replaced.
fn with_arg(e: &Expr, i: usize, new: Expr) -> Expr {
    let mut args: Vec<Expr> = e.get_app_args().into_iter().cloned().collect();
    assert!(i < args.len(), "argument {i} of {e:?}");
    args[i] = new;
    Expr::apps(e.get_app_fn().clone(), args)
}

/// The kernel declarations a compiled module makes, read off its own `.olean`,
/// each with its declared safety, and the number of compiler-only names. A
/// split module is refused (its private part would go unread).
fn module_constants(
    family_dir: &Path,
    module: &str,
) -> (Vec<(Name, Option<DefinitionSafety>)>, usize) {
    let path = family_dir.join(format!("{module}.olean"));
    for part in ["olean.private", "olean.server"] {
        let sibling = family_dir.join(format!("{module}.{part}"));
        assert!(
            !sibling.exists(),
            "{} exists: a split module",
            sibling.display()
        );
    }
    let bytes = std::fs::read(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let parsed = parse_module(&bytes).unwrap_or_else(|e| panic!("parse {}: {e}", path.display()));
    let listed: BTreeSet<&str> = parsed.const_names.iter().map(String::as_str).collect();
    let carried: BTreeSet<&str> = parsed.constants.iter().map(|c| c.name.as_str()).collect();
    assert_eq!(listed, carried, "{module}: constNames and constants agree");
    let decls = parsed
        .constants
        .iter()
        .map(|c| (n(&c.name), c.definition_safety))
        .collect();
    (decls, parsed.extra_const_names.len())
}

