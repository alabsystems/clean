// Dependency Ordering
// ════════════════════════════════════════════════════════════════════════════

/// An item to formalize, with metadata for dependency ordering.
#[derive(Clone, Debug)]
pub(crate) struct OrderableItem {
    pub kind: String,
    pub label: String,
    pub ref_label: String,
    pub latex: String,
    pub proof_latex: String,
    pub dependencies: Vec<String>,
}

/// Order items by dependencies: definitions first (in dependency order), then theorems.
#[must_use]
pub(crate) fn order_by_dependencies(items: &[OrderableItem]) -> Vec<usize> {
    use std::collections::{HashMap, HashSet};

    let by_label: HashMap<&str, usize> = items
        .iter()
        .enumerate()
        .filter(|(_, item)| !item.ref_label.is_empty())
        .map(|(i, item)| (item.ref_label.as_str(), i))
        .collect();

    let definitions: Vec<usize> = items
        .iter()
        .enumerate()
        .filter(|(_, item)| item.kind == "definition")
        .map(|(i, _)| i)
        .collect();

    let theorems: Vec<usize> = items
        .iter()
        .enumerate()
        .filter(|(_, item)| item.kind != "definition")
        .map(|(i, _)| i)
        .collect();

    // Topological sort for definitions
    let mut ordered_defs = Vec::new();
    let mut visited = HashSet::new();

    fn visit(
        idx: usize,
        items: &[OrderableItem],
        by_label: &HashMap<&str, usize>,
        visited: &mut HashSet<usize>,
        ordered: &mut Vec<usize>,
    ) {
        if visited.contains(&idx) {
            return;
        }
        visited.insert(idx);
        for dep in &items[idx].dependencies {
            if let Some(&dep_idx) = by_label.get(dep.as_str()) {
                visit(dep_idx, items, by_label, visited, ordered);
            }
        }
        ordered.push(idx);
    }

    for &def_idx in &definitions {
        visit(def_idx, items, &by_label, &mut visited, &mut ordered_defs);
    }

    ordered_defs.extend(theorems);
    ordered_defs
}

