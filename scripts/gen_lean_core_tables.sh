# Regenerate Clean's two tables of Lean 4.8.0 core facts from Lean itself:
#
#   crates/clean-elab/data/lean_core/init_constants_v4.8.0.txt
#       every constant a Lean file with no import line starts with (the names
#       a user declaration cannot take);
#   crates/clean-parser/data/lean_core/keywords_v4.8.0.txt
#       every identifier-shaped token of that file's token table (the
#       spellings that are keywords, never names).
#
# The generator is crates/clean-elab/data/lean_core/DumpLeanCore.lean. Each
# table gets a header with the Lean that ran, the generator's SHA-256, the
# entry count and the entries' SHA-256; `cargo test -p clean-elab
# lean_core_names` checks the digests and regenerates both tables to compare.
#
#   scripts/gen_lean_core_tables.sh          # Lean at CLEAN_LEAN_4_8_0, else elan's v4.8.0
set -eu

LEAN="${CLEAN_LEAN_4_8_0:-$HOME/.elan/toolchains/leanprover--lean4---v4.8.0/bin/lean}"
ROOT=$(cd "$(dirname "$0")/.." && pwd)
GEN="$ROOT/crates/clean-elab/data/lean_core/DumpLeanCore.lean"
CONSTANTS="$ROOT/crates/clean-elab/data/lean_core/init_constants_v4.8.0.txt"
KEYWORDS="$ROOT/crates/clean-parser/data/lean_core/keywords_v4.8.0.txt"

[ -x "$LEAN" ] || { echo "no Lean 4.8.0 at $LEAN (set CLEAN_LEAN_4_8_0)" >&2; exit 1; }
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

meta=$("$LEAN" --run "$GEN" "$tmp/constants" "$tmp/keywords")
case "$meta" in
  "lean 4.8.0 "*) ;;
  *) echo "the generator did not run on Lean 4.8.0: $meta" >&2; exit 1 ;;
esac
gen_sha=$(shasum -a 256 "$GEN" | cut -d' ' -f1)

# write <out> <entries> <description line>...
write() {
  out=$1 entries=$2
  shift 2
  mkdir -p "$(dirname "$out")"
  {
    for line in "$@"; do printf '# %s\n' "$line"; done
    printf '# Generated by scripts/gen_lean_core_tables.sh from\n'
    printf '# crates/clean-elab/data/lean_core/DumpLeanCore.lean; do not edit.\n'
    printf '# lean: %s\n' "${meta#lean }"
    printf '# generator-sha256: %s\n' "$gen_sha"
    printf '# entries: %s\n' "$(wc -l < "$entries" | tr -d ' ')"
    printf '# body-sha256: %s\n' "$(shasum -a 256 "$entries" | cut -d' ' -f1)"
    cat "$entries"
  } > "$out"
}

write "$CONSTANTS" "$tmp/constants" \
  "Every constant of the environment of a Lean 4.8.0 file with no import line" \
  "(importModules #[Init]), one per line: components separated by '.', a" \
  "numeric component as digits, a string component bare or inside «» (see the" \
  "generator). Read by crates/clean-elab/src/lean_core_names.rs."
write "$KEYWORDS" "$tmp/keywords" \
  "Every token of the token table of a Lean 4.8.0 file with no import line" \
  "that is spelled like an identifier (Lean.isIdFirst, then Lean.isIdRest):" \
  "Lean scans such a spelling as the keyword, never as a name. One per line." \
  "Read by crates/clean-parser/src/lean_keywords.rs."
echo "wrote $CONSTANTS and $KEYWORDS ($meta)"
