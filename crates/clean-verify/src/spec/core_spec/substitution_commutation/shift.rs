//! Successor-shift helper lemmas for substitution commutation.

use std::collections::HashSet;

use crate::spec::definition::SpecDefinition;
use crate::spec::error::SpecError;
use crate::spec::types::{AxiomCategory, ProofStatus};
use crate::Specification;

mod witness;

impl Specification {
    pub(super) fn add_substitution_commutation_shift_lemmas(&mut self) -> Result<(), SpecError> {
        // ── Helper: lift_at (bvar i) 0 1 = bvar (i+1) ──
        // Packages the cutoff-0 geq branch together with the concrete n+1 = succ n
        // arithmetic rewrite. Part of #464.
        self.add_definition_structural(SpecDefinition {
            name: "lift_at_bvar_zero_succ".to_string(),
            type_src: "forall (i : Nat), Eq KExpr (lift_at (KExpr.bvar i) Nat.zero (Nat.succ Nat.zero)) (KExpr.bvar (Nat.succ i))".to_string(),
            value_src: Some(concat!(
                "fun (i : Nat) => ",
                "Eq.trans KExpr ",
                "(lift_at (KExpr.bvar i) Nat.zero (Nat.succ Nat.zero)) ",
                "(KExpr.bvar (Nat.add i (Nat.succ Nat.zero))) ",
                "(KExpr.bvar (Nat.succ i)) ",
                "(lift_at_bvar_geq i Nat.zero (Nat.succ Nat.zero) ",
                "(nat_sub_zero_left i)) ",
                "(Eq.cong Nat KExpr KExpr.bvar ",
                "(Nat.add i (Nat.succ Nat.zero)) ",
                "(Nat.succ i) ",
                "(nat_add_succ_zero i))",
            ).to_string()),
            is_axiom: false,
            description: "lift_at (bvar i) 0 1 = bvar (succ i). DerivedProved via lift_at_bvar_geq at cutoff 0 plus nat_add_succ_zero. Part of #464.".to_string(),
            category: AxiomCategory::DerivedLemma,
            proof_status: ProofStatus::DerivedProved,
            elaborated_type: None,
            elaborated_value: None,
            dependencies: Some(HashSet::from([
                "Eq.cong".to_string(),
                "Eq.trans".to_string(),
                "lift_at_bvar_geq".to_string(),
                "nat_add_succ_zero".to_string(),
                "nat_sub_zero_left".to_string(),
            ])),
            axiom_deps: HashSet::new(),
        })?;

        // ── Boundary case: shifting the equality branch by one binder ──
        // This is the i = depth + 1 frontier that the generalized nested bvar
        // theorem will need when threading the "equal after one shift" case.
        // Part of #461, #464.
        self.add_definition_structural(SpecDefinition {
            name: "instantiate_at_bvar_succ_eq_shift".to_string(),
            type_src: concat!(
                "forall (depth : Nat) (val : KExpr), ",
                "Eq KExpr ",
                "(instantiate_at (KExpr.bvar (Nat.add (Nat.succ Nat.zero) depth)) val (Nat.succ depth)) ",
                "(lift_at (instantiate_at (KExpr.bvar depth) val depth) Nat.zero (Nat.succ Nat.zero))",
            ).to_string(),
            value_src: Some(concat!(
                "fun (depth : Nat) (val : KExpr) => ",
                "Eq.trans KExpr ",
                "(instantiate_at (KExpr.bvar (Nat.add (Nat.succ Nat.zero) depth)) val (Nat.succ depth)) ",
                "(instantiate_at (KExpr.bvar (Nat.succ depth)) val (Nat.succ depth)) ",
                "(lift_at (instantiate_at (KExpr.bvar depth) val depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(Eq.cong Nat KExpr ",
                "(fun (idx : Nat) => instantiate_at (KExpr.bvar idx) val (Nat.succ depth)) ",
                "(Nat.add (Nat.succ Nat.zero) depth) ",
                "(Nat.succ depth) ",
                "(Eq.trans Nat ",
                "(Nat.add (Nat.succ Nat.zero) depth) ",
                "(Nat.succ (Nat.add Nat.zero depth)) ",
                "(Nat.succ depth) ",
                "(nat_succ_add Nat.zero depth) ",
                "(Eq.cong Nat Nat Nat.succ ",
                "(Nat.add Nat.zero depth) ",
                "depth ",
                "(nat_add_zero depth)))) ",
                "(Eq.trans KExpr ",
                "(instantiate_at (KExpr.bvar (Nat.succ depth)) val (Nat.succ depth)) ",
                "(lift_at val Nat.zero (Nat.succ depth)) ",
                "(lift_at (instantiate_at (KExpr.bvar depth) val depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(Eq.trans KExpr ",
                "(instantiate_at (KExpr.bvar (Nat.succ depth)) val (Nat.succ depth)) ",
                "(instantiate_bvar_at (Nat.succ depth) (Nat.succ depth) val) ",
                "(lift_at val Nat.zero (Nat.succ depth)) ",
                "(instantiate_at_bvar (Nat.succ depth) val (Nat.succ depth)) ",
                "(instantiate_bvar_at_eq (Nat.succ depth) val)) ",
                "(Eq.trans KExpr ",
                "(lift_at val Nat.zero (Nat.succ depth)) ",
                "(lift_at (lift_at val Nat.zero depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(lift_at (instantiate_at (KExpr.bvar depth) val depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(Eq.symm KExpr ",
                "(lift_at (lift_at val Nat.zero depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(lift_at val Nat.zero (Nat.succ depth)) ",
                "(Eq.trans KExpr ",
                "(lift_at (lift_at val Nat.zero depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(lift_at val Nat.zero (Nat.add depth (Nat.succ Nat.zero))) ",
                "(lift_at val Nat.zero (Nat.succ depth)) ",
                "(lift_at_compose val Nat.zero depth (Nat.succ Nat.zero)) ",
                "(Eq.cong Nat KExpr ",
                "(fun (amount : Nat) => lift_at val Nat.zero amount) ",
                "(Nat.add depth (Nat.succ Nat.zero)) ",
                "(Nat.succ depth) ",
                "(nat_add_succ_zero depth)))) ",
                "(Eq.symm KExpr ",
                "(lift_at (instantiate_at (KExpr.bvar depth) val depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(lift_at (lift_at val Nat.zero depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(Eq.cong KExpr KExpr ",
                "(fun (x : KExpr) => lift_at x Nat.zero (Nat.succ Nat.zero)) ",
                "(instantiate_at (KExpr.bvar depth) val depth) ",
                "(lift_at val Nat.zero depth) ",
                "(Eq.trans KExpr ",
                "(instantiate_at (KExpr.bvar depth) val depth) ",
                "(instantiate_bvar_at depth depth val) ",
                "(lift_at val Nat.zero depth) ",
                "(instantiate_at_bvar depth val depth) ",
                "(instantiate_bvar_at_eq depth val))))))",
            ).to_string()),
            is_axiom: false,
            description: "Boundary shift case: substituting at depth succ d on bvar (1 + d) equals lifting the depth-d equality case by one. DerivedProved via instantiate_bvar_at_eq and lift_at_compose. Part of #461, #464.".to_string(),
            category: AxiomCategory::DerivedLemma,
            proof_status: ProofStatus::DerivedProved,
            elaborated_type: None,
            elaborated_value: None,
            dependencies: Some(HashSet::from([
                "Eq.cong".to_string(),
                "Eq.symm".to_string(),
                "Eq.trans".to_string(),
                "instantiate_at_bvar".to_string(),
                "instantiate_bvar_at_eq".to_string(),
                "lift_at_compose".to_string(),
                "nat_add_succ_zero".to_string(),
                "nat_add_zero".to_string(),
                "nat_succ_add".to_string(),
            ])),
            axiom_deps: HashSet::new(),
        })?;

        self.add_substitution_commutation_shift_witness_lemmas()?;

        // ── Strict-above case: shifting the above branch by one binder ──
        // Routes through bvar(add (succ j) depth) as midpoint. LHS reduces via
        // instantiate_bvar_at_above + arithmetic; RHS reduces via the new
        // instantiate_at_bvar_add_succ_reduces helper + lift_at_bvar_zero_succ.
        // Part of #461, #464.
        self.add_definition_structural(SpecDefinition {
            name: "instantiate_at_bvar_succ_above_shift".to_string(),
            type_src: concat!(
                "forall (depth : Nat) (j : Nat) (val : KExpr), ",
                "Eq KExpr ",
                "(instantiate_at (KExpr.bvar (Nat.add (Nat.succ (Nat.succ j)) depth)) val (Nat.succ depth)) ",
                "(lift_at (instantiate_at (KExpr.bvar (Nat.add (Nat.succ j) depth)) val depth) Nat.zero (Nat.succ Nat.zero))",
            )
            .to_string(),
            value_src: Some(concat!(
                "fun (depth : Nat) (j : Nat) (val : KExpr) => ",
                // Outer: LHS → bvar(add (succ j) depth) → RHS
                "Eq.trans KExpr ",
                "(instantiate_at (KExpr.bvar (Nat.add (Nat.succ (Nat.succ j)) depth)) val (Nat.succ depth)) ",
                "(KExpr.bvar (Nat.add (Nat.succ j) depth)) ",
                "(lift_at (instantiate_at (KExpr.bvar (Nat.add (Nat.succ j) depth)) val depth) Nat.zero (Nat.succ Nat.zero)) ",
                // ── PROOF1: LHS = bvar(add (succ j) depth) ──
                "(Eq.trans KExpr ",
                "(instantiate_at (KExpr.bvar (Nat.add (Nat.succ (Nat.succ j)) depth)) val (Nat.succ depth)) ",
                "(KExpr.bvar (Nat.sub (Nat.add (Nat.succ (Nat.succ j)) depth) (Nat.succ Nat.zero))) ",
                "(KExpr.bvar (Nat.add (Nat.succ j) depth)) ",
                // proof1a: via instantiate_at_bvar + instantiate_bvar_at_above
                "(Eq.trans KExpr ",
                "(instantiate_at (KExpr.bvar (Nat.add (Nat.succ (Nat.succ j)) depth)) val (Nat.succ depth)) ",
                "(instantiate_bvar_at (Nat.add (Nat.succ (Nat.succ j)) depth) (Nat.succ depth) val) ",
                "(KExpr.bvar (Nat.sub (Nat.add (Nat.succ (Nat.succ j)) depth) (Nat.succ Nat.zero))) ",
                "(instantiate_at_bvar (Nat.add (Nat.succ (Nat.succ j)) depth) val (Nat.succ depth)) ",
                "(instantiate_bvar_at_above (Nat.add (Nat.succ (Nat.succ j)) depth) (Nat.succ depth) val ",
                // H1: sub (succ depth) (add (ss j) depth) = 0
                "(Eq.trans Nat ",
                "(Nat.sub (Nat.succ depth) (Nat.add (Nat.succ (Nat.succ j)) depth)) ",
                "(Nat.sub (Nat.add (Nat.succ Nat.zero) depth) (Nat.add (Nat.succ (Nat.succ j)) depth)) ",
                "Nat.zero ",
                "(Eq.cong Nat Nat ",
                "(fun (x : Nat) => Nat.sub x (Nat.add (Nat.succ (Nat.succ j)) depth)) ",
                "(Nat.succ depth) ",
                "(Nat.add (Nat.succ Nat.zero) depth) ",
                "(Eq.symm Nat ",
                "(Nat.add (Nat.succ Nat.zero) depth) ",
                "(Nat.succ depth) ",
                "(Eq.trans Nat ",
                "(Nat.add (Nat.succ Nat.zero) depth) ",
                "(Nat.succ (Nat.add Nat.zero depth)) ",
                "(Nat.succ depth) ",
                "(nat_succ_add Nat.zero depth) ",
                "(Eq.cong Nat Nat Nat.succ (Nat.add Nat.zero depth) depth (nat_add_zero depth))))) ",
                "(nat_sub_zero_add_same_right (Nat.succ Nat.zero) (Nat.succ (Nat.succ j)) depth ",
                "(Eq.trans Nat ",
                "(Nat.sub (Nat.succ Nat.zero) (Nat.succ (Nat.succ j))) ",
                "(Nat.sub Nat.zero (Nat.succ j)) ",
                "Nat.zero ",
                "(nat_sub_succ_succ Nat.zero (Nat.succ j)) ",
                "(nat_sub_zero_left (Nat.succ j))))) ",
                // H2: sub (add (ss j) depth) (succ depth) = succ(...)
                "(Eq.trans Nat ",
                "(Nat.sub (Nat.add (Nat.succ (Nat.succ j)) depth) (Nat.succ depth)) ",
                "(Nat.sub (Nat.add (Nat.succ (Nat.succ j)) depth) (Nat.add (Nat.succ Nat.zero) depth)) ",
                "(Nat.succ (Nat.sub (Nat.sub (Nat.add (Nat.succ (Nat.succ j)) depth) (Nat.succ depth)) (Nat.succ Nat.zero))) ",
                "(Eq.cong Nat Nat ",
                "(fun (x : Nat) => Nat.sub (Nat.add (Nat.succ (Nat.succ j)) depth) x) ",
                "(Nat.succ depth) ",
                "(Nat.add (Nat.succ Nat.zero) depth) ",
                "(Eq.symm Nat ",
                "(Nat.add (Nat.succ Nat.zero) depth) ",
                "(Nat.succ depth) ",
                "(Eq.trans Nat ",
                "(Nat.add (Nat.succ Nat.zero) depth) ",
                "(Nat.succ (Nat.add Nat.zero depth)) ",
                "(Nat.succ depth) ",
                "(nat_succ_add Nat.zero depth) ",
                "(Eq.cong Nat Nat Nat.succ (Nat.add Nat.zero depth) depth (nat_add_zero depth))))) ",
                "(Eq.trans Nat ",
                "(Nat.sub (Nat.add (Nat.succ (Nat.succ j)) depth) (Nat.add (Nat.succ Nat.zero) depth)) ",
                "(Nat.succ (Nat.sub (Nat.sub (Nat.add (Nat.succ (Nat.succ j)) depth) (Nat.add (Nat.succ Nat.zero) depth)) (Nat.succ Nat.zero))) ",
                "(Nat.succ (Nat.sub (Nat.sub (Nat.add (Nat.succ (Nat.succ j)) depth) (Nat.succ depth)) (Nat.succ Nat.zero))) ",
                "(nat_sub_pos_add_same_right (Nat.succ (Nat.succ j)) (Nat.succ Nat.zero) depth ",
                "(nat_sub_pos_witness (Nat.succ Nat.zero) (Nat.succ j) ",
                "(Eq.trans Nat ",
                "(Nat.sub (Nat.succ Nat.zero) (Nat.succ j)) ",
                "(Nat.sub Nat.zero j) ",
                "Nat.zero ",
                "(nat_sub_succ_succ Nat.zero j) ",
                "(nat_sub_zero_left j)))) ",
                "(Eq.cong Nat Nat ",
                "(fun (x : Nat) => Nat.succ (Nat.sub (Nat.sub (Nat.add (Nat.succ (Nat.succ j)) depth) x) (Nat.succ Nat.zero))) ",
                "(Nat.add (Nat.succ Nat.zero) depth) ",
                "(Nat.succ depth) ",
                "(Eq.trans Nat ",
                "(Nat.add (Nat.succ Nat.zero) depth) ",
                "(Nat.succ (Nat.add Nat.zero depth)) ",
                "(Nat.succ depth) ",
                "(nat_succ_add Nat.zero depth) ",
                "(Eq.cong Nat Nat Nat.succ (Nat.add Nat.zero depth) depth (nat_add_zero depth)))))))) ",
                // proof1b: bvar(sub idx1 1) = bvar(add (succ j) depth)
                "(Eq.cong Nat KExpr KExpr.bvar ",
                "(Nat.sub (Nat.add (Nat.succ (Nat.succ j)) depth) (Nat.succ Nat.zero)) ",
                "(Nat.add (Nat.succ j) depth) ",
                "(Eq.trans Nat ",
                "(Nat.sub (Nat.add (Nat.succ (Nat.succ j)) depth) (Nat.succ Nat.zero)) ",
                "(Nat.sub (Nat.succ (Nat.add (Nat.succ j) depth)) (Nat.succ Nat.zero)) ",
                "(Nat.add (Nat.succ j) depth) ",
                "(Eq.cong Nat Nat ",
                "(fun (x : Nat) => Nat.sub x (Nat.succ Nat.zero)) ",
                "(Nat.add (Nat.succ (Nat.succ j)) depth) ",
                "(Nat.succ (Nat.add (Nat.succ j) depth)) ",
                "(nat_succ_add (Nat.succ j) depth)) ",
                "(nat_sub_succ_one (Nat.add (Nat.succ j) depth))))) ",
                // ── PROOF2: bvar(add (succ j) depth) = RHS ──
                "(Eq.symm KExpr ",
                "(lift_at (instantiate_at (KExpr.bvar (Nat.add (Nat.succ j) depth)) val depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(KExpr.bvar (Nat.add (Nat.succ j) depth)) ",
                "(Eq.trans KExpr ",
                "(lift_at (instantiate_at (KExpr.bvar (Nat.add (Nat.succ j) depth)) val depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(lift_at (KExpr.bvar (Nat.add j depth)) Nat.zero (Nat.succ Nat.zero)) ",
                "(KExpr.bvar (Nat.add (Nat.succ j) depth)) ",
                "(Eq.cong KExpr KExpr ",
                "(fun (x : KExpr) => lift_at x Nat.zero (Nat.succ Nat.zero)) ",
                "(instantiate_at (KExpr.bvar (Nat.add (Nat.succ j) depth)) val depth) ",
                "(KExpr.bvar (Nat.add j depth)) ",
                "(instantiate_at_bvar_add_succ_reduces j depth val)) ",
                "(Eq.trans KExpr ",
                "(lift_at (KExpr.bvar (Nat.add j depth)) Nat.zero (Nat.succ Nat.zero)) ",
                "(KExpr.bvar (Nat.succ (Nat.add j depth))) ",
                "(KExpr.bvar (Nat.add (Nat.succ j) depth)) ",
                "(lift_at_bvar_zero_succ (Nat.add j depth)) ",
                "(Eq.cong Nat KExpr KExpr.bvar ",
                "(Nat.succ (Nat.add j depth)) ",
                "(Nat.add (Nat.succ j) depth) ",
                "(Eq.symm Nat ",
                "(Nat.add (Nat.succ j) depth) ",
                "(Nat.succ (Nat.add j depth)) ",
                "(nat_succ_add j depth))))))",
            ).to_string()),
            is_axiom: false,
            description: "Strict-above successor-shift case. DerivedProved via instantiate_bvar_at_above on the LHS, instantiate_at_bvar_add_succ_reduces on the RHS, with arithmetic transport via nat_succ_add and nat_sub_succ_one. Part of #461, #464.".to_string(),
            category: AxiomCategory::DerivedLemma,
            proof_status: ProofStatus::DerivedProved,
            elaborated_type: None,
            elaborated_value: None,
            dependencies: Some(HashSet::from([
                "Eq.cong".to_string(),
                "Eq.symm".to_string(),
                "Eq.trans".to_string(),
                "instantiate_at_bvar".to_string(),
                "instantiate_at_bvar_add_succ_reduces".to_string(),
                "instantiate_bvar_at_above".to_string(),
                "lift_at_bvar_zero_succ".to_string(),
                "nat_add_zero".to_string(),
                "nat_sub_pos_add_same_right".to_string(),
                "nat_sub_pos_witness".to_string(),
                "nat_sub_succ_one".to_string(),
                "nat_sub_succ_succ".to_string(),
                "nat_sub_zero_add_same_right".to_string(),
                "nat_sub_zero_left".to_string(),
                "nat_succ_add".to_string(),
            ])),
            axiom_deps: HashSet::new(),
        })?;

        // ── Gap-indexed successor transport for at/above-depth bvars ──
        // Packages the equality and strict-above branches behind one Nat.rec
        // wrapper so downstream proofs can consume a single shifted-gap API.
        // Part of #461, #464.
        self.add_definition_structural(SpecDefinition {
            name: "instantiate_at_bvar_succ_gap_shift".to_string(),
            type_src: concat!(
                "forall (depth : Nat) (gap : Nat) (val : KExpr), ",
                "Eq KExpr ",
                "(instantiate_at (KExpr.bvar (Nat.add (Nat.succ gap) depth)) val (Nat.succ depth)) ",
                "(lift_at (instantiate_at (KExpr.bvar (Nat.add gap depth)) val depth) Nat.zero (Nat.succ Nat.zero))",
            )
            .to_string(),
            value_src: Some(concat!(
                "fun (depth : Nat) (gap : Nat) (val : KExpr) => ",
                "Nat.rec ",
                "(fun (k : Nat) => ",
                "Eq KExpr ",
                "(instantiate_at (KExpr.bvar (Nat.add (Nat.succ k) depth)) val (Nat.succ depth)) ",
                "(lift_at (instantiate_at (KExpr.bvar (Nat.add k depth)) val depth) Nat.zero (Nat.succ Nat.zero))) ",
                "(Eq.trans KExpr ",
                "(instantiate_at (KExpr.bvar (Nat.add (Nat.succ Nat.zero) depth)) val (Nat.succ depth)) ",
                "(lift_at (instantiate_at (KExpr.bvar depth) val depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(lift_at (instantiate_at (KExpr.bvar (Nat.add Nat.zero depth)) val depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(instantiate_at_bvar_succ_eq_shift depth val) ",
                "(Eq.cong KExpr KExpr ",
                "(fun (x : KExpr) => lift_at (instantiate_at x val depth) Nat.zero (Nat.succ Nat.zero)) ",
                "(KExpr.bvar depth) ",
                "(KExpr.bvar (Nat.add Nat.zero depth)) ",
                "(Eq.cong Nat KExpr KExpr.bvar depth (Nat.add Nat.zero depth) ",
                "(Eq.symm Nat (Nat.add Nat.zero depth) depth (nat_add_zero depth))))) ",
                "(fun (j : Nat) ",
                "(_ : Eq KExpr ",
                "(instantiate_at (KExpr.bvar (Nat.add (Nat.succ j) depth)) val (Nat.succ depth)) ",
                "(lift_at (instantiate_at (KExpr.bvar (Nat.add j depth)) val depth) Nat.zero (Nat.succ Nat.zero))) => ",
                "instantiate_at_bvar_succ_above_shift depth j val) ",
                "gap",
            ).to_string()),
            is_axiom: false,
            description: "Gap-indexed successor transport for bvars at or above the substitution depth. DerivedProved by Nat.rec on the gap, using instantiate_at_bvar_succ_eq_shift for the boundary case and instantiate_at_bvar_succ_above_shift for strict-above successors. Part of #461, #464.".to_string(),
            category: AxiomCategory::DerivedLemma,
            proof_status: ProofStatus::DerivedProved,
            elaborated_type: None,
            elaborated_value: None,
            dependencies: Some(HashSet::from([
                "Eq.cong".to_string(),
                "Eq.symm".to_string(),
                "Eq.trans".to_string(),
                "Nat.rec".to_string(),
                "instantiate_at_bvar_succ_above_shift".to_string(),
                "instantiate_at_bvar_succ_eq_shift".to_string(),
                "nat_add_zero".to_string(),
            ])),
            axiom_deps: HashSet::new(),
        })?;

        Ok(())
    }
}
