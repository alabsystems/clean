//! Dafny program verification importer (Boogie VCs → SMT cert replay).
//!
//! Dafny compiles programs to Boogie intermediate verification language, which
//! generates verification conditions (VCs) discharged by an SMT solver (Z3).
//! This module imports Boogie VCs and Dafny verification results into the
//! Mathverse trust framework.
//!
//! Trust model:
//! - Unverified VCs: `SMT_ORACLE` axiom profile, `TrustedOracle` trust level
//! - Certificate-replayed VCs: `SAT_CERT` axiom profile, `CertificateReplayed`

use serde::{Deserialize, Serialize};
use thiserror::Error;

use crate::types::{AxiomProfile, Provenance, SourceSystem, TrustLevel};

