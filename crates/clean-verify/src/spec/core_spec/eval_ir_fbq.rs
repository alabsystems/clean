//! `reduce_float_beq::{closure#0}` as EvalIR — the first chained body whose
//! emitted instruction is an `fcmp`.
//!
//! Read `eval_ir_float_add.rs` first: this is its COMPARISON twin. Same three
//! parameters (`ptr`, `f64`, `f64`), same empty aggregate lanes, same two-node
//! shape. What differs is the instruction and the RESULT TYPE — an `fcmp`
//! answers a `bool`, so this module is the first minted one whose `ret` carries
//! `IRScalar.bool_`.
//!
//! **What this chain is worth, so it cannot inflate.** `fcmp` already has
//! battery rows from the W4 SYNTHETIC lane, which covers all twelve `FCmpOp`
//! predicates over authored micro-modules. This adds NOTHING to that coverage.
//! It changes the KIND of evidence for one predicate: `oeq` at binary64 is
//! witnessed here by an EMITTED body from the shipped kernel rather than by a
//! module an author wrote. It is not A0-eligible — the body's `derived_mir`
//! verdict is `unsupported` — and it says nothing about `Level::is_zero`.
//!
//! The witnesses below run `ir_eval` on the REGISTERED module, not on
//! `ir_fcmp_eval` directly, so they are executions of this body rather than of
//! the primitive underneath it. The NaN row is the sharp one: `oeq` is an
//! ORDERED comparison, so `NaN == NaN` is FALSE, and a model that treated the
//! predicate as bit equality — or as `ueq`/`une` — answers differently here
//! while agreeing on every ordinary pair.

use crate::spec::SpecError;
use crate::spec::Specification;

/// The minted script, generated by `ir_mint` from `generated/ir_fbq.core.txt`,
/// which reader A projected from the artifact BINARY. Not transcribed.
const MINTED_IR_FBQ: &str = include_str!("generated/ir_fbq.defs.txt");

/// Registration rationales, one per minted line, in script order.
const MINTED_IR_FBQ_DOCS: &[&str] = &[
    "ir_fbq_b0: THE WHOLE BODY, MINTED FROM THE EMITTED ARTIFACT (generated/ir_fbq.core.txt, cut from tests/fixtures/float_beq.trust-ir.txt's body). One `fcmp oeq` at f64 over %1 and %2, then a `ret` of ITS result. The predicate is load-bearing: `oeq` and `une` print as the same shape and are different programs on a NaN operand.",
    "ir_fbq_func: the closure as EvalIR -- THREE parameters (%0 the closure environment pointer, %1 and %2 the operands), entry block 0, one block. %0 is bound and never read: the closure captures nothing.",
    "ir_fbq_module: the module for env::native_reducers_float::reduce_float_beq::{closure#0}, MINTED from the emitted trust-ir rather than transcribed from it. Reader A projected it from the artifact BINARY and the A2 gate re-runs the mint and fails closed against this script. The fixture was WITHDRAWN (def6e2fc0), so reader B no longer reads this body and no two-reader agreement is claimed.",
];

/// The minted script's lines, in registration order — ONE source of truth for
/// the stage below and for anything running the machine on *the registered
/// module* rather than on a second transcription.
static MINTED_IR_FBQ_LINES: std::sync::LazyLock<Vec<&'static str>> =
    std::sync::LazyLock::new(|| {
        MINTED_IR_FBQ
            .lines()
            .map(str::trim)
            .filter(|l| !l.is_empty())
            .collect()
    });

/// The minted `reduce_float_beq::{closure#0}` module definitions, in
/// registration order.
#[must_use]
pub(crate) fn ir_fbq_module_defs() -> &'static [&'static str] {
    &MINTED_IR_FBQ_LINES
}

// ── kernel-EXECUTED witnesses, through the REGISTERED module ──────────
//   1.0        = 0x3FF0000000000000 = 4607182418800017408
//   2.0        = 0x4000000000000000 = 4611686018427387904
//   a quiet NaN= 0x7FF8000000000000 = 9221120237041090560
const SRC_W_EQUAL: &str = "def ir_fbq_equal_operands_answer_true : Eq IROutcome (ir_eval ir_d2 ir_fbq_module ir_d0 (ir_vl3 IRScalar.undef_ (IRScalar.float_ 4607182418800017408) (IRScalar.float_ 4607182418800017408)) ir_mem0 ir_d0) (IROutcome.ret (ir_vl1 (IRScalar.bool_ Bool.true))) := Eq.refl IROutcome (IROutcome.ret (ir_vl1 (IRScalar.bool_ Bool.true)))";
const SRC_W_DISTINCT: &str = "def ir_fbq_distinct_operands_answer_false : Eq IROutcome (ir_eval ir_d2 ir_fbq_module ir_d0 (ir_vl3 IRScalar.undef_ (IRScalar.float_ 4607182418800017408) (IRScalar.float_ 4611686018427387904)) ir_mem0 ir_d0) (IROutcome.ret (ir_vl1 (IRScalar.bool_ Bool.false))) := Eq.refl IROutcome (IROutcome.ret (ir_vl1 (IRScalar.bool_ Bool.false)))";
const SRC_W_NAN: &str = "def ir_fbq_nan_is_not_equal_to_itself : Eq IROutcome (ir_eval ir_d2 ir_fbq_module ir_d0 (ir_vl3 IRScalar.undef_ (IRScalar.float_ 9221120237041090560) (IRScalar.float_ 9221120237041090560)) ir_mem0 ir_d0) (IROutcome.ret (ir_vl1 (IRScalar.bool_ Bool.false))) := Eq.refl IROutcome (IROutcome.ret (ir_vl1 (IRScalar.bool_ Bool.false)))";

impl Specification {
    /// Register the minted `fcmp oeq` module and its executed witnesses.
    ///
    /// # Errors
    /// Returns `SpecError` if a definition fails to elaborate, or if the minted
    /// script's length stops matching the rationale table.
    pub(super) fn add_eval_ir_fbq(&mut self) -> Result<(), SpecError> {
        let minted = ir_fbq_module_defs();
        if minted.len() != MINTED_IR_FBQ_DOCS.len() {
            return Err(SpecError::EnvError(format!(
                "the minted ir_fbq script has {} definitions but {} rationales are declared; \
                 regenerate the docs table with the script rather than reusing it",
                minted.len(),
                MINTED_IR_FBQ_DOCS.len()
            )));
        }
        for (src, doc) in minted.iter().zip(MINTED_IR_FBQ_DOCS) {
            self.add_recursive_def(src, doc)?;
        }
        self.add_recursive_def(
            SRC_W_EQUAL,
            "ir_fbq_equal_operands_answer_true: the machine RUN on the registered module at 1.0 == 1.0. Kernel-executed: the Eq.refl is discharged by REDUCING ir_eval over the minted module, not by asserting a constant.",
        )?;
        self.add_recursive_def(
            SRC_W_DISTINCT,
            "ir_fbq_distinct_operands_answer_false: 1.0 == 2.0 is false. The coverage denominator for the row above -- a module that answered `true` unconditionally would pass that one and fail this.",
        )?;
        self.add_recursive_def(
            SRC_W_NAN,
            "ir_fbq_nan_is_not_equal_to_itself: NaN == NaN is FALSE, because `oeq` is an ORDERED comparison. This is the sharp input of the chain: a model reading the predicate as bit equality answers `true` here and agrees on every ordinary pair, and `ueq`/`une` at the same operands answer differently again.",
        )?;
        Ok(())
    }
}
