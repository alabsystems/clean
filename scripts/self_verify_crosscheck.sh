fail() {
  echo "FAIL: $*" >&2
  echo "  evidence: $WORK" >&2
  exit 1
}

command -v lean >/dev/null 2>&1 || command -v ~/.elan/bin/lean >/dev/null 2>&1 \
  || fail "no lean on PATH (install elan + $TOOLCHAIN)"
LEAN="$(command -v lean || echo "$HOME/.elan/bin/lean")"

# Trust's authenticated frontend must be invoked from its canonical sysroot,
# never through the rustup targo symlink. This is an explicitly unverified
# tooling build; the evidence below is independent Lean replay, not a compiler
# verification claim. Keep the lane separate from ordinary Cargo fingerprints.
SYSROOT="$(trustc --print sysroot)" || fail "cannot resolve pinned Trust sysroot"
TARGO="$SYSROOT/bin/targo"
[ -x "$TARGO" ] || fail "pinned Trust frontend is missing: $TARGO"
export CARGO_TARGET_DIR="${CARGO_TARGET_DIR:-$REPO/target-self-verify}"

echo "==> evidence: $WORK"
echo "==> building lean_export (release, explicit unverified tooling build)"
"$TARGO" --unverified build --locked --release -p clean-verify --bin lean_export >"$BUILDOUT" 2>&1 \
  || { tail -n 40 "$BUILDOUT" >&2; fail "lean_export build failed"; }

# The binary lands wherever cargo put it. Under scripts/verify_runner.py the
# build runs with CARGO_TARGET_DIR pointing OUTSIDE the checkout (the pinned
# worktree has no target/ of its own), and this script used to hardcode
# ./target/release -- so the suite row gate::leancross measured RED with
# "lean_export run failed" (exit 127, binary not found) at a commit whose
# working-tree run had just PASSED. Measured 2026-09-08.
BIN="${CARGO_TARGET_DIR:-$REPO/target}/release/lean_export"
[ -x "$BIN" ] || fail "lean_export binary not found at $BIN (CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-unset})"

echo "==> exporting full live spec -> Lean"
"$BIN" --all-spec --out "$EXPORT" 2>"$SUMMARY" \
  || { tail -n 40 "$SUMMARY" >&2; fail "lean_export run failed"; }

# Invariant 3 — zero skips.
grep -q "skipped: none" "$SUMMARY" || fail "export has skips: $(grep -i skipped "$SUMMARY")"

# Invariant 2 — exactly the 3 foundational axioms.
naxioms="$(sed -n 's/.*explicit axioms in export (\([0-9]*\)):.*/\1/p' "$SUMMARY")"
[ "$naxioms" = "3" ] || fail "expected 3 explicit axioms, got '${naxioms:-?}'"
for ax in propext Quot.sound Classical.choice; do
  grep -qE "^\[lean_export\]   axiom $ax\$" "$SUMMARY" \
    || fail "missing foundational axiom in export: $ax"
done
grep -E "^\[lean_export\]   axiom " "$SUMMARY" | grep -qvE "axiom (propext|Quot\.sound|Classical\.choice)$" \
  && fail "export carries a non-foundational axiom: $(grep 'axiom ' "$SUMMARY")"

# Invariant 4 — 100% spec coverage (direct + via-block == total).
read -r direct viablock total < <(sed -n \
  's/.*coverage: \([0-9]*\) directly + \([0-9]*\) via inductive blocks, of \([0-9]*\) total.*/\1 \2 \3/p' "$SUMMARY")
[ -n "${total:-}" ] || fail "could not parse coverage line"
[ "$((direct + viablock))" = "$total" ] \
  || fail "coverage not 100%: $direct + $viablock != $total"

emitted="$(sed -n 's/.*emitted \([0-9]*\) Lean declarations.*/\1/p' "$SUMMARY")"

echo "==> lean $TOOLCHAIN re-checking $emitted declarations"
"$LEAN" "+$TOOLCHAIN" "$EXPORT" >"$LEANOUT" 2>&1
lexit=$?

# Invariant 1 — report actual Lean rejections before an abnormal exit. Match
# both legacy and modern error diagnostics; a nonzero exit without either
# remains an independently checked abort.
nerr="$(grep -cE 'error(:|\()' "$LEANOUT" || true)"
if [ "$nerr" != "0" ]; then
  head -n 80 "$LEANOUT" >&2
  fail "lean reported $nerr error diagnostic(s) (exit $lexit)"
fi
[ "$lexit" = "0" ] || fail "lean exited $lexit with no error diagnostic (an abort, not a rejection)"

# Lean can return success after admitting an unfinished proof. No declaration
# may acquire that escape hatch, including one outside the flagship closures.
if grep -qE "sorryAx|declaration uses 'sorry'" "$LEANOUT"; then
  fail "independent replay reported an admitted proof"
fi

# Invariant 5 — flagship theorems reach no axiom.
for f in "${FLAGSHIPS[@]}"; do
  grep -qF "'$f' does not depend on any axioms" "$LEANOUT" \
    || fail "flagship '$f' did NOT report a zero-axiom closure"
done

echo ""
echo "PASS — foreign-kernel cross-check green"
echo "  toolchain          : $TOOLCHAIN"
echo "  emitted decls      : $emitted"
echo "  spec coverage      : $direct direct + $viablock via-block = $total (100%)"
echo "  explicit axioms    : 3 (propext, Quot.sound, Classical.choice)"
echo "  skips              : 0"
echo "  lean errors        : 0"
echo "  flagship closures  : ${#FLAGSHIPS[@]} × zero-axiom"
echo "  evidence           : $WORK"
exit 0
