/// Errors raised during Dafny import operations.
#[derive(Debug, Error)]
#[non_exhaustive]
pub enum DafnyError {
    /// Failed to parse a Boogie verification condition.
    #[error("failed to parse Boogie VC: {reason}")]
    ParseError { reason: String },

    /// Error in the Boogie verification condition structure.
    #[error("Boogie VC error in `{vc_name}`: {reason}")]
    BoogieVcError { vc_name: String, reason: String },

    /// Certificate replay failed for a VC.
    #[error("certificate replay failed for `{vc_name}`: {reason}")]
    CertReplayError { vc_name: String, reason: String },

    /// Unsupported Dafny/Boogie feature encountered.
    #[error("unsupported Dafny feature: {feature}")]
    UnsupportedFeature { feature: String },
}

