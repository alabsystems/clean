/// A single attempt to formalize a statement.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct FormalizationAttempt {
    /// Generated Lean 4 code.
    pub lean_code: String,
    /// Whether it type-checks in the clean kernel.
    pub type_checks: bool,
    /// Error message if type-check failed.
    pub error_message: String,
    /// Back-translated natural language (for semantic alignment check).
    pub roundtrip_nl: String,
    /// Semantic similarity score between original and roundtrip (0.0–1.0).
    pub roundtrip_score: f64,
    /// Current admission tier.
    pub tier: AdmissionTier,
}

/// Result of formalizing one extracted statement.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct FormalizationResult {
    /// Source paper ID.
    pub paper_id: String,
    /// Statement label (e.g., "Theorem 1").
    pub label: String,
    /// Whether this is a theorem or definition.
    pub kind: String,
    /// Original LaTeX statement.
    pub original_latex: String,
    /// Proof LaTeX (if available).
    pub proof_latex: String,
    /// Labels this statement depends on.
    pub depends_on: Vec<String>,
    /// All formalization attempts, best first.
    pub attempts: Vec<FormalizationAttempt>,
    /// Best successful formalization (empty if none succeeded).
    pub best_lean: String,
    /// Whether any attempt succeeded.
    pub success: bool,
    /// Highest admission tier reached.
    pub tier: AdmissionTier,
}

/// Aggregate formalization result for one paper.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct PaperFormalization {
    pub paper_id: String,
    pub title: String,
    pub definitions: Vec<FormalizationResult>,
    pub theorems: Vec<FormalizationResult>,
    pub def_formalized: usize,
    pub def_total: usize,
    pub thm_formalized: usize,
    pub thm_total: usize,
}

