//! Statement formalization pipeline: converts extracted LaTeX statements into
//! clean type expressions with definition-first ordering, concept linking,
//! semantic validation, and quarantine staging.
//!
//! Architecture (addresses AI Model/AI Model review findings):
//!   1. Definition-First Pipeline: formalize definitions before theorems
//!   2. Concept Linking: match NL concepts to Mathlib/Mathverse Library names
//!   3. LLM Formalization: generate candidate clean type expressions
//!   4. Type Check: verify with clean kernel
//!   5. Semantic Validation: roundtrip check, counter-example search
//!   6. Quarantine: staged admission (candidate → audited → verified)

use serde::{Deserialize, Serialize};

use super::formalize_prompt::{
    ANTI_HALLUCINATION_PROMPT, FAILURE_PATTERNS_PROMPT, KNOWN_TYPES_PROMPT,
    LEAN4_INIT_TYPES_PROMPT, RULES_PROMPT,
};

// ════════════════════════════════════════════════════════════════════════════
// Admission Tiers (quarantine staging)
// ════════════════════════════════════════════════════════════════════════════

/// Admission tier for formalized statements. Formalizations progress through
/// these tiers as they pass additional validation gates.
#[derive(Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[non_exhaustive]
pub enum AdmissionTier {
    /// Just generated by LLM. May or may not type-check.
    Candidate,
    /// Type-checks in clean kernel.
    TypeChecked,
    /// Passed semantic alignment validation (roundtrip + counter-example).
    AuditedAlignment,
    /// Fully kernel-proved (proof term verified, not just type signature).
    KernelProved,
}

