/// A single Boogie verification condition extracted from Dafny compilation.
///
/// Each VC corresponds to one proof obligation generated by the Boogie pipeline
/// (e.g., a precondition check, postcondition check, loop invariant, or
/// termination proof).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[non_exhaustive]
pub struct DafnyVerificationCondition {
    /// VC identifier (typically `<method>::<check_kind>::<index>`).
    pub name: String,
    /// Dafny method or function this VC belongs to.
    pub method_name: String,
    /// Source `.dfy` file path, if known.
    pub source_file: Option<String>,
    /// Source line number, if known.
    pub source_line: Option<u32>,
    /// The VC assertion in SMT-LIB2 format.
    pub assertion: String,
}

/// Result of importing a Dafny verification session.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[non_exhaustive]
pub struct DafnyImportResult {
    /// Name of the Dafny module or file imported.
    pub name: String,
    /// Total number of verification conditions.
    pub vc_count: usize,
    /// Number of VCs successfully verified.
    pub verified_count: usize,
    /// Axiom profile for the imported result.
    pub axiom_profile: AxiomProfile,
    /// Trust level assigned to the imported result.
    pub trust_level: TrustLevel,
    /// Provenance record for the import.
    pub provenance: Provenance,
    /// Diagnostic messages from the import process.
    pub diagnostics: Vec<String>,
}

