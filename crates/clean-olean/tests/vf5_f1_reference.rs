/// Measured 2026-10-27 in `--release`; the unoptimized replay of the cone is far
/// slower, so a debug run skips it unless `--ignored` asks.
#[test]
#[cfg_attr(
    debug_assertions,
    ignore = "unoptimized replay of the cone takes many minutes; run with --release or --ignored"
)]
fn vf5_theorems_are_admitted_through_the_entry_with_closure_in_ax0() {
    let lib = pinned_lib();
    let dir = compiled_fixture_dir(FAMILY);
    check_pinned_axiom_expectations(&dir);
    let mut env = Environment::for_lean_replay();
    load_module_with_deps(&mut env, ROOT_MODULE, &[dir.clone(), lib])
        .unwrap_or_else(|e| panic!("load {ROOT_MODULE}: {e}"));

    // ── Every constant the family declares, through the entry from EMPTY. ──
    let mut declared: BTreeSet<Name> = BTreeSet::new();
    let mut violations: Vec<String> = Vec::new();
    let (mut unsafe_aux, mut compiler_names) = (0usize, 0usize);
    for module in MODULES {
        let (decls, extra) = module_constants(&dir, module);
        compiler_names += extra;
        for (name, safety) in decls {
            match safety {
                Some(DefinitionSafety::Unsafe | DefinitionSafety::Partial) => {
                    if name.to_string().ends_with("._unsafe_rec") {
                        unsafe_aux += 1;
                    } else {
                        violations.push(format!(
                            "{name}: is a {safety:?} declaration that is not a compiler twin"
                        ));
                    }
                }
                _ => {
                    declared.insert(name);
                }
            }
        }
    }
    let started = Instant::now();
    let built =
        reference_base_closed(&env, &declared, &ClosedRecheckOptions::default()).expect("start");
    let replay = started.elapsed();
    if !built.report.passed() {
        violations.push(format!("replay: {}", built.report.verdict_sentence()));
    }
    for (unit, refusal) in &built.entry_refusals {
        violations.push(format!("{unit}: refused by the entry: {refusal:?}"));
    }
    let ax0: BTreeSet<String> = AX0.iter().map(|s| (*s).to_string()).collect();
    {
        let k = built.kernel().environment();
        for name in &declared {
            let present = k.get_const(name).is_some()
                || k.get_inductive(name).is_some()
                || k.get_constructor(name).is_some()
                || k.get_recursor(name).is_some();
            if !present {
                violations.push(format!("{name}: not admitted through the entry"));
                continue;
            }
            if let Some(c) = k.get_const(name) {
                if matches!(c.kind, ConstantKind::Axiom | ConstantKind::Opaque) {
                    violations.push(format!("{name}: is an {:?} constant", c.kind));
                }
            }
            let closure = axioms_of(k, name);
            if !closure.is_subset(&ax0) {
                violations.push(format!("{name}: closure {closure:?} is not ⊆ Ax0"));
            }
            let cone = reach(k, name);
            for bad in NATIVE {
                if cone.contains(&n(bad)) {
                    violations.push(format!("{name}: reaches {bad}"));
                }
            }
        }
    }
    assert!(
        violations.is_empty(),
        "{} audit violation(s):\n  {}",
        violations.len(),
        violations.join("\n  ")
    );
    for (t, _) in EXPECTED {
        assert!(
            built.admitted.contains(&n(t)),
            "{t} was not admitted through the entry"
        );
    }
    for generated in [
        "SemR.decode",
        "SemR.runFunction",
        "VF5.vc",
        "VF5.sx",
        "VF5.checkBlob",
        "ChkLIA.chk_LIA_cases",
    ] {
        assert!(
            built.admitted.contains(&n(generated)),
            "{generated} was not admitted through the entry"
        );
    }
    eprintln!(
        "vf5_f1_reference: {} constants admitted through the entry in {:.1?}; {} declared and \
         audited; set aside: {unsafe_aux} unsafe compiler twins, {compiler_names} compiler names",
        built.admitted.len(),
        replay,
        declared.len()
    );
    let mut k = built.into_kernel().expect("a passing, pinned replay");
    assert_eq!(k.theory_id(), TheoryId::LeanReferenceV1);

    // ── Closures, read from the entry's own environment. ──
    for (t, want) in EXPECTED {
        let got = axioms_of(k.environment(), &n(t));
        let want: BTreeSet<String> = want.iter().map(|s| (*s).to_string()).collect();
        assert_eq!(got, want, "{t}: closure differs from Lean's #print axioms");
        assert!(got.is_subset(&ax0), "{t}: closure {got:?} is not ⊆ Ax0");
    }

    // Every annotated function's precondition has its satisfiability witness, admitted,
    // with closure `{propext}`.
    let pres = pre_witnesses(&family_source());
    assert!(pres.len() >= 5, "the annotated functions: {pres:?}");
    for t in &pres {
        assert!(
            built_admits(&k, t),
            "{t}: an annotated function's witness was not admitted"
        );
        let got = axioms_of(k.environment(), &n(t));
        assert_eq!(
            got,
            PROPEXT
                .iter()
                .map(|s| (*s).to_string())
                .collect::<BTreeSet<_>>(),
            "{t}: closure"
        );
    }

    // The identical body's 64-bit proof cannot certify its 32-bit target.
    let valid64 = type_of(&env, "VF5Spec.width64_valid");
    refused(
        &mut k,
        theorem(
            "VF5Spec.forged_width32_valid",
            with_arg(&valid64, 0, c("VF5Spec.width32Module")),
            value(&env, "VF5Spec.width64_valid"),
        ),
        "a 64-bit usize proof offered for the 32-bit module",
    );
    accepted(
        &mut k,
        theorem(
            "VF5Spec.control_width64_valid",
            valid64,
            value(&env, "VF5Spec.width64_valid"),
        ),
        "the same usize proof at its admitted 64-bit target",
    );

    // ── Control 1: premise-free soundness and composition are refused. ──
    refused(
        &mut k,
        theorem(
            "VF5Spec.forged_vc_sound",
            c("VF5Spec.ForgedVcSound"),
            value(&env, "VF5.vc_sound_F1"),
        ),
        "vc_sound_F1's proof for every function valid",
    );
    refused(
        &mut k,
        theorem(
            "VF5Spec.forged_closed",
            c("VF5Spec.ForgedClosed"),
            value(&env, "VF5.compose_F1"),
        ),
        "compose_F1's proof for every program safe",
    );
    accepted(
        &mut k,
        theorem(
            "VF5Spec.control_vc_sound",
            type_of(&env, "VF5.vc_sound_F1"),
            value(&env, "VF5.vc_sound_F1"),
        ),
        "vc_sound_F1 under a fresh name",
    );

    // ── Control 2: each artifact's checks, perturbed three ways. ──
    let keys: BTreeSet<&str> = ROWS.iter().map(|(_, key)| *key).collect();
    for key in keys {
        let checks = format!("VF5Rows.checks_{key}");
        let ty = type_of(&env, &checks);
        let (eq, bool_ty, lhs, rhs) = eq_parts(&ty, &checks);
        let proof = value(&env, &checks);
        let t = Instant::now();
        accepted(
            &mut k,
            theorem(&format!("{checks}_control"), ty.clone(), proof.clone()),
            &format!("{checks} under a fresh name"),
        );
        eprintln!(
            "vf5_f1_reference: {checks} re-admitted (decode + vc + chk_LIA_cases by kernel \
             evaluation) in {:.0} ms",
            t.elapsed().as_secs_f64() * 1e3
        );
        // `checkBlob blob A certs`: argument 1 is the annotation.
        let no_annot = with_arg(&lhs, 1, c("VF5Spec.noAnnot"));
        refused(
            &mut k,
            theorem(
                &format!("{checks}_no_annot"),
                Expr::apps(eq.clone(), [bool_ty.clone(), no_annot, rhs.clone()]),
                proof.clone(),
            ),
            &format!("{checks} with no precondition"),
        );
        for refusal in ["refused_cert", "refused_zero_divisor"] {
            let name = format!("VF5Rows.{refusal}_{key}");
            let rty = type_of(&env, &name);
            let (req, rbool, rlhs, _) = eq_parts(&rty, &name);
            let flipped = Expr::apps(req, [rbool, rlhs, c("Bool.true")]);
            refused(
                &mut k,
                theorem(&format!("{name}_flipped"), flipped, proof.clone()),
                &format!("{name} with the honest certificates' proof"),
            );
        }
    }
    // Each row's proof for a function the artifact does not have.
    for (row, _) in ROWS {
        let rty = type_of(&env, row);
        let missing = with_arg(&rty, 2, Expr::nat_lit(99));
        refused(
            &mut k,
            theorem(&format!("{row}_fid99"), missing, value(&env, row)),
            &format!("{row} at function 99"),
        );
    }

    // Each row's proof at another function's symbol; the honest row under a fresh name.
    accepted(
        &mut k,
        theorem(
            "VF5Rows.row_collision_41_helper_control",
            type_of(&env, "VF5Rows.row_collision_41_helper"),
            value(&env, "VF5Rows.row_collision_41_helper"),
        ),
        "row_collision_41_helper under a fresh name",
    );
    for (row, other) in SYM_SWAPS {
        let rty = type_of(&env, row);
        let swapped = with_arg(&rty, 3, c(other));
        refused(
            &mut k,
            theorem(&format!("{row}_as_{other}"), swapped, value(&env, row)),
            &format!("{row} at {other}"),
        );
    }

    // ── Control 2b: D-2(b)'s rows at a function the artifact lacks, and B3. ──
    for row in D2B_ROWS {
        assert!(
            built_admits(&k, row),
            "{row} was not admitted through the entry"
        );
        let rty = type_of(&env, row);
        let missing = with_arg(&rty, 2, Expr::nat_lit(99));
        refused(
            &mut k,
            theorem(&format!("{row}_fid99"), missing, value(&env, row)),
            &format!("{row} at function 99"),
        );
    }
    // `@Eq.refl Bool true`: a proof the kernel accepts at `lhs = true` exactly when
    // `lhs` evaluates to `true`.
    let refl_true = Expr::apps(
        Expr::const_(n("Eq.refl"), vec![Level::succ(Level::zero())]),
        [c("Bool"), c("Bool.true")],
    );
    for name in B3_ACCEPTED {
        let t = Instant::now();
        accepted(
            &mut k,
            theorem(
                &format!("{name}_refl"),
                type_of(&env, name),
                refl_true.clone(),
            ),
            &format!("{name} by evaluation"),
        );
        eprintln!(
            "vf5_f1_reference: {name} re-admitted by evaluation in {:.0} ms",
            t.elapsed().as_secs_f64() * 1e3
        );
    }
    for name in B3_REFUSED {
        let ty = type_of(&env, name);
        let (eq, bool_ty, lhs, _) = eq_parts(&ty, name);
        refused(
            &mut k,
            theorem(
                &format!("{name}_flipped"),
                Expr::apps(eq, [bool_ty, lhs, c("Bool.true")]),
                refl_true.clone(),
            ),
            &format!("{name} flipped to true"),
        );
    }
    // The D-2(b) artifact's checks, with no precondition (none is needed) — and the
    // same check with one certificate dropped refused.
    accepted(
        &mut k,
        theorem(
            "VF5Rows.checks_fieldless_refl",
            type_of(&env, "VF5Rows.checks_fieldless"),
            refl_true.clone(),
        ),
        "checks_fieldless by evaluation",
    );

    // B3 over the whole artifact: the D-2(b) rows' premise, accepted by evaluation; the
    // two artifact mutants' obligations still check, and B3 over each is refused.
    for name in ["VF5Rows.b3all_fieldless", "VF5Rows.checks_artifact_swap"] {
        accepted(
            &mut k,
            theorem(
                &format!("{name}_refl"),
                type_of(&env, name),
                refl_true.clone(),
            ),
            &format!("{name} by evaluation"),
        );
    }
    for name in [
        "VF5Rows.b3all_refused_artifact_swap",
        "VF5Rows.b3all_refused_artifact_index_tags",
    ] {
        let ty = type_of(&env, name);
        let (eq, bool_ty, lhs, _) = eq_parts(&ty, name);
        refused(
            &mut k,
            theorem(
                &format!("{name}_flipped"),
                Expr::apps(eq, [bool_ty, lhs, c("Bool.true")]),
                refl_true.clone(),
            ),
            &format!("{name} flipped to true"),
        );
    }

    // ── Control 2b': aterm's rows. Each admitted, each refused at a function the
    // artifact lacks; the artifact's checks re-admitted by evaluation and the
    // perturbed certificates refused. ──
    for row in ATERM_ROWS {
        assert!(
            built_admits(&k, row),
            "{row} was not admitted through the entry"
        );
        let rty = type_of(&env, row);
        let missing = with_arg(&rty, 2, Expr::nat_lit(99));
        refused(
            &mut k,
            theorem(&format!("{row}_fid99"), missing, value(&env, row)),
            &format!("{row} at function 99"),
        );
    }
    {
        let t = Instant::now();
        accepted(
            &mut k,
            theorem(
                "VF5Rows.checks_aterm_refl",
                type_of(&env, "VF5Rows.checks_aterm"),
                refl_true.clone(),
            ),
            "checks_aterm by evaluation",
        );
        eprintln!(
            "vf5_f1_reference: checks_aterm re-admitted by evaluation in {:.0} ms",
            t.elapsed().as_secs_f64() * 1e3
        );
        let name = "VF5Rows.refused_cert_aterm";
        let ty = type_of(&env, name);
        let (eq, bool_ty, lhs, _) = eq_parts(&ty, name);
        refused(
            &mut k,
            theorem(
                &format!("{name}_flipped"),
                Expr::apps(eq, [bool_ty, lhs, c("Bool.true")]),
                refl_true.clone(),
            ),
            &format!("{name} flipped to true"),
        );
    }

    // ── Control 2c: the entry premise. An annotation on a root certifies the
    // reproducer's obligations, and no row's shape admits it. ──
    for (checks, row) in PROBES {
        accepted(
            &mut k,
            theorem(
                &format!("{checks}_refl"),
                type_of(&env, checks),
                refl_true.clone(),
            ),
            &format!("{checks} by evaluation"),
        );
        let ty = type_of(&env, row);
        let (eq, bool_ty, lhs, _) = eq_parts(&ty, row);
        refused(
            &mut k,
            theorem(
                &format!("{row}_flipped"),
                Expr::apps(eq, [bool_ty, lhs, c("Bool.true")]),
                refl_true.clone(),
            ),
            &format!("{row} flipped to true"),
        );
    }

    // ── Control 2d: VF7's rows (R206). Each artifact's checks by evaluation (timed),
    // its certificates with one multiplier changed refused, each row at a function the
    // artifact lacks and at another row's symbol refused. ──
    let spec_tables: [(&str, &[&str]); 2] =
        [("VF7Rows", &VF7_ROWS), ("VF5AtermRows", &ATERM_SPEC_ROWS)];
    for (module, row) in spec_tables
        .iter()
        .flat_map(|(m, rows)| rows.iter().map(move |r| (*m, *r)))
    {
        let key = row
            .trim_start_matches(&format!("{module}.row_"))
            .to_string();
        let checks = format!("{module}.checks_{key}");
        let t = Instant::now();
        accepted(
            &mut k,
            theorem(
                &format!("{checks}_refl"),
                type_of(&env, &checks),
                refl_true.clone(),
            ),
            &format!("{checks} by evaluation"),
        );
        eprintln!(
            "vf5_f1_reference: {checks} re-admitted (decode + vc + chk_LIA_cases by kernel \
             evaluation) in {:.0} ms",
            t.elapsed().as_secs_f64() * 1e3
        );
        let name = format!("{module}.refused_cert_{key}");
        let ty = type_of(&env, &name);
        let (eq, bool_ty, lhs, _) = eq_parts(&ty, &name);
        refused(
            &mut k,
            theorem(
                &format!("{name}_flipped"),
                Expr::apps(eq, [bool_ty, lhs, c("Bool.true")]),
                refl_true.clone(),
            ),
            &format!("{name} flipped to true"),
        );
    }
    for row in VF7_ROWS.iter().chain(ATERM_SPEC_ROWS.iter()) {
        let row = *row;
        assert!(
            built_admits(&k, row),
            "{row} was not admitted through the entry"
        );
        let rty = type_of(&env, row);
        let missing = with_arg(&rty, 2, Expr::nat_lit(99));
        refused(
            &mut k,
            theorem(&format!("{row}_fid99"), missing, value(&env, row)),
            &format!("{row} at function 99"),
        );
    }
    for (row, other) in [
        ("VF7Rows.row_exited_zero", "VF7Rows.sym_does_token_fit"),
        ("VF7Rows.row_h6_of_hash", "VF7Rows.sym_level_bit"),
        // Two harnesses of one name, `utf8_len_spec`, in two crates: the crate binds too.
        (
            "VF5AtermRows.row_json_utf8_len",
            "VF5AtermRows.sym_lex_utf8_len",
        ),
        (
            "VF5AtermRows.row_least_greater_odd",
            "VF5AtermRows.sym_least_greater_even",
        ),
    ] {
        let rty = type_of(&env, row);
        let swapped = with_arg(&rty, 3, c(other));
        refused(
            &mut k,
            theorem(&format!("{row}_as_{other}"), swapped, value(&env, row)),
            &format!("{row} at {other}"),
        );
    }

    // ── Control 2e: VF7's false-clause controls. Each `*_wrong_unsafe` is admitted; the
    // row's own harness at the same counterexample runs clean by evaluation, and that run
    // flipped to `true` is refused (the panic is the false clause's, not the body's). ──
    for (module, key) in VF7_WRONG
        .iter()
        .map(|(k, _)| ("VF7Rows", k.to_string()))
        .chain(ATERM_SPEC_ROWS.iter().map(|r| {
            (
                "VF5AtermRows",
                r.trim_start_matches("VF5AtermRows.row_").to_string(),
            )
        }))
    {
        let unsafe_ = format!("{module}.{key}_wrong_unsafe");
        assert!(
            built_admits(&k, &unsafe_),
            "{unsafe_} was not admitted through the entry"
        );
        let name = format!("{module}.{key}_spec_runs_at_cex");
        let ty = type_of(&env, &name);
        let (eq, bool_ty, lhs, _) = eq_parts(&ty, &name);
        refused(
            &mut k,
            theorem(
                &format!("{name}_flipped"),
                Expr::apps(eq, [bool_ty, lhs, c("Bool.true")]),
                refl_true.clone(),
            ),
            &format!("{name} flipped to true"),
        );
    }

    // ── Control 2f: the D-2(b) rows (R213). Per artifact: its checks by evaluation
    // (timed), its certificates perturbed refused, B3 by evaluation and B3 over a swapped
    // table refused. Per row: admitted within Ax0, refused at a function the artifact lacks
    // and at a sibling row's symbol, its false-clause control admitted, its counterexample
    // valid, and its own clean run there flipped to a panic refused. ──
    let rows = d2b_rows();
    assert_eq!(rows.len(), D2B_ROW_COUNT, "d2b_rows/rows.tsv");
    let stems: Vec<&str> = {
        let mut v: Vec<&str> = Vec::new();
        for (stem, _, _) in &rows {
            if !v.contains(&stem.as_str()) {
                v.push(stem);
            }
        }
        v
    };
    let mut d2b_ms = Vec::new();
    for stem in &stems {
        let checks = format!("VF5D2bRows.checks_{stem}");
        let t = Instant::now();
        accepted(
            &mut k,
            theorem(
                &format!("{checks}_refl"),
                type_of(&env, &checks),
                refl_true.clone(),
            ),
            &format!("{checks} by evaluation"),
        );
        let ms = t.elapsed().as_secs_f64() * 1e3;
        d2b_ms.push(ms);
        eprintln!(
            "vf5_f1_reference: {checks} re-admitted (decode + vc + chk_LIA_cases by kernel \
             evaluation) in {ms:.0} ms"
        );
        let b3 = format!("VF5D2bRows.b3all_{stem}");
        accepted(
            &mut k,
            theorem(&format!("{b3}_refl"), type_of(&env, &b3), refl_true.clone()),
            &format!("{b3} by evaluation"),
        );
        for refusal in ["refused_cert", "b3all_refused"] {
            let name = format!("VF5D2bRows.{refusal}_{stem}");
            if refusal == "b3all_refused" && env.get_const(&n(&name)).is_none() {
                // A one-variant first enum has no pair to swap.
                continue;
            }
            let ty = type_of(&env, &name);
            let (eq, bool_ty, lhs, _) = eq_parts(&ty, &name);
            refused(
                &mut k,
                theorem(
                    &format!("{name}_flipped"),
                    Expr::apps(eq, [bool_ty, lhs, c("Bool.true")]),
                    refl_true.clone(),
                ),
                &format!("{name} flipped to true"),
            );
        }
    }
    d2b_ms.sort_by(f64::total_cmp);
    eprintln!(
        "vf5_f1_reference: {} D-2(b) artifacts' checks by evaluation: median {:.0} ms, max {:.0} ms",
        d2b_ms.len(),
        d2b_ms[d2b_ms.len() / 2],
        d2b_ms[d2b_ms.len() - 1]
    );
    let ax0_all: BTreeSet<String> = AX0_ALL.iter().map(|s| (*s).to_string()).collect();
    for (i, (_, _, row)) in rows.iter().enumerate() {
        let name = format!("VF5D2bRows.row_{row}");
        assert!(
            built_admits(&k, &name),
            "{name} was not admitted through the entry"
        );
        assert_eq!(
            axioms_of(k.environment(), &n(&name)),
            ax0_all,
            "{name}: closure"
        );
        let rty = type_of(&env, &name);
        refused(
            &mut k,
            theorem(
                &format!("{name}_fid99"),
                with_arg(&rty, 2, Expr::nat_lit(99)),
                value(&env, &name),
            ),
            &format!("{name} at function 99"),
        );
        // A sibling row's symbol (the next row of the TSV, cyclically).
        let other = format!("VF5D2bRows.sym_{}", rows[(i + 1) % rows.len()].2);
        refused(
            &mut k,
            theorem(
                &format!("{name}_as_{other}"),
                with_arg(&rty, 3, c(&other)),
                value(&env, &name),
            ),
            &format!("{name} at {other}"),
        );
        let unsafe_ = format!("VF5D2bRows.{row}_wrong_unsafe");
        assert!(
            built_admits(&k, &unsafe_),
            "{unsafe_} was not admitted through the entry"
        );
        assert_eq!(
            axioms_of(k.environment(), &n(&unsafe_)),
            ax0_all,
            "{unsafe_}: closure"
        );
        let valid = format!("VF5D2bRows.{row}_cex_valid");
        assert!(built_admits(&k, &valid), "{valid} was not admitted");
        let clean = format!("VF5D2bRows.{row}_spec_runs_at_cex");
        let ty = type_of(&env, &clean);
        let (eq, bool_ty, lhs, _) = eq_parts(&ty, &clean);
        refused(
            &mut k,
            theorem(
                &format!("{clean}_flipped"),
                Expr::apps(eq, [bool_ty, lhs, c("Bool.true")]),
                refl_true.clone(),
            ),
            &format!("{clean} flipped to true"),
        );
    }
    let name = "VF5D2bRows.row_creation_flags_b3";
    assert!(
        built_admits(&k, name),
        "{name} was not admitted through the entry"
    );

    // ── Control 2g: the behind-PM-1 rows. Per row: its checks by evaluation (timed), its
    // certificates perturbed refused, the row admitted within Ax0, refused at a function the
    // artifact lacks and at the next row's symbol, its false-clause control admitted, its
    // counterexample valid, and its own clean run there flipped to a panic refused. ──
    let rows = pm1_rows();
    assert_eq!(rows.len(), PM1_ROW_COUNT, "pm1_rows/rows.tsv");
    let mut pm1_ms = Vec::new();
    for (i, (key, _)) in rows.iter().enumerate() {
        let checks = format!("VF5PM1Rows.checks_{key}");
        let t = Instant::now();
        accepted(
            &mut k,
            theorem(
                &format!("{checks}_refl"),
                type_of(&env, &checks),
                refl_true.clone(),
            ),
            &format!("{checks} by evaluation"),
        );
        let ms = t.elapsed().as_secs_f64() * 1e3;
        pm1_ms.push(ms);
        eprintln!(
            "vf5_f1_reference: {checks} re-admitted (decode + vc + chk_LIA_cases by kernel \
             evaluation) in {ms:.0} ms"
        );
        for flip in [
            format!("VF5PM1Rows.refused_cert_{key}"),
            format!("VF5PM1Rows.{key}_spec_runs_at_cex"),
        ] {
            let ty = type_of(&env, &flip);
            let (eq, bool_ty, lhs, _) = eq_parts(&ty, &flip);
            refused(
                &mut k,
                theorem(
                    &format!("{flip}_flipped"),
                    Expr::apps(eq, [bool_ty, lhs, c("Bool.true")]),
                    refl_true.clone(),
                ),
                &format!("{flip} flipped to true"),
            );
        }
        let name = format!("VF5PM1Rows.row_{key}");
        assert!(
            built_admits(&k, &name),
            "{name} was not admitted through the entry"
        );
        assert_eq!(
            axioms_of(k.environment(), &n(&name)),
            ax0_all,
            "{name}: closure"
        );
        let rty = type_of(&env, &name);
        refused(
            &mut k,
            theorem(
                &format!("{name}_fid99"),
                with_arg(&rty, 2, Expr::nat_lit(99)),
                value(&env, &name),
            ),
            &format!("{name} at function 99"),
        );
        let other = format!("VF5PM1Rows.sym_{}", rows[(i + 1) % rows.len()].0);
        refused(
            &mut k,
            theorem(
                &format!("{name}_as_{other}"),
                with_arg(&rty, 3, c(&other)),
                value(&env, &name),
            ),
            &format!("{name} at {other}"),
        );
        let unsafe_ = format!("VF5PM1Rows.{key}_wrong_unsafe");
        assert!(
            built_admits(&k, &unsafe_),
            "{unsafe_} was not admitted through the entry"
        );
        assert_eq!(
            axioms_of(k.environment(), &n(&unsafe_)),
            ax0_all,
            "{unsafe_}: closure"
        );
        let valid = format!("VF5PM1Rows.{key}_cex_valid");
        assert!(built_admits(&k, &valid), "{valid} was not admitted");
    }
    pm1_ms.sort_by(f64::total_cmp);
    eprintln!(
        "vf5_f1_reference: {} behind-PM-1 artifacts' checks by evaluation: median {:.0} ms, max {:.0} ms",
        pm1_ms.len(),
        pm1_ms[pm1_ms.len() / 2],
        pm1_ms[pm1_ms.len() - 1]
    );

    // ── Control 3: a mutant's refutation is no refutation of F1. ──
    for name in MUTANT_REFUTATIONS {
        let not_std = with_arg(
            &type_of(&env, name),
            0,
            Expr::app(c("VF5.CalcSound"), c("VF5.stdCalc")),
        );
        refused(
            &mut k,
            theorem(&format!("{name}_for_std"), not_std, value(&env, name)),
            &format!("{name}'s refutation offered for ¬ CalcSound stdCalc"),
        );
    }
    accepted(
        &mut k,
        theorem(
            "VF5Spec.control_std_sound",
            type_of(&env, "VF5.stdCalc_sound"),
            value(&env, "VF5.stdCalc_sound"),
        ),
        "stdCalc_sound under a fresh name",
    );
}

fn built_admits(k: &ReferenceKernel, name: &str) -> bool {
    k.environment().get_const(&n(name)).is_some()
}

/// `(exit code, stderr)` of the pinned `leanchecker --fresh <module>` over `dir`.
fn leanchecker(dir: &Path, module: &str) -> (Option<i32>, String) {
    assert_eq!(
        include_str!("../../../lean-toolchain").trim(),
        format!("leanprover/lean4:{PINNED}"),
        "this fixture is compiled by {PINNED}; the workspace pin moved"
    );
    let lean = clean_olean::pinned_lean_binary().expect("the pinned Lean toolchain");
    let bin = lean.parent().expect("bin/").to_path_buf();
    // `leanchecker` asks `lean --print-prefix`; the pinned `bin/` goes first on
    // PATH so a `lean` earlier on it is not the one asked.
    let path = std::env::var_os("PATH").unwrap_or_default();
    let mut dirs = vec![bin.clone()];
    dirs.extend(std::env::split_paths(&path));
    let out = Command::new(bin.join("leanchecker"))
        .arg("--fresh")
        .arg(module)
        .current_dir(dir)
        .env("LEAN_PATH", dir)
        .env("PATH", std::env::join_paths(dirs).expect("PATH"))
        .output()
        .expect("run leanchecker");
    (
        out.status.code(),
        String::from_utf8_lossy(&out.stderr).into_owned(),
    )
}

