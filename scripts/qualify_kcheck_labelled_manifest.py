"""Untrusted W3 manifest producer/control driver; never grants checker authority.

Only `structural` is lightweight. Run every other mode through build-slot and
scripts/heavy_gate.sh. `bootstrap` exports measurements and intentionally keeps
the unminted test red. `mint` adopts only a successful complete measurement,
then requires an ordinary passing replay. No expectation is generated by a
production consumer or by a normal test invocation.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
TEST = "crates/clean-olean/tests/kcheck_labelled_manifest.rs"
LEGACY = "crates/clean-olean/tests/kcheck_labelled.rs"
MANIFEST = "data/kcheck_labelled_canonical_manifest.json"
EXPORT = "CLEAN_KCHECK_LABELLED_MANIFEST_EXPORT"
THEORIES = ("cic_l", "cic_l_model", "kcheck_spec", "kcheck_labelled")
EXPECTED_COUNTS = (68, 162, 106, 90)
MODULE_COUNT = sum(EXPECTED_COUNTS)
LEGACY_PIN_COUNT = 3611
TARGET = "clean-olean::test::kcheck_labelled_manifest"
AGGREGATE = "CleanQualification.kcheck_labelled"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def order(path):
    return [s.strip() for s in path.read_text().splitlines()
            if s.strip() and not s.strip().startswith("#")]


def rust_strings(source, table):
    section = source.split("const " + table + ":", 1)[1].split("];", 1)[0]
    return re.findall(r'"([^"]+)"', section)


def extra_paths_table():
    # Read the local verifier module's source without importing it. Parsing the
    # literal preserves duplicate keys for the check below.
    spec = importlib.util.find_spec("verify_runner")
    if spec is None or spec.origin is None:
        raise RuntimeError("missing verifier module")
    source = Path(spec.origin).resolve()
    if source.parent != ROOT / "scripts":
        raise RuntimeError("verifier module is outside this checkout")
    tree = ast.parse(source.read_text())
    node = next(n.value for n in tree.body if isinstance(n, ast.AnnAssign)
                and isinstance(n.target, ast.Name) and n.target.id == "TARGET_EXTRA_PATHS")
    keys = [ast.literal_eval(k) for k in node.keys]
    if len(keys) != len(set(keys)):
        raise RuntimeError("duplicate TARGET_EXTRA_PATHS key")
    return ast.literal_eval(node)


def structural():
    current = (ROOT / TEST).read_text()
    legacy = (ROOT / LEGACY).read_text()
    definitions = rust_strings(current, "DEFINITIONS")
    if definitions != rust_strings(legacy, "CHECKER") or len(definitions) != 79:
        raise RuntimeError("legacy ordered 79-root contract differs")
    if len(json.loads((ROOT / "theories/kcheck_labelled/statement_pins.json").read_text())) != LEGACY_PIN_COUNT:
        raise RuntimeError(f"legacy {LEGACY_PIN_COUNT}-pin denominator differs")
    family = ROOT / "crates/clean-olean/tests/fixtures/lean/v4.30.0-rc2/kcheck_labelled/ORDER"
    if order(family) != ["theory " + t for t in THEORIES]:
        raise RuntimeError("fixture theories differ")
    counts = []
    all_modules = []
    for theory, count in zip(THEORIES, EXPECTED_COUNTS):
        directory = ROOT / "theories" / theory
        modules = [s.replace("/", ".") for s in order(directory / "ORDER")]
        roots_text = re.search(r"^roots\s*=\s*(\[[\s\S]*?\])", (directory / "lakefile.toml").read_text(), re.M)
        if roots_text is None or json.loads(roots_text.group(1)) != modules:
            raise RuntimeError("library roots and ORDER differ: " + theory)
        if len(modules) != count:
            raise RuntimeError("module denominator differs: " + theory)
        source_modules = {str(p.relative_to(directory).with_suffix("")).replace(os.sep, ".")
                          for p in directory.rglob("*.lean")
                          if not any(s.startswith(".") for s in p.relative_to(directory).parts)
                          and p.name != "lakefile.lean"}
        allowed = set(modules) | ({"KCheckLabelledMain"} if theory == "kcheck_labelled" else set())
        if source_modules != allowed:
            raise RuntimeError("unaccounted source modules: " + theory)
        if (directory / "lean-toolchain").read_text().strip() != (ROOT / "lean-toolchain").read_text().strip():
            raise RuntimeError("theory Lean pin differs: " + theory)
        counts.append(len(modules))
        all_modules.extend(modules)
    if len(all_modules) != MODULE_COUNT or len(set(all_modules)) != MODULE_COUNT:
        raise RuntimeError(f"{MODULE_COUNT}-module partition differs")
    table = extra_paths_table()
    required = {"lean-toolchain", *("theories/" + t for t in THEORIES), MANIFEST,
                "scripts/kcheck_labelled_manifest_roster.lean", LEGACY,
                "scripts/qualify_kcheck_labelled_manifest.py",
                "crates/clean-olean/src/meaning_digest.rs",
                "crates/clean-olean/tests/fixtures/lean/v4.30.0-rc2/kcheck_labelled"}
    if not required <= set(table.get(TARGET, ())):
        raise RuntimeError("missing verifier input registration")
    state = json.loads((ROOT / MANIFEST).read_text())
    if state.get("schema") != 1 or state.get("state") not in ("unminted", "measured"):
        raise RuntimeError("invalid manifest state")
    return {"scope": "structural source checks only", "module_counts": counts,
            "definition_roots": 79, "theorem_roots": 2, "legacy_pins": LEGACY_PIN_COUNT,
            "manifest_state": state["state"], "native_qualification_run": False}



def current_source_book():
    book = {}
    directories = [*("theories/" + name for name in THEORIES),
                   "crates/clean-kernel/src", "crates/clean-olean/src"]
    for directory in directories:
        for path in (ROOT / directory).rglob("*"):
            if any(part.startswith(".") for part in path.relative_to(ROOT / directory).parts):
                continue
            if path.is_symlink():
                raise RuntimeError("source book refuses symlink: " + str(path))
            if path.is_file():
                book[path.relative_to(ROOT).as_posix()] = sha(path.read_bytes())
    for name in ("lean-toolchain", "Cargo.toml", "Cargo.lock",
                 "crates/clean-olean/Cargo.toml", "crates/clean-kernel/Cargo.toml",
                 "crates/clean-olean/src/meaning_digest.rs", LEGACY, TEST,
                 "scripts/kcheck_labelled_manifest_roster.lean",
                 "scripts/qualify_kcheck_labelled_manifest.py",
                 "crates/clean-olean/tests/fixtures/lean/v4.30.0-rc2/kcheck_labelled/ORDER"):
        book[name] = sha((ROOT / name).read_bytes())
    return book


def validate_provenance(measured, provenance):
    modules = {row["module"] for row in measured["modules"]}
    if (provenance.get("schema") != 1 or len(modules) != MODULE_COUNT
            or len(measured["modules"]) != MODULE_COUNT or AGGREGATE in modules):
        raise RuntimeError("incomplete input provenance receipt")
    if provenance.get("source_sha256") != current_source_book():
        raise RuntimeError("candidate source book changed or has missing/extra inputs")
    hashes = provenance.get("artifact_sha256", {})
    paths = provenance.get("artifact_paths", {})
    artifact_modules = modules | {AGGREGATE}
    if set(hashes) != artifact_modules or set(paths) != artifact_modules:
        raise RuntimeError("candidate artifact book has missing/extra modules")
    bases = set()
    for module in artifact_modules:
        path = Path(paths[module])
        suffix = Path(module.replace(".", "/") + ".olean")
        if not path.is_absolute() or tuple(path.parts[-len(suffix.parts):]) != suffix.parts:
            raise RuntimeError("candidate artifact path does not identify its module: " + module)
        bases.add(path.parents[len(suffix.parts) - 1])
        if sha(path.read_bytes()) != hashes[module]:
            raise RuntimeError("candidate artifact changed before adoption: " + module)
    if len(bases) != 1:
        raise RuntimeError("candidate artifacts do not share their staged fixture root")
    aggregate_source = Path(provenance.get("aggregate_source_path", ""))
    if aggregate_source != Path(paths[AGGREGATE]).with_suffix(".lean"):
        raise RuntimeError("candidate aggregate source does not match its artifact path")
    source_bytes = aggregate_source.read_bytes()
    expected_source = "prelude\n" + "".join(
        "import " + stem.replace("/", ".") + "\n"
        for stem in order(ROOT / "theories/kcheck_labelled/ORDER"))
    if (source_bytes != expected_source.encode()
            or sha(source_bytes) != provenance.get("aggregate_source_sha256")):
        raise RuntimeError("candidate aggregate source differs from exact checker ORDER")
    for label, name in (("lean", "lean"), ("leanchecker", "leanchecker")):
        path = Path(provenance.get(label + "_binary_path", ""))
        if not path.is_absolute() or path.name != name:
            raise RuntimeError("candidate tool path does not identify " + label)
        if sha(path.read_bytes()) != provenance.get(label + "_binary_sha256"):
            raise RuntimeError("candidate tool changed before adoption: " + label)
    if provenance.get("lean_githash") != measured["lean_githash"]:
        raise RuntimeError("candidate Lean githash differs from receipt")


class Replay:
    def __init__(self, report):
        self.report = report
        self.steps = []
        self.report.mkdir(parents=True, exist_ok=False)
        self.save()

    def save(self):
        result = {"schema": 1, "scope": "additional adopted-checker identity only",
                  "authority_changed": False, "whole_w3_complete": False, "steps": self.steps}
        (self.report / "observations.json").write_text(json.dumps(result, indent=2) + "\n")

    def run(self, label, target="kcheck_labelled_manifest", refusal=None, export=None):
        env = dict(os.environ)
        if env.get(EXPORT):
            raise RuntimeError("driver refuses inherited bootstrap export")
        if export is not None:
            env[EXPORT] = str(export)
        command = ["targo", "--unverified", "test", "--profile", "authority", "--locked", "-p", "clean-olean",
                   "--test", target, "--", "--nocapture", "--test-threads=1"]
        log = self.report / (label + ".log")
        with log.open("wb") as output:
            proc = subprocess.run(command, cwd=ROOT, env=env, stdout=output, stderr=subprocess.STDOUT)
        data = log.read_bytes()
        accepted = (proc.returncode == 0) if refusal is None else (
            proc.returncode != 0 and any(marker.encode() in data for marker in refusal))
        self.steps.append({"label": label, "command": command, "exit": proc.returncode,
                           "expected_refusal": refusal, "matched_expectation": accepted,
                           "log": log.name, "log_sha256": sha(data)})
        self.save()
        if not accepted:
            raise RuntimeError("unexpected replay result; inspect " + str(log))

    def bootstrap(self):
        if json.loads((ROOT / MANIFEST).read_text()).get("state") != "unminted":
            raise RuntimeError("bootstrap requires the explicit unminted state")
        candidate = self.report / "measured-candidate.json"
        self.run("bootstrap-expected-unminted-refusal", refusal=[
            "W3_MANIFEST_UNMINTED: complete native measurement exported"], export=candidate)
        measured = json.loads(candidate.read_text())
        if (measured.get("state") != "measured" or measured.get("schema") != 1
                or len(measured.get("modules", ())) != MODULE_COUNT or len(measured.get("roots", ())) != 81
                or measured.get("legacy_pin_count") != LEGACY_PIN_COUNT):
            raise RuntimeError("incomplete native candidate")
        provenance_path = candidate.with_suffix(".provenance.json")
        provenance = json.loads(provenance_path.read_text())
        validate_provenance(measured, provenance)
        for label in ("artifact", "lean-tool"):
            forged = json.loads(json.dumps(provenance))
            if label == "artifact":
                module = next(iter(forged["artifact_sha256"]))
                digest = forged["artifact_sha256"][module]
                forged["artifact_sha256"][module] = ("0" if digest[0] != "0" else "1") + digest[1:]
                expected = "candidate artifact changed before adoption:"
            else:
                digest = forged["lean_binary_sha256"]
                forged["lean_binary_sha256"] = ("0" if digest[0] != "0" else "1") + digest[1:]
                expected = "candidate tool changed before adoption:"
            try:
                validate_provenance(measured, forged)
            except RuntimeError as error:
                if not str(error).startswith(expected):
                    raise
                self.steps.append({"label": "provenance-forged-" + label,
                                   "expected_refusal": expected, "actual_refusal": str(error),
                                   "matched_expectation": True, "input_files_modified": False})
                self.save()
            else:
                raise RuntimeError("forged provenance was accepted: " + label)
        validate_provenance(measured, provenance)
        return candidate

    def qualify(self):
        self.run("canonical-manifest")
        self.run(f"legacy-{LEGACY_PIN_COUNT}-contracts", "kcheck_labelled")
        self.run("canonical-algorithm-controls", "meaning_digest")

    def mutate(self, label, path, transform, refusal):
        source = ROOT / path
        original = source.read_bytes()
        changed = transform(original)
        if changed == original:
            raise RuntimeError("mutation made no change: " + label)
        try:
            source.write_bytes(changed)
            self.run(label, refusal=refusal)
        finally:
            source.write_bytes(original)
            if source.read_bytes() != original:
                raise RuntimeError("exact source restoration failed: " + path)

    def mutations(self):
        self.run("mutation-baseline")

        def replace(old, new):
            def transform(data):
                if data.count(old.encode()) != 1:
                    raise RuntimeError("mutation source anchor is not unique: " + old)
                return data.replace(old.encode(), new.encode())
            return transform

        self.mutate("forged-partial-copy-safety", "scripts/kcheck_labelled_manifest_roster.lean",
                    replace('| .partial => "partial"', '| .partial => "unsafe"'),
                    ["W3_ABSENT_COPY_SAFETY_MISMATCH"])
        self.mutate("checker-base-body", "theories/kcheck_labelled/KCheck/Declaration.lean",
                    replace("def base : Env := PSigmaSeed.seed", "def base : Env := id PSigmaSeed.seed"),
                    ["W3_MEANING_OR_AXIOM_MISMATCH"])
        self.mutate("c3-meaning-definition", "theories/kcheck_spec/KCheckSpec/Statements.lean",
                    replace("def C3Owes (K : Checker) : Prop :=\n  kcheck_sound.{u} K ∧",
                            "def C3Owes (K : Checker) : Prop :=\n  id <| kcheck_sound.{u} K ∧"),
                    ["W3_MEANING_OR_AXIOM_MISMATCH"])
        self.mutate("c3-actual-statement", "theories/kcheck_labelled/KCheck/CompleteSound.lean",
                    replace("theorem c3Owes : KCheckSpec.C3Owes.{u} checker :=",
                            "theorem c3Owes : id (KCheckSpec.C3Owes.{u} checker) :="),
                    ["W3_C3_TYPE_GUARD"])
        self.mutate("private-inventory-addition", "theories/kcheck_labelled/KCheck/CompleteSound.lean",
                    lambda data: data + b"\nnamespace KCheck.W3ManifestControl\nprivate theorem extra : True := True.intro\nend KCheck.W3ManifestControl\n",
                    ["W3_OWNERSHIP_MISMATCH"])
        self.mutate("outside-ax0", "theories/kcheck_labelled/KCheck/CompleteSound.lean",
                    lambda data: data + b"\nnamespace KCheck.W3ManifestControl\naxiom assumed : False\ntheorem borrowed : False := assumed\nend KCheck.W3ManifestControl\n",
                    ["W3_FENCED_NATIVE_REENTRY", "W3_FENCED_NATIVE_REFUSED"])

        def drop_auxiliary(data):
            expected = json.loads(data)
            for module in expected["modules"]:
                for i, row in enumerate(module["declarations"]):
                    if any(c["value"] == "_f" for c in row["name"]):
                        del module["declarations"][i]
                        return (json.dumps(expected, indent=2) + "\n").encode()
            raise RuntimeError("manifest has no actual _f auxiliary to omit")

        def forge_digest(data):
            expected = json.loads(data)
            digest = expected["roots"][0]["digest"]
            expected["roots"][0]["digest"] = ("0" if digest[0] != "0" else "1") + digest[1:]
            return (json.dumps(expected, indent=2) + "\n").encode()

        self.mutate("roster-auxiliary-omission", MANIFEST, drop_auxiliary, ["W3_OWNERSHIP_MISMATCH"])
        self.mutate("forged-root-digest", MANIFEST, forge_digest, ["W3_MEANING_OR_AXIOM_MISMATCH"])
        self.run("mutation-exact-restoration")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("structural", "bootstrap", "mint", "qualify", "mutations"))
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()
    checked = structural()
    if args.mode == "structural":
        print(json.dumps(checked, indent=2))
        return 0
    if args.report is None:
        parser.error("native modes require a new --report directory")
    replay = Replay(args.report.resolve())
    if args.mode in ("bootstrap", "mint"):
        candidate = replay.bootstrap()
        if args.mode == "mint":
            destination = ROOT / MANIFEST
            original = destination.read_bytes()
            try:
                destination.write_bytes(candidate.read_bytes())
                replay.run("mint-ordinary-confirmation")
            except BaseException:
                destination.write_bytes(original)
                raise
    elif args.mode == "qualify":
        replay.qualify()
    elif args.mode == "mutations":
        replay.mutations()
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (RuntimeError, OSError, ValueError, KeyError) as error:
        print("W3 manifest qualification refused: " + str(error), file=sys.stderr)
        sys.exit(1)
