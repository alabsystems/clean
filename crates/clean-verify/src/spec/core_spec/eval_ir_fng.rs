//! `reduce_float_neg::{closure#0}` as EvalIR — the only chained body whose
//! emitted instruction is a `unop`.
//!
//! Read `eval_ir_float_add.rs` first: this is its UNARY sibling. Same empty
//! aggregate lanes, same two-node shape — but TWO parameters rather than three,
//! which makes the arity as load-bearing as the width on this chain.
//!
//! **What this chain is worth, so it cannot inflate.** `unop` already has
//! battery rows from the W2a SYNTHETIC lane, whose header names it among "the
//! constructors no emitted body exercises". This adds NOTHING to that coverage.
//! What it does is make that sentence false for `fneg`: the operator is now
//! witnessed by an EMITTED body from the shipped kernel rather than only by a
//! module an author wrote. It is not A0-eligible — the body's `derived_mir`
//! verdict is `unsupported` — and it says nothing about `Level::is_zero`.
//!
//! The witnesses below run `ir_eval` on the REGISTERED module, not on
//! `ir_unop_eval` directly, so they are executions of this body rather than of
//! the primitive underneath it. The ZERO rows are the sharp ones: `fneg` flips
//! the sign BIT, so `fneg(+0.0)` is `-0.0`, where the obvious wrong
//! implementation `0.0 - x` yields `+0.0`. Those two agree on every value except
//! the zeros, so a chain witnessed only at `1.0` would not separate them.

use crate::spec::SpecError;
use crate::spec::Specification;

/// The minted script, generated by `ir_mint` from `generated/ir_fng.core.txt`,
/// which reader A projected from the artifact BINARY. Not transcribed.
const MINTED_IR_FNG: &str = include_str!("generated/ir_fng.defs.txt");

/// Registration rationales, one per minted line, in script order.
const MINTED_IR_FNG_DOCS: &[&str] = &[
    "ir_fng_b0: THE WHOLE BODY, MINTED FROM THE EMITTED ARTIFACT (generated/ir_fng.core.txt, projected by reader A from clean_kernel.trust-ir.bin). One `unop fneg` at f64 over %1, then a `ret` of ITS result. The OPERATOR is load-bearing: `fneg` flips the sign bit, and `0.0 - x` agrees with it on every value except the zeros, so the two are separated only at +0.0 and -0.0.",
    "ir_fng_func: the closure as EvalIR -- TWO parameters (%0 the closure environment pointer, %1 the operand), entry block 0, one block. This is the UNARY member of the float tranche, so the arity is as load-bearing as the width. %0 is bound and never read: the closure captures nothing.",
    "ir_fng_module: the module for env::native_reducers_float::reduce_float_neg::{closure#0}, MINTED from the emitted trust-ir rather than transcribed from it. Reader A projected it from the artifact BINARY and the A2 gate re-runs the mint and fails closed against this script. There is NO committed fixture for this body, so reader B has never read it and no two-reader agreement is claimed.",
];

/// The minted script's lines, in registration order — ONE source of truth for
/// the stage below and for anything running the machine on *the registered
/// module* rather than on a second transcription.
static MINTED_IR_FNG_LINES: std::sync::LazyLock<Vec<&'static str>> =
    std::sync::LazyLock::new(|| {
        MINTED_IR_FNG
            .lines()
            .map(str::trim)
            .filter(|l| !l.is_empty())
            .collect()
    });

/// The minted `reduce_float_neg::{closure#0}` module definitions, in
/// registration order.
#[must_use]
pub(crate) fn ir_fng_module_defs() -> &'static [&'static str] {
    &MINTED_IR_FNG_LINES
}

// ── kernel-EXECUTED witnesses, through the REGISTERED module ──────────
//   1.0  = 0x3FF0000000000000 = 4607182418800017408
//   -1.0 = 0xBFF0000000000000 = 13830554455654793216
//   +0.0 = 0
//   -0.0 = 0x8000000000000000 = 9223372036854775808
const SRC_W_ONE: &str = "def ir_fng_negates_one : @Eq IROutcome (ir_eval ir_d2 ir_fng_module ir_d0 (ir_vl2 IRScalar.undef_ (IRScalar.float_ 4607182418800017408)) ir_mem0 ir_d0) (IROutcome.ret (ir_vl1 (IRScalar.float_ 13830554455654793216))) := @Eq.refl IROutcome (IROutcome.ret (ir_vl1 (IRScalar.float_ 13830554455654793216)))";
const SRC_W_PZERO: &str = "def ir_fng_negates_positive_zero_to_negative_zero : @Eq IROutcome (ir_eval ir_d2 ir_fng_module ir_d0 (ir_vl2 IRScalar.undef_ (IRScalar.float_ 0)) ir_mem0 ir_d0) (IROutcome.ret (ir_vl1 (IRScalar.float_ 9223372036854775808))) := @Eq.refl IROutcome (IROutcome.ret (ir_vl1 (IRScalar.float_ 9223372036854775808)))";
const SRC_W_NZERO: &str = "def ir_fng_negates_negative_zero_to_positive_zero : @Eq IROutcome (ir_eval ir_d2 ir_fng_module ir_d0 (ir_vl2 IRScalar.undef_ (IRScalar.float_ 9223372036854775808)) ir_mem0 ir_d0) (IROutcome.ret (ir_vl1 (IRScalar.float_ 0))) := @Eq.refl IROutcome (IROutcome.ret (ir_vl1 (IRScalar.float_ 0)))";

impl Specification {
    /// Register the minted `unop fneg` module and its executed witnesses.
    ///
    /// # Errors
    /// Returns `SpecError` if a definition fails to elaborate, or if the minted
    /// script's length stops matching the rationale table.
    pub(super) fn add_eval_ir_fng(&mut self) -> Result<(), SpecError> {
        let minted = ir_fng_module_defs();
        if minted.len() != MINTED_IR_FNG_DOCS.len() {
            return Err(SpecError::EnvError(format!(
                "the minted ir_fng script has {} definitions but {} rationales are declared; \
                 regenerate the docs table with the script rather than reusing it",
                minted.len(),
                MINTED_IR_FNG_DOCS.len()
            )));
        }
        for (src, doc) in minted.iter().zip(MINTED_IR_FNG_DOCS) {
            self.add_recursive_def(src, doc)?;
        }
        self.add_recursive_def(
            SRC_W_ONE,
            "ir_fng_negates_one: the machine RUN on the registered module at fneg(1.0) = -1.0. Kernel-executed: the Eq.refl is discharged by REDUCING ir_eval over the minted module, not by asserting a constant.",
        )?;
        self.add_recursive_def(
            SRC_W_PZERO,
            "ir_fng_negates_positive_zero_to_negative_zero: fneg(+0.0) = -0.0. THE SHARP ROW: `0.0 - x` gives +0.0 here and agrees with fneg on every value except the zeros, so this is what separates a sign-bit flip from a subtraction.",
        )?;
        self.add_recursive_def(
            SRC_W_NZERO,
            "ir_fng_negates_negative_zero_to_positive_zero: fneg(-0.0) = +0.0, the converse of the row above. Together the two pin the sign bit in both directions; `fabs` would answer +0.0 on BOTH and pass only one of them.",
        )?;
        Ok(())
    }
}
